#ifndef ZAGOLOVKI_H
#define ZAGOLOVKI_H

#include <stddef.h>
#include "аст.h"

// ─── Внешние (C) функции, «увиденные» через заголовки ───────────────────────
//
// Транспилятор читает C-заголовки, подключённые директивами «#содержит», и
// извлекает прототипы функций, чтобы знать, какие имена валидны, — вместо того
// чтобы делегировать проверку целиком компилятору C. Извлекаются имя, число
// параметров и признак вариативности (эвристический разбор прототипов; точное
// сопоставление типов не выполняется — типы C отображаются на Konda лишь
// приблизительно).

// §127: C-тип из объявления заголовка (возврат/параметр функции, переменная),
// отображённый на Konda. Структуру (уровни «*», имя записи) даёт текст объявления
// из «cc -E», точный скалярный тип typedef'ов/перечислений — проба компилятором
// («_Generic»/«sizeof», «cc -S»).
enum {
    СИ_НЕИЗВЕСТЕН = 0,  // неотображаемое (long double, __int128, массив-typedef…)
    СИ_СКАЛЯР,          // целое/вещественное/логическое/символ (тип/беззнаковый)
    СИ_НИЧЕГО,          // void (с указателями — void*)
    СИ_ЗАПИСЬ,          // struct/union (запись/ид_записи/тег)
    СИ_ФУНКЦИЯ          // указатель на функцию (типы не сверяем)
};
typedef struct {
    int класс;           // СИ_*: класс БАЗЫ (то, на что указывают «*»)
    int тип;             // ТипТокена скаляра (класс СИ_СКАЛЯР)
    int беззнаковый;
    int указатели;       // уровней «*» над базой
    int тег;             // запись: 1 — struct, 2 — union
    char запись[128];    // имя записи для программы: typedef-имя, иначе тег
    char ид_записи[128]; // идентичность записи в C: тег (анонимная — typedef-имя)
} СиТип;

typedef struct {
    char имя[128];
    int число_параметров;   // -1 если неизвестно (пустые «()», K&R)
    int переменное_число;   // 1 — вариативная функция («...»)
    // Тип ВОЗВРАТА, отображённый C→Konda (чтобы «целое32 п = fork()» типизировался
    // без ручного «внешняя»). Параметры НЕ отображаем: их типы Konda для C-функций
    // и так не сверяет (пропускает в cc). возврат_известен=0 → тип возврата
    // отобразить не удалось (функц.указатель/структура/незнакомый typedef) →
    // прежнее поведение (тип вызова «неизвестен», нужен явный каст/внешняя).
    int возврат_известен;
    int возврат_тип;         // ТипТокена (ТОКЕН_ЦЕЛОЕ32/…/ТОКЕН_НИЧЕГО/ТОКЕН_ТИП_СИМВОЛ)
    int возврат_указатели;   // число уровней «*»
    int возврат_беззнаковый; // «unsigned»
    // §127 (только от компилятора, иначе типы_известны=0): полные C-типы возврата
    // и параметров + атрибут nonnull («__attribute__((nonnull(…)))»).
    int типы_известны;
    СиТип возврат_си;
    СиТип *параметры;        // число_параметров элементов (владеет таблица)
    unsigned long long ненулевые;  // бит k-1 — параметр k «nonnull»
    int все_ненулевые;       // «nonnull» без списка — все указатели
    int возврат_ненулевой;   // §128: «returns_nonnull» — возврат-указатель не NULL
} ВнешняяФункция;

// §127: объект C из заголовка — константа перечисления или внешняя переменная.
enum { ВНЕШНИЙ_КОНСТАНТА = 1, ВНЕШНИЙ_ПЕРЕМЕННАЯ = 2 };
typedef struct {
    char имя[128];
    int вид;                 // ВНЕШНИЙ_КОНСТАНТА / ВНЕШНИЙ_ПЕРЕМЕННАЯ
    СиТип тип;
    long long значение;      // константа: значение (беззнаковые — бит-паттерн)
    int значение_известно;
    int только_чтение;       // переменная const-квалифицирована
} ВнешнийОбъект;

// Константа из C-заголовка (§115, §117): объектный макрос «#define ИМЯ …» —
// целочисленный, вещественный или строковый. Позволяет использовать SIGKILL/
// RB_*/WNOHANG/UINT64_MAX/M_PI/_PATH_BSHELL и т.п. БЕЗ ручного переобъявления
// «конст» в .конда. В кодоген попадает ИМЯ (cpp раскроет), поэтому значение
// нужно лишь для ТИПА (и на будущее — для конст-вычислений).
//
// Источник (§117): при разрешённом компиляторе (CLI) — САМ компилятор:
// «cc -dM -E» даёт полный список макросов, «cc -E» раскрывает каждый (макросы-
// через-макросы, функциональные макросы вроде _IOR), а вычислитель C-константных
// выражений применяет настоящие правила типов C (суффиксы, касты, sizeof, все
// операторы). Без компилятора (IDE) — эвристический скан «#define» из текста
// заголовков тем же вычислителем (без раскрытия макросов).
typedef struct {
    char имя[128];
    long long значение;      // целое: значение (для беззнаковых — бит-паттерн)
    double вещественное;     // вещественное: значение
    int тип;                 // ТипТокена (ЦЕЛОЕ8…64/БАЙТ/ВЕЩЕСТВЕННОЕ*/ТИП_СИМВОЛ/ЛОГИЧЕСКИЙ)
    int указатели;           // строковая константа → 1 (символ*), иначе 0
    int беззнаковый;
} ВнешняяКонстанта;

typedef struct ТаблицаВнешних ТаблицаВнешних;

ТаблицаВнешних *внешние_создать(void);
void            внешние_освободить(ТаблицаВнешних *);

// §117: разрешить опрос компилятора за макросами (CLI). компилятор — имя/путь
// C-компилятора (обычно «cc», при кросс-сборке «<триплет>-gcc»). Не вызвано
// (IDE, libkonda_ide) → процессы не порождаются, работает эвристический скан.
void внешние_разрешить_компилятор(ТаблицаВнешних *т, const char *компилятор);

// Сканирует заголовки из «#содержит»-директив программы (узлы препроцессора в
// корне AST), разрешая пути и следуя вложенным «#include». база_путей —
// каталог исходного .конда для разрешения «локальных.h» (может быть NULL:
// тогда используются только системные каталоги).
void собрать_внешние_функции(const Узел *корень, const char *база_путей,
                             ТаблицаВнешних *куда);

// Поиск внешней функции по имени (nullptr, если не найдена).
const ВнешняяФункция *найти_внешнюю(const ТаблицаВнешних *т,
                                    const char *имя, size_t длина);

// Поиск константы из заголовков по имени (nullptr, если не найдена). При
// разрешённом компиляторе первый промах ЛЕНИВО опрашивает его (§117): программа
// без неизвестных идентификаторов не платит ни одного лишнего запуска cc.
const ВнешняяКонстанта *найти_внешнюю_константу(const ТаблицаВнешних *т,
                                                const char *имя, size_t длина);

// §127: константа перечисления (CAIRO_OPERATOR_SOURCE, SOCK_STREAM) или внешняя
// переменная (stderr, optind) из заголовков. Спрашивает компилятор (лениво,
// однократно): «cc -E» — объявления, «cc -S» пробы — точные типы/значения.
// nullptr — не найдено (или компилятор недоступен: IDE).
const ВнешнийОбъект *найти_внешний_объект(const ТаблицаВнешних *т,
                                         const char *имя, size_t длина);

// §127: знает ли C тип-запись (struct/union) с таким именем — typedef-имя записи
// («FILE», «cairo_t») или тег без typedef («wl_display»). *тег: 0 — есть typedef
// (печатать имя как есть), 1/2 — только тег struct/union (кодоген объявит
// «typedef struct X X;»). *имя_занято — имя занято обычным C-идентификатором
// (функция «stat» при «struct stat») → такой typedef невозможен.
int внешняя_запись(const ТаблицаВнешних *т, const char *имя, size_t длина,
                   int *тег, int *имя_занято);

// §127: идентичность записи в C по имени типа (typedef → тег; тег → сам).
// Сравнение «FILE» и «struct _IO_FILE» как одного типа. 1 — найдено (ид в ид[cap]).
int внешний_ид_записи(const ТаблицаВнешних *т, const char *имя, size_t длина,
                      char *ид, size_t cap);

// §127: запомнить «#содержит»/«использовать»-директиву (текст токена
// препроцессора) — для разбора заголовков ДО построения AST (пред-проход имён
// типов парсера). Дубли игнорируются.
void внешние_учесть_директиву(ТаблицаВнешних *т, const char *текст, size_t длина,
                              const char *база_путей);

// §127: дополнить AST до семантики: для типов-записей C, которые программа
// использует (по имени типа в объявлениях, через тип возврата/параметра
// вызванной C-функции, тип внешней переменной), но не объявила, — синтетический
// «внешний тип» (как если бы программист написал его сам); у явных и синтетических
// «внешних типов»-тегов выставляется тег_си (кодоген объявит typedef). Имена
// синтетических узлов живут в таблице — освобождать её ПОСЛЕ кодогена.
void внешние_дополнить_программу(ТаблицаВнешних *т, Узел *корень);

size_t                внешние_число(const ТаблицаВнешних *т);
const ВнешняяФункция *внешние_получить(const ТаблицаВнешних *т, size_t i);

#endif /* ZAGOLOVKI_H */
