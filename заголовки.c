typedef struct ИндексСи ИндексСи;   // §127, ниже

struct ТаблицаВнешних {
    // Записи по указателям: адрес функции стабилен, пока жива таблица (семантика
    // держит «внеш» через типизацию вложенных аргументов, которая может добавить
    // новые записи — рост массива не должен его инвалидировать).
    ВнешняяФункция **функции;
    size_t число;
    size_t емкость;
    ВнешняяКонстанта *константы;   // §115: эвристический скан «#define» (фолбэк/IDE)
    size_t число_констант;
    size_t емкость_констант;
    // §117: константы ОТ КОМПИЛЯТОРА (cc -dM -E + cc -E). Заполняются лениво —
    // при первом промахе поиска. Если опрос удался, они авторитетны (эвристика
    // не используется: иначе «#undef»-нутый в заголовках макрос всплыл бы).
    ВнешняяКонстанта *константы_компилятора;
    size_t число_констант_компилятора;
    size_t емкость_констант_компилятора;
    char *компилятор;              // nullptr → компилятор не звать (IDE)
    char *база_путей;              // каталог исходника → «-I» для «локальных.h»
    char **включения;              // строки «#include <…>»/«#include "…"» программы
    size_t число_включений;
    int опрос_выполнен;
    int опрос_успешен;
    // Уже просканированные пути заголовков — чтобы не сканировать дважды и не
    // зациклиться на взаимных #include.
    char (*пути)[1024];
    size_t число_путей;
    size_t емкость_путей;
    // Эвристический скан прототипов (без компилятора — IDE; с компилятором —
    // лениво, только если индекс §127 не дал имени: функциональные макросы,
    // сбой cc). Числа файлов не ограничиваем: пути дедуплицируются, цикл
    // включений обрывает предел глубины.
    int эвристика_выполнена;
    ИндексСи *индекс;   // §127: объявления C от компилятора
    // §127: годность включений для опросов компилятора. Если «cc -E» по всем
    // включениям падает (заголовок не найден — «config.h» без -I, cairo.h без
    // pkg-config), каждое пробуется вместе с уже годными предыдущими; негодные
    // выпадают из пробных файлов (иначе один отсутствующий заголовок обнулял
    // и индекс, и макросы §117). Вывод удачного полного прогона — в кэш индекса.
    unsigned char *годные;
    size_t проверено_включений;
    int включения_проверены;
    char *пп_полный;
    size_t длина_пп_полного;
};

#define МАКС_ГЛУБИНА_ВКЛЮЧЕНИЙ 24

static void освободить_индекс(ИндексСи *и);
static size_t индекс_размер(void);

ТаблицаВнешних *внешние_создать(void)
{
    ТаблицаВнешних *т = calloc(1, sizeof(ТаблицаВнешних));
    if (т) т->индекс = calloc(1, индекс_размер());
    return т;
}

void внешние_освободить(ТаблицаВнешних *т)
{
    if (!т) return;
    for (size_t i = 0; i < т->число; ++i) {
        free(т->функции[i]->параметры);
        free(т->функции[i]);
    }
    free(т->функции);
    освободить_индекс(т->индекс);
    free(т->константы);
    free(т->константы_компилятора);
    free(т->компилятор);
    free(т->база_путей);
    for (size_t i = 0; i < т->число_включений; ++i) free(т->включения[i]);
    free(т->включения);
    free(т->пути);
    free(т->годные);
    free(т->пп_полный);
    free(т);
}

static void обеспечить_эвристику(ТаблицаВнешних *т);

size_t внешние_число(const ТаблицаВнешних *т)
{
    if (!т) return 0;
    обеспечить_эвристику((ТаблицаВнешних *)т);
    return т->число;
}

const ВнешняяФункция *внешние_получить(const ТаблицаВнешних *т, size_t i)
{
    if (!т || i >= т->число) return nullptr;
    return т->функции[i];
}

// Поиск в уже собранных записях: из_индекса = 1 — только от компилятора (§127),
// 0 — только эвристические, -1 — любые.
static ВнешняяФункция *искать_функцию(const ТаблицаВнешних *т, const char *имя,
                                      size_t длина, int из_индекса)
{
    for (size_t i = 0; i < т->число; ++i) {
        ВнешняяФункция *ф = т->функции[i];
        if (из_индекса >= 0 && ф->типы_известны != из_индекса) continue;
        if (strlen(ф->имя) == длина && memcmp(ф->имя, имя, длина) == 0) return ф;
    }
    return nullptr;
}

static ВнешняяФункция *новая_функция(ТаблицаВнешних *т)
{
    if (т->число == т->емкость) {
        size_t нов = т->емкость ? т->емкость * 2 : 64;
        ВнешняяФункция **p = realloc(т->функции, нов * sizeof(*p));
        if (!p) return nullptr;
        т->функции = p;
        т->емкость = нов;
    }
    ВнешняяФункция *ф = calloc(1, sizeof(*ф));
    if (!ф) return nullptr;
    т->функции[т->число++] = ф;
    return ф;
}

static const ВнешняяФункция *функция_из_индекса(ТаблицаВнешних *т, ИндексСи *и,
                                               const char *имя, size_t длина);
static ИндексСи *индекс_си(ТаблицаВнешних *т);
static int индекс_успешен(const ИндексСи *и);

const ВнешняяФункция *найти_внешнюю(const ТаблицаВнешних *тк,
                                    const char *имя, size_t длина)
{
    if (!тк) return nullptr;
    ТаблицаВнешних *т = (ТаблицаВнешних *)тк;   // ленивый кэш (см. константы)
    // §127: от компилятора — с типами параметров и nonnull.
    if (т->компилятор) {
        const ВнешняяФункция *ф = искать_функцию(т, имя, длина, 1);
        if (ф) return ф;
        ИндексСи *и = индекс_си(т);
        if (индекс_успешен(и)) {
            ф = функция_из_индекса(т, и, имя, длина);
            if (ф) return ф;
        }
    }
    // Эвристика: без компилятора; с компилятором — фолбэк (функциональный
    // макрос, сбой cc).
    обеспечить_эвристику(т);
    return искать_функцию(т, имя, длина, 0);
}

static void добавить_функцию(ТаблицаВнешних *т, const char *имя, size_t длина,
                             int число_параметров, int переменное,
                             int возврат_известен, int возврат_тип,
                             int возврат_указатели, int возврат_беззнаковый)
{
    if (длина == 0 || длина >= sizeof(((ВнешняяФункция *)0)->имя)) return;
    if (искать_функцию(т, имя, длина, 0)) return;  // дедуп
    ВнешняяФункция *ф = новая_функция(т);
    if (!ф) return;
    memcpy(ф->имя, имя, длина);
    ф->имя[длина] = '\0';
    ф->число_параметров = число_параметров;
    ф->переменное_число = переменное;
    ф->возврат_известен = возврат_известен;
    ф->возврат_тип = возврат_тип;
    ф->возврат_указатели = возврат_указатели;
    ф->возврат_беззнаковый = возврат_беззнаковый;
}

static void опросить_компилятор(ТаблицаВнешних *т);   // §117, ниже

static const ВнешняяКонстанта *искать_в(const ВнешняяКонстанта *м, size_t n,
                                        const char *имя, size_t длина)
{
    for (size_t i = 0; i < n; ++i)
        if (strlen(м[i].имя) == длина && memcmp(м[i].имя, имя, длина) == 0)
            return &м[i];
    return nullptr;
}

const ВнешняяКонстанта *найти_внешнюю_константу(const ТаблицаВнешних *т,
                                                const char *имя, size_t длина)
{
    if (!т) return nullptr;
    if (т->компилятор) {
        // Ленивый опрос: таблица создана внешние_создать() (не const-объект),
        // константность API — лишь для читателей-семантики; снимать её здесь
        // корректно (кэш на объекте).
        if (!т->опрос_выполнен) опросить_компилятор((ТаблицаВнешних *)т);
        if (т->опрос_успешен)
            return искать_в(т->константы_компилятора, т->число_констант_компилятора,
                            имя, длина);
    }
    return искать_в(т->константы, т->число_констант, имя, длина);
}

// Добавить константу в массив (м, число, ёмкость). дедуп=1 — пропустить, если имя
// уже есть (первое определение побеждает; эвристический скан).
static void добавить_в(ВнешняяКонстанта **м, size_t *число, size_t *емкость,
                       const char *имя, size_t длина, const ВнешняяКонстанта *значение,
                       int дедуп)
{
    if (длина == 0 || длина >= sizeof((*м)[0].имя)) return;
    if (дедуп && искать_в(*м, *число, имя, длина)) return;
    if (*число == *емкость) {
        size_t нов = *емкость ? *емкость * 2 : 128;
        ВнешняяКонстанта *p = realloc(*м, нов * sizeof(*p));
        if (!p) return;
        *м = p;
        *емкость = нов;
    }
    ВнешняяКонстанта *к = &(*м)[(*число)++];
    *к = *значение;
    memcpy(к->имя, имя, длина);
    к->имя[длина] = '\0';
}

// Путь уже сканировали? Если нет — запоминаем и возвращаем 0 (нужно сканировать).
static int путь_виден(ТаблицаВнешних *т, const char *путь)
{
    for (size_t i = 0; i < т->число_путей; ++i)
        if (strcmp(т->пути[i], путь) == 0) return 1;
    if (т->число_путей == т->емкость_путей) {
        size_t нов = т->емкость_путей ? т->емкость_путей * 2 : 32;
        void *p = realloc(т->пути, нов * sizeof(т->пути[0]));
        if (!p) return 1;  // нет памяти — считаем «видели», чтобы не сканировать
        т->пути = p;
        т->емкость_путей = нов;
    }
    snprintf(т->пути[т->число_путей], sizeof(т->пути[0]), "%s", путь);
    т->число_путей++;
    return 0;
}

