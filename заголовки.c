// ─── Токенизация вывода «cc -E» ───────────────────────────────────────────────

static int си_имя_старт(unsigned char c) { return c == '_' || c == '$' || isalpha(c) || c >= 0x80; }
static int си_имя_прод(unsigned char c) { return c == '_' || c == '$' || isalnum(c) || c >= 0x80; }

// Одна UCN-последовательность «\uXXXX»/«\UXXXXXXXX» → UTF-8 в буф[4]. Возврат —
// длина UTF-8 (0 — не UCN); *занято — длина последовательности в исходнике.
static size_t декодировать_ucn(const char *с, size_t n, char буф[4], size_t *занято)
{
    if (n < 2 || с[0] != '\\' || (с[1] != 'u' && с[1] != 'U')) return 0;
    size_t цифр = с[1] == 'u' ? 4 : 8;
    if (n < 2 + цифр) return 0;
    unsigned long кп = 0;
    for (size_t d = 0; d < цифр; ++d) {
        unsigned char h = (unsigned char)с[2 + d];
        if (!isxdigit(h)) return 0;
        кп = кп * 16 + (unsigned long)(isdigit(h) ? h - '0' : tolower(h) - 'a' + 10);
    }
    if (кп > 0x10FFFF || (кп >= 0xD800 && кп <= 0xDFFF)) return 0;
    *занято = 2 + цифр;
    if (кп < 0x80) { буф[0] = (char)кп; return 1; }
    if (кп < 0x800) {
        буф[0] = (char)(0xC0 | (кп >> 6)); буф[1] = (char)(0x80 | (кп & 0x3F));
        return 2;
    }
    if (кп < 0x10000) {
        буф[0] = (char)(0xE0 | (кп >> 12)); буф[1] = (char)(0x80 | ((кп >> 6) & 0x3F));
        буф[2] = (char)(0x80 | (кп & 0x3F));
        return 3;
    }
    буф[0] = (char)(0xF0 | (кп >> 18)); буф[1] = (char)(0x80 | ((кп >> 12) & 0x3F));
    буф[2] = (char)(0x80 | ((кп >> 6) & 0x3F)); буф[3] = (char)(0x80 | (кп & 0x3F));
    return 4;
}

// gcc печатает расширенные идентификаторы как UCN («\U00000446»): раскрываем их
// в UTF-8 НА МЕСТЕ (UTF-8 не длиннее UCN), вне строковых/символьных литералов.
static size_t раскрыть_ucn(char *т, size_t n)
{
    size_t r = 0, w = 0;
    while (r < n) {
        char c = т[r];
        if (c == '"' || c == '\'') {             // литерал — как есть
            т[w++] = т[r++];
            while (r < n && т[r] != c && т[r] != '\n') {
                if (т[r] == '\\' && r + 1 < n) т[w++] = т[r++];
                т[w++] = т[r++];
            }
            if (r < n) т[w++] = т[r++];
            continue;
        }
        char буф[4]; size_t занято = 0;
        size_t дл = c == '\\' ? декодировать_ucn(т + r, n - r, буф, &занято) : 0;
        if (дл) {
            memcpy(т + w, буф, дл);
            w += дл;
            r += занято;
            continue;
        }
        т[w++] = т[r++];
    }
    т[w] = '\0';
    return w;
}

static void токенизировать_си(ИндексСи *и, const char *т, size_t n)
{
    size_t i = 0;
    while (i < n) {
        unsigned char c = (unsigned char)т[i];
        if (c == '\n' || c == ' ' || c == '\t' || c == '\r' || c == '\f' || c == '\v') { i++; continue; }
        if (c == '#' && (i == 0 || т[i - 1] == '\n')) {      // #pragma и пр. — строка целиком
            while (i < n && т[i] != '\n') i++;
            continue;
        }
        size_t н = i;
        unsigned char вид;
        if (си_имя_старт(c)) {
            while (i < n && си_имя_прод((unsigned char)т[i])) i++;
            вид = СТ_ИМЯ;
            // Префиксы строк L"…"/u8"…" — строка.
            if (i < n && (т[i] == '"' || т[i] == '\'') && i - н <= 2) { c = (unsigned char)т[i]; н = i; goto литерал; }
        } else if (isdigit(c) || (c == '.' && i + 1 < n && isdigit((unsigned char)т[i + 1]))) {
            while (i < n && (isalnum((unsigned char)т[i]) || т[i] == '.' || т[i] == '_' || т[i] == '\''
                   || ((т[i] == '+' || т[i] == '-') && (т[i - 1] == 'e' || т[i - 1] == 'E'
                                                       || т[i - 1] == 'p' || т[i - 1] == 'P')))) i++;
            вид = СТ_ЧИСЛО;
        } else if (c == '"' || c == '\'') {
        литерал:
            i++;
            while (i < n && т[i] != (char)c && т[i] != '\n') { if (т[i] == '\\') i++; i++; }
            if (i < n) i++;
            вид = СТ_СТРОКА;
        } else if (c == '.' && i + 2 < n && т[i + 1] == '.' && т[i + 2] == '.') {
            i += 3; вид = СТ_ЗНАК;
        } else {
            i++; вид = СТ_ЗНАК;
        }
        ОБЕСПЕЧИТЬ_ЁМКОСТЬ(и->токены, и->ёмкость_токенов, и->число_токенов + 1);
        и->токены[и->число_токенов++] = (СиТокен){ т + н, (unsigned)(i - н), вид };
    }
}

