static int ст_равно(const СиТокен *т, const char *с)
{
    size_t n = strlen(с);
    return т->длина == n && memcmp(т->начало, с, n) == 0;
}

static int ст_знак(const СиТокен *т, char с)
{
    return т->вид == СТ_ЗНАК && т->длина == 1 && т->начало[0] == с;
}

