// Известные C-typedef'ы → (тип Konda, беззнаковый). Разрешаем частые POSIX/stdint
// имена, чтобы «pid_t»/«size_t»/«ssize_t» и т.п. давали корректный тип возврата
// без раскрытия typedef из заголовка. Незнакомый typedef → тип возврата не
// отображаем (прежнее поведение: тип вызова «неизвестен»).
