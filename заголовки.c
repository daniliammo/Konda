static int это_имя_старт(int c) { return c == '_' || isalpha((unsigned char)c); }
static int это_имя_прод(int c) { return c == '_' || isalnum((unsigned char)c); }

// Ключевые слова C, которые могут стоять перед «(», но функциями не являются.
static int это_ключевое(const char *с, size_t n)
{
    static const char *кс[] = {
        "if", "while", "for", "switch", "return", "sizeof", "do",
        "_Static_assert", "static_assert", "defined", "typeof", "__typeof",
        "__typeof__", "__attribute__", "__attribute", "__asm", "__asm__",
        "asm", "_Alignof", "alignof", "_Generic", "__extension__",
        "__builtin_va_arg", "va_arg", nullptr
    };
    for (int i = 0; кс[i]; ++i)
        if (strlen(кс[i]) == n && memcmp(кс[i], с, n) == 0) return 1;
    return 0;
}

// ─── §115: отображение C-типа возврата на Konda + разбор целых констант ───────

// Известные C-typedef'ы → (тип Konda, беззнаковый). Разрешаем частые POSIX/stdint
// имена, чтобы «pid_t»/«size_t»/«ssize_t» и т.п. давали корректный тип возврата
// без раскрытия typedef из заголовка. Незнакомый typedef → тип возврата не
// отображаем (прежнее поведение: тип вызова «неизвестен»).
static int typedef_в_konda(const char *с, size_t n, int *тип, int *беззнак)
{
    struct { const char *имя; int тип; int беззнак; } таб[] = {
        { "size_t", ТОКЕН_ЦЕЛОЕ64, 1 }, { "ssize_t", ТОКЕН_ЦЕЛОЕ64, 0 },
        { "ptrdiff_t", ТОКЕН_ЦЕЛОЕ64, 0 }, { "intptr_t", ТОКЕН_ЦЕЛОЕ64, 0 },
        { "uintptr_t", ТОКЕН_ЦЕЛОЕ64, 1 },
        { "int8_t", ТОКЕН_ЦЕЛОЕ8, 0 }, { "int16_t", ТОКЕН_ЦЕЛОЕ16, 0 },
        { "int32_t", ТОКЕН_ЦЕЛОЕ32, 0 }, { "int64_t", ТОКЕН_ЦЕЛОЕ64, 0 },
        { "uint8_t", ТОКЕН_БАЙТ, 1 }, { "uint16_t", ТОКЕН_ЦЕЛОЕ16, 1 },
        { "uint32_t", ТОКЕН_ЦЕЛОЕ32, 1 }, { "uint64_t", ТОКЕН_ЦЕЛОЕ64, 1 },
        { "pid_t", ТОКЕН_ЦЕЛОЕ32, 0 }, { "off_t", ТОКЕН_ЦЕЛОЕ64, 0 },
        { "uid_t", ТОКЕН_ЦЕЛОЕ32, 1 }, { "gid_t", ТОКЕН_ЦЕЛОЕ32, 1 },
        { "mode_t", ТОКЕН_ЦЕЛОЕ32, 1 }, { "socklen_t", ТОКЕН_ЦЕЛОЕ32, 1 },
        { "time_t", ТОКЕН_ЦЕЛОЕ64, 0 }, { "clock_t", ТОКЕН_ЦЕЛОЕ64, 0 },
        { nullptr, 0, 0 }
    };
    for (int i = 0; таб[i].имя; ++i)
        if (strlen(таб[i].имя) == n && memcmp(таб[i].имя, с, n) == 0) {
            *тип = таб[i].тип; *беззнак = таб[i].беззнак; return 1;
        }
    return 0;
}

// Отображает C-тип ВОЗВРАТА (спан текста до имени функции) на Konda. Считает
// «*» (уровни указателя), пропускает квалификаторы/классы хранения и
// __attribute__((…)), распознаёт базовый тип или известный typedef. Возвращает
// 1 при успехе. void с указателем (void*) и незнакомый база/struct → 0 (не
// отображаем — вызов останется «неизвестного типа», как раньше).
static int отобразить_си_тип(const char *с, size_t n,
                             int *тип, int *указатели, int *беззнак)
{
    int указ = 0, есть_unsigned = 0, есть_signed = 0;
    int есть_void = 0, есть_char = 0, есть_short = 0, длинных = 0;
    int есть_int = 0, есть_float = 0, есть_double = 0, есть_bool = 0;
    int тд_тип = 0, тд_беззнак = 0, есть_тд = 0, чужой = 0;
    size_t i = 0;
    while (i < n) {
        char c = с[i];
        if (c == '*') { указ++; i++; continue; }
        if (c == ' ' || c == '\t' || c == '\n' || c == '(' || c == ')') { i++; continue; }
        if (это_имя_старт((unsigned char)c)) {
            size_t s0 = i;
            while (i < n && это_имя_прод((unsigned char)с[i])) i++;
            size_t дл = i - s0;
            const char *w = с + s0;
            #define СЛОВО(x) (дл == sizeof(x)-1 && memcmp(w, x, sizeof(x)-1) == 0)
            if (СЛОВО("const") || СЛОВО("volatile") || СЛОВО("restrict")
                || СЛОВО("__restrict") || СЛОВО("__restrict__")
                || СЛОВО("static") || СЛОВО("extern") || СЛОВО("inline")
                || СЛОВО("__inline") || СЛОВО("__inline__") || СЛОВО("register")
                || СЛОВО("_Noreturn") || СЛОВО("__extension__")) { continue; }
            if (СЛОВО("__attribute__") || СЛОВО("__attribute")) {
                while (i < n && с[i] != '(') i++;   // пропустить balanced (…)
                int ур = 0;
                while (i < n) { if (с[i]=='(') ур++; else if (с[i]==')') { ур--; if (ур==0){ i++; break; } } i++; }
                continue;
            }
            if (СЛОВО("unsigned")) { есть_unsigned = 1; continue; }
            if (СЛОВО("signed"))   { есть_signed = 1; continue; }
            if (СЛОВО("void"))   { есть_void = 1; continue; }
            if (СЛОВО("char"))   { есть_char = 1; continue; }
            if (СЛОВО("short"))  { есть_short = 1; continue; }
            if (СЛОВО("long"))   { длинных++; continue; }
            if (СЛОВО("int"))    { есть_int = 1; continue; }
            if (СЛОВО("float"))  { есть_float = 1; continue; }
            if (СЛОВО("double")) { есть_double = 1; continue; }
            if (СЛОВО("_Bool") || СЛОВО("bool")) { есть_bool = 1; continue; }
            if (СЛОВО("struct") || СЛОВО("union") || СЛОВО("enum")) { чужой = 1; continue; }
            if (!есть_тд && typedef_в_konda(w, дл, &тд_тип, &тд_беззнак)) { есть_тд = 1; continue; }
            чужой = 1;  // незнакомый идентификатор (чужой typedef/имя)
            continue;
            #undef СЛОВО
        }
        // Любой иной символ (напр. запятая — не должно быть в возвратном спане) —
        // считаем неотображаемым.
        чужой = 1; i++;
    }
    int базовый_есть = есть_void || есть_char || есть_short || длинных
                       || есть_int || есть_float || есть_double || есть_bool
                       || есть_unsigned || есть_signed || есть_тд;
    if (!базовый_есть) return 0;
    // Разрешаем «чужой» ТОЛЬКО если это единственный источник базы (typedef мы
    // уже обработали); если есть и базовый, и чужой — неоднозначно → отказ.
    if (чужой && !есть_тд) return 0;
    if (чужой && есть_тд) return 0;

    *указатели = указ; *беззнак = 0;
    if (есть_тд) { *тип = тд_тип; *беззнак = тд_беззнак; return 1; }
    if (есть_double) { *тип = ТОКЕН_ВЕЩЕСТВЕННОЕ64; return 1; }
    if (есть_float)  { *тип = ТОКЕН_ВЕЩЕСТВЕННОЕ;   return 1; }
    if (есть_bool)   { *тип = ТОКЕН_ЛОГИЧЕСКИЙ;     return 1; }
    if (есть_char)   { *тип = ТОКЕН_ТИП_СИМВОЛ;     return 1; }  // char/…char, в т.ч. char*
    if (есть_void) {
        if (указ > 0) return 0;   // void* — не отображаем (нет типа в Konda)
        *тип = ТОКЕН_НИЧЕГО; return 1;
    }
    // Целочисленные.
    *беззнак = есть_unsigned ? 1 : 0;
    if (есть_short)   { *тип = ТОКЕН_ЦЕЛОЕ16; return 1; }
    if (длинных >= 1) { *тип = ТОКЕН_ЦЕЛОЕ64; return 1; }
    *тип = ТОКЕН_ЦЕЛОЕ32; return 1;   // int / signed / unsigned (int)
}

// Вычисляет ПРОСТОЙ целочисленный литерал из RHS «#define» / enum-инициализатора:
// опц. скобки, каст к целому «(int)»/«(unsigned…)», унарный -/+/~, литерал
// dec/hex/oct + суффиксы u/l. Иное (идентификатор, арифметика двух операндов,
// строка) → 0 (не импортируем — безопасно). *беззнак/*тип — по суффиксу/величине.
static int вычислить_целую_константу(const char *с, size_t n,
                                     long long *знач, int *тип, int *беззнак)
{
    // Обрезать пробелы.
    while (n && (с[0]==' '||с[0]=='\t'||с[0]=='\n'||с[0]=='\r')) { с++; n--; }
    while (n && (с[n-1]==' '||с[n-1]=='\t'||с[n-1]=='\n'||с[n-1]=='\r')) n--;
    int каст_беззнак = 0, был_каст = 0;
    // Снять ведущие «(…)»: каст к целому типу ИЛИ группировку.
    for (;;) {
        if (n == 0 || с[0] != '(') break;
        // Найти парную «)».
        int ур = 0; size_t к = 0; int ok = 0;
        for (; к < n; ++к) { if (с[к]=='(') ур++; else if (с[к]==')') { ур--; if (ур==0){ ok=1; break; } } }
        if (!ok) return 0;
        // Содержимое (с+1 … с+к).
        const char *вн = с + 1; size_t вд = к - 1;
        while (вд && (вн[0]==' '||вн[0]=='\t')) { вн++; вд--; }
        while (вд && (вн[вд-1]==' '||вн[вд-1]=='\t')) вд--;
        // Каст к целому? (только type-keyword'ы). Иначе — группировка (если это
        // весь остаток) либо отказ.
        int ц_тип, ц_указ, ц_беззн;
        if (вд && отобразить_си_тип(вн, вд, &ц_тип, &ц_указ, &ц_беззн) && ц_указ == 0
            && (ц_тип==ТОКЕН_ЦЕЛОЕ8||ц_тип==ТОКЕН_ЦЕЛОЕ16||ц_тип==ТОКЕН_ЦЕЛОЕ32
                ||ц_тип==ТОКЕН_ЦЕЛОЕ64||ц_тип==ТОКЕН_БАЙТ)) {
            // Каст к целому: отбрасываем «(тип)», разбираем остаток после «)».
            был_каст = 1; каст_беззнак = ц_беззн;
            size_t остаток = n - (к + 1);
            с = с + к + 1; n = остаток;
            break;
        }
        // Группировка «(X)» — снимаем скобки, повторяем.
        с = вн; n = вд;
    }
    // Унарные.
    long long знак = 1; int инверт = 0;
    while (n && (с[0]=='-'||с[0]=='+'||с[0]=='~'||с[0]==' ')) {
        if (с[0]=='-') знак = -знак; else if (с[0]=='~') инверт ^= 1;
        с++; n--;
    }
    if (n == 0) return 0;
    // Литерал.
    unsigned long long v = 0; size_t i = 0; int суф_u = 0; int цифр = 0;
    if (n >= 2 && с[0]=='0' && (с[1]=='x'||с[1]=='X')) {
        i = 2;
        while (i < n && isxdigit((unsigned char)с[i])) {
            int d = isdigit((unsigned char)с[i]) ? с[i]-'0'
                    : (tolower((unsigned char)с[i])-'a'+10);
            v = v*16 + (unsigned)d; i++; цифр++;
        }
    } else if (с[0]=='0' && n > 1 && isdigit((unsigned char)с[1])) {
        i = 1;
        while (i < n && с[i]>='0' && с[i]<='7') { v = v*8 + (unsigned)(с[i]-'0'); i++; цифр++; }
    } else {
        while (i < n && isdigit((unsigned char)с[i])) { v = v*10 + (unsigned)(с[i]-'0'); i++; цифр++; }
    }
    if (цифр == 0) return 0;
    // Суффиксы u/U/l/L.
    while (i < n && (с[i]=='u'||с[i]=='U'||с[i]=='l'||с[i]=='L')) {
        if (с[i]=='u'||с[i]=='U') суф_u = 1;
        i++;
    }
    // Остаток — только пробелы, иначе это не простой литерал.
    while (i < n && (с[i]==' '||с[i]=='\t'||с[i]=='\n'||с[i]=='\r')) i++;
    if (i != n) return 0;

    int беззн = (суф_u || каст_беззнак) ? 1 : 0;
    (void)был_каст;
    long long результат;
    if (инверт) v = ~v;
    if (знак < 0) результат = -(long long)v;
    else результат = (long long)v;
    *знач = результат;
    // Ширина/знаковость итогового типа Konda.
    if (результат < 0) {
        *беззнак = 0;
        *тип = (результат >= INT32_MIN) ? ТОКЕН_ЦЕЛОЕ32 : ТОКЕН_ЦЕЛОЕ64;
    } else if (беззн) {
        *беззнак = 1;
        *тип = (v <= 0xFFFFFFFFull) ? ТОКЕН_ЦЕЛОЕ32 : ТОКЕН_ЦЕЛОЕ64;
    } else {
        *беззнак = 0;
        if (v <= (unsigned long long)INT32_MAX) { *тип = ТОКЕН_ЦЕЛОЕ32; }
        else if (v <= 0xFFFFFFFFull) { *тип = ТОКЕН_ЦЕЛОЕ32; *беззнак = 1; }
        else if (v <= (unsigned long long)INT64_MAX) { *тип = ТОКЕН_ЦЕЛОЕ64; }
        else { *тип = ТОКЕН_ЦЕЛОЕ64; *беззнак = 1; }
    }
    return 1;
}

// Готовит копию текста для разбора прототипов: комментарии, строковые и
// символьные литералы заменяются пробелами (переводы строк сохраняются),
// чтобы «(» внутри них не путал сканер. Директивы (#…) не трогаем — их сканер
// пропускает сам. Возвращает malloc-буфер (звонящий освобождает) или NULL.
static char *подготовить_текст(const char *ист, size_t n)
{
    char *out = malloc(n + 1);
    if (!out) return nullptr;
    for (size_t i = 0; i < n; ++i) {
        char c = ист[i];
        if (c == '/' && i + 1 < n && ист[i + 1] == '*') {          // /* … */
            out[i] = ' '; out[i + 1] = ' '; i += 2;
            while (i < n && !(ист[i] == '*' && i + 1 < n && ист[i + 1] == '/')) {
                out[i] = (ист[i] == '\n') ? '\n' : ' '; i++;
            }
            if (i < n) { out[i] = ' '; if (i + 1 < n) out[i + 1] = ' '; i++; }
            continue;
        }
        if (c == '/' && i + 1 < n && ист[i + 1] == '/') {          // // …
            while (i < n && ист[i] != '\n') { out[i] = ' '; i++; }
            if (i < n) out[i] = '\n';
            continue;
        }
        if (c == '"' || c == '\'') {                                // "…" '…'
            char кавычка = c;
            out[i] = ' '; i++;
            while (i < n && ист[i] != кавычка) {
                if (ист[i] == '\\' && i + 1 < n) { out[i] = ' '; out[i + 1] = ' '; i += 2; continue; }
                out[i] = (ист[i] == '\n') ? '\n' : ' '; i++;
            }
            if (i < n) out[i] = ' ';
            continue;
        }
        out[i] = c;
    }
    out[n] = '\0';
    return out;
}

// Из строки «#include <файл>» / «#include "файл"» извлекает имя и системность.
// Возвращает 1 при успехе.
static int разобрать_include(const char *строка, char *имя, size_t cap, int *системный)
{
    const char *p = строка;
    while (*p == ' ' || *p == '\t') p++;
    if (*p != '#') return 0;
    p++;
    while (*p == ' ' || *p == '\t') p++;
    if (strncmp(p, "include", 7) != 0) return 0;
    p += 7;
    while (*p == ' ' || *p == '\t') p++;
    char откр = *p, закр;
    if (откр == '<') { закр = '>'; *системный = 1; }
    else if (откр == '"') { закр = '"'; *системный = 0; }
    else return 0;
    p++;
    size_t k = 0;
    while (*p && *p != закр && *p != '\n' && k + 1 < cap) имя[k++] = *p++;
    имя[k] = '\0';
    return k > 0;
}

static int файл_существует(const char *путь)
{
    struct stat st;
    return stat(путь, &st) == 0 && S_ISREG(st.st_mode);
}

// Системные каталоги для «<…>»-заголовков. Их РЕАЛЬНЫЙ список берём у самого
// компилятора (`cc -E -Wp,-v`), чтобы видеть все пути, как их видит cc: multiarch
// (`/usr/include/x86_64-linux-gnu`, где живут bits/asm/sys/reboot.h и т.п.),
// gcc-internal и т.д. Это единственный надёжный способ найти те же заголовки,
// что и при последующей компиляции .c (политика проекта: свой реальный тулчейн).
// Кэш на процесс (однократная популяция; утечка намеренна — короткоживущий CLI).
static char **сист_каталоги = nullptr;
static int число_сист_каталогов = 0;
static int сист_каталоги_готовы = 0;

static void добавить_сист_каталог(const char *д)
{
    for (int i = 0; i < число_сист_каталогов; ++i)
        if (strcmp(сист_каталоги[i], д) == 0) return;   // дедуп
    char **p = realloc(сист_каталоги, (size_t)(число_сист_каталогов + 1) * sizeof(char *));
    if (!p) return;
    сист_каталоги = p;
    char *копия = strdup(д);
    if (!копия) return;
    сист_каталоги[число_сист_каталогов++] = копия;
}

static void обнаружить_системные_каталоги(void)
{
    if (сист_каталоги_готовы) return;
    сист_каталоги_готовы = 1;
    // Спрашиваем у компилятора его список поиска «#include <…>». Команда —
    // ФИКСИРОВАННАЯ строка (без пользовательского ввода → нет инъекции).
    FILE *p = popen("cc -E -Wp,-v -xc /dev/null 2>&1", "r");
    if (p) {
        char строка[1024];
        int внутри = 0;
        while (fgets(строка, sizeof(строка), p)) {
            if (strstr(строка, "#include <...> search starts here:")) { внутри = 1; continue; }
            if (strstr(строка, "End of search list.")) { внутри = 0; continue; }
            if (!внутри) continue;
            // Строки-каталоги идут с ведущим пробелом; отрезаем ws и '\n'.
            char *s = строка;
            while (*s == ' ' || *s == '\t') s++;
            size_t дл = strlen(s);
            while (дл && (s[дл-1] == '\n' || s[дл-1] == '\r' || s[дл-1] == ' ')) s[--дл] = '\0';
            if (дл == 0) continue;
            if (strstr(s, " (")) continue;   // «(framework directory)» и пр. — пропускаем
            добавить_сист_каталог(s);
        }
        pclose(p);
    }
    // Фолбэк/добор на случай, если cc недоступен или что-то не распозналось.
    добавить_сист_каталог("/usr/local/include");
    добавить_сист_каталог("/usr/include/x86_64-linux-gnu");
    добавить_сист_каталог("/usr/include");
}

// Разрешает имя заголовка в полный путь. база_путей — каталог исходника (для
// «локальных.h»). Возвращает 1 и пишет путь при успехе.
static int разрешить_заголовок(const char *имя, int системный,
                               const char *база_путей, char *путь, size_t cap)
{
    if (!системный && база_путей && база_путей[0]) {
        snprintf(путь, cap, "%s/%s", база_путей, имя);
        if (файл_существует(путь)) return 1;
    }
    обнаружить_системные_каталоги();
    for (int i = 0; i < число_сист_каталогов; ++i) {
        snprintf(путь, cap, "%s/%s", сист_каталоги[i], имя);
        if (файл_существует(путь)) return 1;
    }
    return 0;
}

// Каталог, содержащий файл (для разрешения относительных вложенных include).
static void каталог_файла(const char *путь, char *out, size_t cap)
{
    const char *слэш = strrchr(путь, '/');
    if (!слэш) { snprintf(out, cap, "."); return; }
    size_t n = (size_t)(слэш - путь);
    if (n >= cap) n = cap - 1;
    memcpy(out, путь, n);
    out[n] = '\0';
}

static void сканировать_файл(ТаблицаВнешних *т, const char *путь,
                             int глубина);

// Сканирует уже прочитанный текст заголовка: (1) извлекает прототипы функций,
// (2) следует вложенным #include.
static void сканировать_текст(ТаблицаВнешних *т, const char *ист, size_t n,
                              const char *свой_каталог, int глубина)
{
    // (1) Вложенные #include — по сырым строкам (до чистки, чтобы "имя.h"
    //     не было стёрто как строковый литерал).
    if (глубина < МАКС_ГЛУБИНА_ВКЛЮЧЕНИЙ) {
        const char *стр = ист;
        while (стр < ист + n) {
            const char *конец = memchr(стр, '\n', (size_t)(ист + n - стр));
            size_t длина_стр = конец ? (size_t)(конец - стр) : (size_t)(ист + n - стр);
            // Быстрый фильтр: строка-директива include.
            const char *q = стр;
            while (q < стр + длина_стр && (*q == ' ' || *q == '\t')) q++;
            if (q < стр + длина_стр && *q == '#') {
                char буфер_стр[1024];
                size_t к = длина_стр < sizeof(буфер_стр) - 1 ? длина_стр : sizeof(буфер_стр) - 1;
                memcpy(буфер_стр, стр, к); буфер_стр[к] = '\0';
                char имя[512]; int системный = 0;
                if (разобрать_include(буфер_стр, имя, sizeof(имя), &системный)) {
                    char путь[1024];
                    if (разрешить_заголовок(имя, системный, свой_каталог,
                                            путь, sizeof(путь))) {
                        сканировать_файл(т, путь, глубина + 1);
                    }
                }
            }
            if (!конец) break;
            стр = конец + 1;
        }
    }

    // (2) Прототипы функций — по очищенной копии.
    char *текст = подготовить_текст(ист, n);
    if (!текст) return;
    int глуб_скобок = 0;  // {…} — тело функции/структуры; прототипы на 0
    size_t i = 0;
    size_t начало_оператора = 0;  // §115: начало текущего C-оператора (для типа возврата)
    while (i < n) {
        char c = текст[i];
        if (c == '#') {  // директива
            size_t дир_старт = i;
            // §115: «#define ИМЯ <int-литерал>» → внешняя константа (без ручного
            // переобъявления «конст» в .конда). Функц.-подобные и не-целые макросы
            // пропускаем. Значение берём из подготовленного текста (строки/
            // комментарии уже стёрты в пробелы), до конца логической строки.
            size_t d = i + 1;
            while (d < n && (текст[d]==' '||текст[d]=='\t')) d++;
            int это_define = (d + 6 <= n && memcmp(текст+d, "define", 6) == 0
                              && (d+6==n || !это_имя_прод((unsigned char)текст[d+6])));
            // Пропустить директиву целиком (с учётом продолжения «\»).
            while (i < n && текст[i] != '\n') {
                if (текст[i] == '\\' && i + 1 < n && текст[i + 1] == '\n') i++;
                i++;
            }
            size_t дир_конец = i;  // указывает на '\n' или n
            if (это_define) {
                size_t p = d + 6;
                while (p < дир_конец && (текст[p]==' '||текст[p]=='\t')) p++;
                if (p < дир_конец && это_имя_старт((unsigned char)текст[p])) {
                    size_t имя0 = p;
                    while (p < дир_конец && это_имя_прод((unsigned char)текст[p])) p++;
                    size_t имя_дл = p - имя0;
                    if (p < дир_конец && текст[p] != '(') {   // объектный (не функц.) макрос
                        long long зн; int кт, кб;
                        if (вычислить_целую_константу(текст+p, дир_конец-p, &зн, &кт, &кб))
                            добавить_константу(т, текст+имя0, имя_дл, зн, кт, кб);
                    }
                }
            }
            (void)дир_старт;
            начало_оператора = (i < n) ? i + 1 : n;   // после директивы
            continue;
        }
        if (c == '{') { глуб_скобок++; i++; начало_оператора = i; continue; }
        if (c == '}') { if (глуб_скобок > 0) глуб_скобок--; i++; начало_оператора = i; continue; }
        if (c == ';') { i++; начало_оператора = i; continue; }
        if (это_имя_старт((unsigned char)c)) {
            size_t старт = i;
            while (i < n && это_имя_прод((unsigned char)текст[i])) i++;
            size_t длина_имени = i - старт;
            size_t j = i;
            while (j < n && (текст[j] == ' ' || текст[j] == '\t' || текст[j] == '\n')) j++;
            if (j < n && текст[j] == '(' && глуб_скобок == 0
                && !это_ключевое(текст + старт, длина_имени)) {
                // Кандидат-функция: разбираем группу скобок.
                size_t p = j + 1;
                int уровень = 1;
                int запятые = 0, переменное = 0;
                size_t содерж_старт = p, содерж_конец = p;
                int есть_содерж = 0;
                while (p < n && уровень > 0) {
                    char d = текст[p];
                    if (d == '(') уровень++;
                    else if (d == ')') { уровень--; if (уровень == 0) { содерж_конец = p; break; } }
                    else if (d == ',' && уровень == 1) запятые++;
                    else if (d == '.' && p + 2 < n && текст[p+1] == '.' && текст[p+2] == '.'
                             && уровень == 1) переменное = 1;
                    if (уровень >= 1 && d != ' ' && d != '\t' && d != '\n') есть_содерж = 1;
                    p++;
                }
                // Число параметров (эвристика; для вариативных — фиксированные).
                int число;
                if (!есть_содерж) {
                    число = -1;  // «()» — неизвестно
                } else {
                    // «(void)» → 0 параметров.
                    const char *s = текст + содерж_старт;
                    size_t дл = содерж_конец > содерж_старт ? содерж_конец - содерж_старт : 0;
                    while (дл && (*s == ' ' || *s == '\t' || *s == '\n')) { s++; дл--; }
                    while (дл && (s[дл-1] == ' ' || s[дл-1] == '\t' || s[дл-1] == '\n')) дл--;
                    if (дл == 4 && memcmp(s, "void", 4) == 0) число = 0;
                    else if (переменное) число = запятые;      // фикс. до «...»
                    else число = запятые + 1;
                }
                // §115: тип ВОЗВРАТА — спан [начало_оператора, старт) до имени.
                int в_изв = 0, в_тип = 0, в_указ = 0, в_беззн = 0;
                if (начало_оператора < старт) {
                    в_изв = отобразить_си_тип(текст + начало_оператора,
                                              старт - начало_оператора,
                                              &в_тип, &в_указ, &в_беззн);
                }
                добавить_функцию(т, текст + старт, длина_имени, число, переменное,
                                 в_изв, в_тип, в_указ, в_беззн);
                i = p;  // за закрывающей «)»
                начало_оператора = i;  // тело/«;» дальше — новый оператор
                continue;
            }
            continue;  // идентификатор без «(» — идём дальше
        }
        i++;
    }
    free(текст);
}

static void сканировать_файл(ТаблицаВнешних *т, const char *путь, int глубина)
{
    if (глубина >= МАКС_ГЛУБИНА_ВКЛЮЧЕНИЙ) return;
    if (т->всего_файлов >= МАКС_ФАЙЛОВ_ЗАГОЛОВКОВ) return;
    if (путь_виден(т, путь)) return;
    т->всего_файлов++;

    FILE *f = fopen(путь, "rb");
    if (!f) return;
    if (fseek(f, 0, SEEK_END) != 0) { fclose(f); return; }
    long размер = ftell(f);
    if (размер < 0 || fseek(f, 0, SEEK_SET) != 0) { fclose(f); return; }
    char *буфер = malloc((size_t)размер + 1);
    if (!буфер) { fclose(f); return; }
    size_t прочитано = fread(буфер, 1, (size_t)размер, f);
    fclose(f);
    буфер[прочитано] = '\0';

    char свой_каталог[1024];
    каталог_файла(путь, свой_каталог, sizeof(свой_каталог));
    сканировать_текст(т, буфер, прочитано, свой_каталог, глубина);
    free(буфер);
}

void собрать_внешние_функции(const Узел *корень, const char *база_путей,
                             ТаблицаВнешних *куда)
{
    if (!корень || !куда) return;
    for (size_t i = 0; i < узел_число_детей(корень); ++i) {
        const Узел *узел = узел_ребёнок(корень, i);
        if (!узел || узел->тип != УЗЕЛ_ПРЕПРОЦЕССОР) continue;
        // Токен препроцессора хранит всю строку «#содержит <файл>».
        char строка[1024];
        size_t дл = узел->токен.длина < sizeof(строка) - 1
            ? узел->токен.длина : sizeof(строка) - 1;
        memcpy(строка, узел->токен.начало, дл);
        строка[дл] = '\0';
        // §102: «использовать имя.h» — включение без решётки/кавычек (локальный).
        {
            const char *p = строка;
            while (*p == ' ' || *p == '\t') p++;
            const char *кисп = "использовать";
            if (strncmp(p, кисп, strlen(кисп)) == 0) {
                p += strlen(кисп);
                while (*p == ' ' || *p == '\t') p++;
                char имя_загл[512]; size_t к = 0;
                while (*p && *p != ' ' && *p != '\t' && *p != '\n'
                       && к + 1 < sizeof(имя_загл))
                    имя_загл[к++] = *p++;
                имя_загл[к] = '\0';
                if (к > 0) {
                    char путь[1024];
                    if (разрешить_заголовок(имя_загл, 0, база_путей, путь, sizeof(путь)))
                        сканировать_файл(куда, путь, 0);
                }
                continue;
            }
        }
        // «содержит» → «include» уже не сделано (это делает кодоген); здесь
        // работаем с исходной формой: заменим «содержит» на «include» для
        // общего разборщика include-директив.
        char нормализ[1024];
        char *содержит = strstr(строка, "содержит");
        if (содержит) {
            size_t смещ = (size_t)(содержит - строка);
            snprintf(нормализ, sizeof(нормализ), "%.*sinclude%s",
                     (int)смещ, строка, содержит + strlen("содержит"));
        } else {
            snprintf(нормализ, sizeof(нормализ), "%s", строка);
        }
        char имя[512]; int системный = 0;
        if (!разобрать_include(нормализ, имя, sizeof(имя), &системный)) continue;
        char путь[1024];
        if (разрешить_заголовок(имя, системный, база_путей, путь, sizeof(путь)))
            сканировать_файл(куда, путь, 0);
    }
}
