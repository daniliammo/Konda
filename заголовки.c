// Тип объявления (спецификаторы + звёзды/массив/функция декларатора).
static void тип_объявления(const ИндексСи *и, const ОбъявлениеСи *о, СиТип *итог, int глубина)
{
    *итог = (СиТип){0};
    if (о->указатель_на_функцию) { итог->класс = СИ_ФУНКЦИЯ; return; }
    if (о->массив == 2) return;
    разрешить_тип_си(и, о->спец_начало, о->спец_конец, итог, глубина);
    if (итог->класс == СИ_НЕИЗВЕСТЕН) return;
    итог->указатели += о->звёзд;
}

static void разрешить_тип_си(const ИндексСи *и, size_t н, size_t к, СиТип *итог, int глубина)
{
    *итог = (СиТип){0};
    if (глубина > 16) return;
    int unsig = 0, sig = 0, void_ = 0, char_ = 0, short_ = 0, длинных = 0, int_ = 0;
    int float_ = 0, double_ = 0, bool_ = 0, чужое = 0;
    for (size_t i = н; i < к; ++i) {
        const СиТокен *т = &и->токены[i];
        if (ст_атрибут(т)) { i = пропустить_атрибут(и, i, к) - 1; continue; }
        if (ст_знак(т, '{')) { i = за_парной(и, i, к) - 1; continue; }
        if (т->вид != СТ_ИМЯ) continue;
        if (ст_квалификатор(т) || ст_равно(т, "typedef") || ст_равно(т, "extern")
            || ст_равно(т, "static") || ст_равно(т, "inline") || ст_равно(т, "__inline")
            || ст_равно(т, "__inline__") || ст_равно(т, "register") || ст_равно(т, "_Noreturn")
            || ст_равно(т, "_Thread_local") || ст_равно(т, "thread_local")
            || ст_равно(т, "__thread") || ст_равно(т, "auto") || ст_равно(т, "constexpr"))
            continue;
        if (ст_равно(т, "unsigned")) { unsig = 1; continue; }
        if (ст_равно(т, "signed") || ст_равно(т, "__signed") || ст_равно(т, "__signed__")) { sig = 1; continue; }
        if (ст_равно(т, "void")) { void_ = 1; continue; }
        if (ст_равно(т, "char")) { char_ = 1; continue; }
        if (ст_равно(т, "short")) { short_ = 1; continue; }
        if (ст_равно(т, "long")) { длинных++; continue; }
        if (ст_равно(т, "int")) { int_ = 1; continue; }
        if (ст_равно(т, "float")) { float_ = 1; continue; }
        if (ст_равно(т, "double")) { double_ = 1; continue; }
        if (ст_равно(т, "_Bool") || ст_равно(т, "bool")) { bool_ = 1; continue; }
        if (ст_равно(т, "struct") || ст_равно(т, "union")) {
            size_t j = пропустить_атрибут(и, i + 1, к);
            итог->класс = СИ_ЗАПИСЬ;
            итог->тег = ст_равно(т, "struct") ? 1 : 2;
            if (j < к && и->токены[j].вид == СТ_ИМЯ && !си_ключевое(&и->токены[j])) {
                имя_в(итог->ид_записи, sizeof итог->ид_записи, &и->токены[j]);
                канон_записи(и, &и->токены[j], итог->запись, sizeof итог->запись);
            }
            // Анонимная запись — имя даст объемлющий typedef (вызывающий).
            return;
        }
        if (ст_равно(т, "enum")) {
            size_t j = пропустить_атрибут(и, i + 1, к);
            *итог = (СиТип){ .класс = СИ_СКАЛЯР, .тип = ТОКЕН_ЦЕЛОЕ32 };
            if (j < к && и->токены[j].вид == СТ_ИМЯ && !си_ключевое(&и->токены[j])) {
                const ЗаписьКарты *п = результат_пробы(и, 'e', &и->токены[j]);
                if (п && !скаляр_пробы(п->а, п->б, итог))
                    *итог = (СиТип){ .класс = СИ_СКАЛЯР, .тип = ТОКЕН_ЦЕЛОЕ32 };
            }
            return;
        }
        if (си_ключевое(т)) { чужое = 1; continue; }   // __int128, typeof, _Float128…
        // typedef-имя.
        const ОбъявлениеСи *тд = найти_объявление(и, т->начало, т->длина, ОБ_ТИПЕДЕФ);
        if (!тд) { чужое = 1; continue; }
        const ЗаписьКарты *п = результат_пробы(и, 't', т);
        if (п) {
            if (!скаляр_пробы(п->а, п->б, итог)) *итог = (СиТип){0};
            return;
        }
        if (тд->функция || тд->массив) return;   // тип-функция/массив — неотображаемо
        тип_объявления(и, тд, итог, глубина + 1);
        if (итог->класс == СИ_ЗАПИСЬ && тд->звёзд == 0 && !итог->ид_записи[0]) {
            // «typedef struct { … } X» — анонимная запись: имя и идентичность — X.
            имя_в(итог->ид_записи, sizeof итог->ид_записи, т);
            имя_в(итог->запись, sizeof итог->запись, т);
        }
        // Иначе имя записи — каноническое по тегу (единое для всех typedef'ов
        // одного тега: «__FILE*» и «FILE*» — один тип «FILE»).
        return;
    }
    if (чужое) return;
    if (double_ && длинных) return;              // long double — неотображаемо
    if (double_) { итог->класс = СИ_СКАЛЯР; итог->тип = ТОКЕН_ВЕЩЕСТВЕННОЕ64; return; }
    if (float_) { итог->класс = СИ_СКАЛЯР; итог->тип = ТОКЕН_ВЕЩЕСТВЕННОЕ; return; }
    if (bool_) { итог->класс = СИ_СКАЛЯР; итог->тип = ТОКЕН_ЛОГИЧЕСКИЙ; return; }
    if (char_) {
        итог->класс = СИ_СКАЛЯР;
        итог->тип = unsig ? ТОКЕН_БАЙТ : sig ? ТОКЕН_ЦЕЛОЕ8 : ТОКЕН_ТИП_СИМВОЛ;
        итог->беззнаковый = unsig;
        return;
    }
    if (void_) { итог->класс = СИ_НИЧЕГО; return; }
    if (!(unsig || sig || short_ || длинных || int_)) return;
    итог->класс = СИ_СКАЛЯР;
    итог->беззнаковый = unsig;
    итог->тип = short_ ? ТОКЕН_ЦЕЛОЕ16 : длинных ? ТОКЕН_ЦЕЛОЕ64 : ТОКЕН_ЦЕЛОЕ32;
}

// ─── Построение индекса (cc -E) ───────────────────────────────────────────────

static void построить_индекс(ТаблицаВнешних *т, ИндексСи *и)
{
    if (и->построен) return;
    и->построен = 1;
    if (!т->компилятор || т->число_включений == 0) return;
    проверить_включения(т);
    char *текст = nullptr; size_t длина = 0;
    if (т->пп_полный) {                     // кэш удачного полного прогона
        текст = т->пп_полный; длина = т->длина_пп_полного;
        т->пп_полный = nullptr;
    } else {
        // Только годные включения; частичный вывод при ошибке — тоже годен.
        прогнать_включения(т, т->число_включений, -1, &текст, &длина);
    }
    if (!текст || длина == 0) { free(текст); return; }
    длина = раскрыть_ucn(текст, длина);
    и->текст = текст;
    токенизировать_си(и, текст, длина);
    сканировать_объявления(и);
    и->успешен = 1;
}

// ─── Проба (cc -S): точные скалярные типы и значения констант ────────────────

typedef struct {
    char вид;        // 't' typedef, 'e' тег enum, 'c' константа
    const СиТокен *имя;
} ЭлементПробы;

static void добавить_в_пробу(ЭлементПробы **м, size_t *число, size_t *ёмкость,
                             Карта *видено, char вид, const СиТокен *имя)
{
    char ключ[300];
    if (имя->длина + 3 > sizeof ключ) return;
    ключ[0] = вид; ключ[1] = ':';
    memcpy(ключ + 2, имя->начало, имя->длина);
    ЗаписьКарты *з = карта_вставить(видено, ключ, имя->длина + 2);
    if (!з || з->есть) return;
    з->есть = 1;
    ОБЕСПЕЧИТЬ_ЁМКОСТЬ(*м, *ёмкость, *число + 1);
    (*м)[(*число)++] = (ЭлементПробы){ вид, имя };
}

// Typedef'ы и enum-теги, на которые опирается тип в [н, к) (транзитивно).
static void собрать_зависимости_типа(const ИндексСи *и, size_t н, size_t к, int глубина,
                                     ЭлементПробы **м, size_t *число, size_t *ёмкость,
                                     Карта *видено)
{
    if (глубина > 16) return;
    for (size_t i = н; i < к; ++i) {
        const СиТокен *т = &и->токены[i];
        if (ст_атрибут(т)) { i = пропустить_атрибут(и, i, к) - 1; continue; }
        if (т->вид != СТ_ИМЯ) continue;
        if (ст_равно(т, "enum")) {
            size_t j = пропустить_атрибут(и, i + 1, к);
            if (j < к && и->токены[j].вид == СТ_ИМЯ && !си_ключевое(&и->токены[j]))
                добавить_в_пробу(м, число, ёмкость, видено, 'e', &и->токены[j]);
            continue;
        }
        if (ст_равно(т, "struct") || ст_равно(т, "union")) return;
        if (си_ключевое(т)) continue;
        const ОбъявлениеСи *тд = найти_объявление(и, т->начало, т->длина, ОБ_ТИПЕДЕФ);
        if (!тд) continue;
        // Скалярный ли typedef (по тексту)? Записи/указатели/функции не пробуем:
        // «(T)0» для них невалиден и сломал бы пакет.
        СиТип с;
        тип_объявления(и, тд, &с, 0);
        if (с.класс == СИ_СКАЛЯР && с.указатели == 0 && !тд->функция && !тд->массив)
            добавить_в_пробу(м, число, ёмкость, видено, 't', т);
        if (тд->звёзд == 0)
            собрать_зависимости_типа(и, тд->спец_начало, тд->спец_конец, глубина + 1,
                                     м, число, ёмкость, видено);
        return;
    }
}

// Числа после метки «__konda_rN:» в .s: .quad/.xword/.8byte/.dword V; .zero N.
static int прочитать_ответ(const char *s, size_t номер, long long *куда, int сколько)
{
    char метка[48];
    snprintf(метка, sizeof метка, "konda_r%zu:", номер);
    const char *p = s;
    size_t дм = strlen(метка);
    for (;;) {
        p = strstr(p, метка);
        if (!p) return 0;
        if (p > s && (isalnum((unsigned char)p[-1]) && p[-1] != '_')) { p += дм; continue; }
        // Убедиться, что перед «konda_r» — «__» (gcc/clang; на Mach-O «___»).
        if (p - s < 2 || p[-1] != '_' || p[-2] != '_') { p += дм; continue; }
        break;
    }
    p += дм;
    int n = 0;
    while (n < сколько) {
        const char *стр = strchr(p, '\n');
        if (!стр) return 0;
        p = стр + 1;
        while (*p == ' ' || *p == '\t') p++;
        if (strncmp(p, ".quad", 5) == 0 || strncmp(p, ".xword", 6) == 0
            || strncmp(p, ".8byte", 6) == 0 || strncmp(p, ".dword", 6) == 0) {
            const char *ч = p;
            while (*ч && *ч != ' ' && *ч != '\t') ч++;
            куда[n++] = strtoll(ч, nullptr, 0);
        } else if (strncmp(p, ".zero", 5) == 0 || strncmp(p, ".space", 6) == 0) {
            const char *ч = p;
            while (*ч && *ч != ' ' && *ч != '\t') ч++;
            long long байт = strtoll(ч, nullptr, 0);
            for (long long b = 0; b < байт / 8 && n < сколько; ++b) куда[n++] = 0;
        } else {
            return n == сколько;
        }
    }
    return 1;
}

static void записать_элемент_пробы(Строитель *с, size_t номер, const ЭлементПробы *э)
{
    char шапка[64];
    snprintf(шапка, sizeof шапка, "const long long __konda_r%zu[] = { ", номер);
    строитель_строка(с, шапка);
    if (э->вид == 'c') {
        строитель_строка(с, "__KONDA_KC(");
        строитель_добавить(с, э->имя->начало, э->имя->длина);
        строитель_строка(с, "), (long long)sizeof(");
        строитель_добавить(с, э->имя->начало, э->имя->длина);
        строитель_строка(с, "), (long long)(");
        строитель_добавить(с, э->имя->начало, э->имя->длина);
        строитель_строка(с, ") };\n");
    } else {
        const char *пр = э->вид == 'e' ? "enum " : "";
        строитель_строка(с, "__KONDA_KC((");
        строитель_строка(с, пр);
        строитель_добавить(с, э->имя->начало, э->имя->длина);
        строитель_строка(с, ")0), (long long)sizeof(");
        строитель_строка(с, пр);
        строитель_добавить(с, э->имя->начало, э->имя->длина);
        строитель_строка(с, "), 0 };\n");
    }
}

static const char МАКРОС_KC[] =
    "#define __KONDA_KC(x) _Generic((x), _Bool: 1, char: 2, signed char: 3, "
    "unsigned char: 4, short: 5, unsigned short: 6, int: 7, unsigned: 8, long: 9, "
    "unsigned long: 10, long long: 11, unsigned long long: 12, float: 13, "
    "double: 14, default: 0)\n";

// Пробует элементы [н, к) одним запуском; при ошибке компиляции — бисекция.
static void пробовать(ТаблицаВнешних *т, ИндексСи *и, const ЭлементПробы *э, size_t н, size_t к)
{
    if (н >= к) return;
    Строитель с = {0};
    добавить_включения(т, &с);
    строитель_строка(&с, МАКРОС_KC);
    for (size_t i = н; i < к; ++i) записать_элемент_пробы(&с, i, &э[i]);
    if (с.ошибка) { free(с.данные); return; }
    char путь[1024];
    if (!записать_временный(&с, путь, sizeof путь)) { free(с.данные); return; }
    free(с.данные);
    char *argv[10];
    собрать_argv(т, "-S", "-w", путь, argv);
    // «-o -»: ассемблер в stdout — перед именем файла: … -x c [-I база] -o - файл
    char *argv2[12];
    int n = 0;
    for (int i = 0; argv[i]; ++i) {
        if (!argv[i + 1]) { argv2[n++] = (char *)"-o"; argv2[n++] = (char *)"-"; }
        argv2[n++] = argv[i];
    }
    argv2[n] = nullptr;
    char *вывод = nullptr; size_t длина = 0;
    int код = выполнить_и_захватить(argv2, &вывод, &длина);
    unlink(путь);
    if (код != 0 || !вывод) {
        free(вывод);
        if (к - н > 1) {
            size_t середина = н + (к - н) / 2;
            пробовать(т, и, э, н, середина);
            пробовать(т, и, э, середина, к);
        }
        return;
    }
    for (size_t i = н; i < к; ++i) {
        long long ответ[3];
        if (!прочитать_ответ(вывод, i, ответ, 3)) continue;
        char ключ[300];
        ключ[0] = э[i].вид; ключ[1] = ':';
        memcpy(ключ + 2, э[i].имя->начало, э[i].имя->длина);
        ЗаписьКарты *з = карта_вставить(&и->проба, ключ, э[i].имя->длина + 2);
        if (!з) continue;
        з->а = ответ[0]; з->б = ответ[1]; з->в = ответ[2]; з->есть = 1;
    }
    free(вывод);
}

// Однократная проба для всего, что нужно ПРОГРАММЕ: функции/переменные/константы,
// чьи имена встречаются в её AST, и typedef'ы/enum'ы их типов.
static void выполнить_пробу(ТаблицаВнешних *т, ИндексСи *и)
{
    if (и->проба_выполнена) return;
    и->проба_выполнена = 1;
    if (!и->успешен) return;
    ЭлементПробы *э = nullptr; size_t число = 0, ёмкость = 0;
    Карта видено = {0};
    for (size_t i = 0; i < и->число_объявлений; ++i) {
        const ОбъявлениеСи *о = &и->объявления[i];
        const СиТокен *имя = &и->токены[о->имя];
        if (!карта_найти(&и->имена_программы, имя->начало, имя->длина)) continue;
        if (о->вид == ОБ_КОНСТАНТА) {
            добавить_в_пробу(&э, &число, &ёмкость, &видено, 'c', имя);
            continue;
        }
        if (о->вид == ОБ_ТИПЕДЕФ) continue;
        собрать_зависимости_типа(и, о->спец_начало, о->спец_конец, 0, &э, &число, &ёмкость, &видено);
        if (о->вид == ОБ_ФУНКЦИЯ && о->пар_конец > о->пар_начало) {
            // Каждый параметр — свои спецификаторы.
            size_t п = о->пар_начало;
            while (п < о->пар_конец) {
                size_t конец = п;
                while (конец < о->пар_конец && !ст_знак(&и->токены[конец], ',')) {
                    const СиТокен *т2 = &и->токены[конец];
                    if (ст_знак(т2, '(') || ст_знак(т2, '[') || ст_знак(т2, '{'))
                        конец = за_парной(и, конец, о->пар_конец);
                    else конец++;
                }
                size_t кс = конец_спецификаторов(и, п, конец, nullptr);
                собрать_зависимости_типа(и, п, кс, 0, &э, &число, &ёмкость, &видено);
                п = конец + 1;
            }
        }
    }
    карта_освободить(&видено);
    пробовать(т, и, э, 0, число);
    free(э);
}

