/* ─────────────────────────────────────────────────────────────────────────────
   конда_ио.h — L1: ДОВЕРЕННЫЙ C-шим stdlib Konda для файлового ввода/вывода.
   ─────────────────────────────────────────────────────────────────────────────

   Идея архитектуры (см. РЕШЕНИЯ §33 / stdlib):
     • L0 — POSIX (open/read/write/close/lseek). Скрыт от пользователя.
     • L1 — этот файл: одна аудируемая точка «небезопасности». Принимает
            дескриптор ФАЙЛА (int fd) и БУФЕР как Konda-Срез {данные, длина} по
            значению — значит границы гарантируются длиной среза ПО ПОСТРОЕНИЮ.
            Пользовательский код на Konda сюда не смотрит.
     • L2 — файл.конда: безопасные обёртки (RAII-структура «Файл» с
            [удалить=…], sum-тип «Открытие» вместо errno-глобала).

   Конвенция возврата: long, где ≥0 — успех/число байт, <0 — «-errno».
   Так signed-возврат сам служит маркером ошибки — не нужен второй out-параметр
   и не нужно тянуть <errno.h> в пользовательский модуль. Пользователь Konda
   получает `целое32 код` (положительный errno) через sum-тип «Ошибка(код)».

   Тип Срез должен совпадать с ТИПДЕФ_СРЕЗ из кодогена (kодоген.c:844):
     typedef struct { void *данные; size_t длина; } Срез;
   Guard KONDA_SREZ_DEFINED тот же, чтобы не конфликтовать с эмитом кодогена.
   ────────────────────────────────────────────────────────────────────────── */
#pragma once
#include <stddef.h>
#include <stdint.h>
#include <errno.h>
#include <unistd.h>
#include <fcntl.h>
#include <sys/stat.h>

#ifndef KONDA_SREZ_DEFINED
#define KONDA_SREZ_DEFINED
typedef struct { void *данные; size_t длина; } Срез;
#endif

/* Внутренний хелпер: превратить (-1 + errno) в отрицательный код возврата.
   errno всегда >0 по POSIX → инверсия даёт <0 → маркер ошибки. Ошибку 0
   (не бывает) страхуем: -EINVAL. */
static inline long _конда_возврат_ошибки(void) {
    int e = errno;
    return e > 0 ? -(long)e : -(long)EINVAL;
}

/* Открыть файл. Три отдельные функции — по режиму: так POSIX-флаги ВООБЩЕ
   не пересекают границу Konda (пользователь не тянет <fcntl.h>). Строка пути —
   NUL-терминированная (Konda «символ*» = char*, литералы NUL-терминированы).
   Возврат: fd (>=0) или -errno. */
static inline long конда_ио_открыть_чтение(const char *путь) {
    long fd = open(путь, O_RDONLY);
    return fd < 0 ? _конда_возврат_ошибки() : fd;
}
static inline long конда_ио_открыть_запись(const char *путь, int режим) {
    long fd = open(путь, O_WRONLY | O_CREAT | O_TRUNC, режим);
    return fd < 0 ? _конда_возврат_ошибки() : fd;
}
static inline long конда_ио_открыть_добавление(const char *путь, int режим) {
    long fd = open(путь, O_WRONLY | O_CREAT | O_APPEND, режим);
    return fd < 0 ? _конда_возврат_ошибки() : fd;
}

/* Прочитать в буфер. Возврат: число прочитанных байт (0 = EOF) или -errno.
   Границы: read(2) сама ограничивается буфер.длина — выйти за конец
   Konda-среза невозможно. */
static inline long конда_ио_прочитать(int fd, Срез буфер) {
    ssize_t н = read(fd, буфер.данные, буфер.длина);
    return н < 0 ? _конда_возврат_ошибки() : (long)н;
}

/* Записать из буфера. Возврат: число записанных байт (может быть < длины —
   частичная запись — обычное поведение write) или -errno. */
static inline long конда_ио_записать(int fd, Срез буфер) {
    ssize_t н = write(fd, буфер.данные, буфер.длина);
    return н < 0 ? _конда_возврат_ошибки() : (long)н;
}

/* Закрыть fd. Возврат: 0 или -errno. Идемпотентно относительно fd<0
   (позволяет вызывать из деструктора без второй проверки). */
static inline long конда_ио_закрыть(int fd) {
    if (fd < 0) return 0;
    return close(fd) < 0 ? _конда_возврат_ошибки() : 0;
}

/* Размер файла в байтах (через fstat, без seek — не двигает позицию).
   Возврат: размер (>=0) или -errno. */
static inline long конда_ио_размер(int fd) {
    struct stat s;
    if (fstat(fd, &s) < 0) return _конда_возврат_ошибки();
    return (long)s.st_size;
}

