/* ─────────────────────────────────────────────────────────────────────────────
   stdlib/конда_хеш.h — L1: доверенный C-шим хеш-функций stdlib.
   FNV-1a 64-бит по байтам среза. Байтовая арифметика и БЕЗЗНАКОВОЕ переполнение с
   переносом не выражаются в Konda: символ неарифметичен (вне §71/§75-каста), а
   знаковый целое64-overflow в отладке падает по guard (§43); плюс литерал offset-
   basis 14695981039346656037 (> int64 max) эмитился бы без суффикса ULL → -Werror
   генерируемого C (§65). Поэтому хеш — в шиме; Konda-слой (хеш.конда) лишь
   передаёт срез и получает готовый целое64. Паттерн — как stdlib/конда_ио.h.

   Тип Срез должен совпадать с ТИПДЕФ_СРЕЗ кодогена; общий guard KONDA_SREZ_DEFINED
   (тот же, что у конда_ио.h — при подключении обоих модулей Срез определится раз).
   ────────────────────────────────────────────────────────────────────────── */
#pragma once
#include <stddef.h>
#include <stdint.h>

#ifndef KONDA_SREZ_DEFINED
#define KONDA_SREZ_DEFINED
typedef struct { void *данные; size_t длина; } Срез;
#endif

/* FNV-1a 64-бит. Границы гарантированы длиной среза по построению (доступа за
   пределы .данные нет). Детерминированный, без состояния. */
static inline uint64_t конда_фнв1а(Срез данные) {
    const unsigned char *байты = (const unsigned char *)данные.данные;
    uint64_t хеш = 14695981039346656037ULL;   /* FNV offset basis */
    for (size_t i = 0; i < данные.длина; ++i) {
        хеш ^= байты[i];
        хеш *= 1099511628211ULL;               /* FNV prime */
    }
    return хеш;
}
