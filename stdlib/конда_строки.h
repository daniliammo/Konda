/* конда_строки.h — доверенный C-шим строковых операций (§32, слой L1).
 *
 * ЗАЧЕМ. Побайтовые циклы сравнения в Konda компилируются в скалярный код;
 * glibc же несёт memcmp с диспетчером ifunc (SSE2/AVX2/AVX-512 под CPU) — на
 * больших строках он в разы быстрее. Роутим горячие равно/начинается_с в glibc
 * memcmp: паритет с glibc по построению (мы вызываем ЕЁ реализацию). Разбор
 * (это_число/в_целое) остаётся чистым Konda — там посимвольная логика, не блочный
 * memcmp, а домен разбора и был причиной §75.
 *
 * БЕЗОПАСНОСТЬ. Срез приходит ПО ЗНАЧЕНИЮ ({данные,длина,…}) → длина известна,
 * memcmp ограничен ею, за конец среза не выйти. Konda-обёртка гейтит вызов
 * «небезопасно», пользователь строк — нет. Никакой записи, только сравнение.
 */
#pragma once
#include <stddef.h>
#include <string.h>

/* Совместимо с ABI-дескриптором кодогена: реальный Срез (3 поля {данные,длина,
 * ёмкость}) определяется в .c ДО этого include, а KONDA_SREZ_DEFINED подавляет
 * здешний. memcmp читает лишь .данные/.длина — первые два поля в обоих раскладках,
 * поэтому шим корректен независимо от того, чей Срез вкомпилён. */
#ifndef KONDA_SREZ_DEFINED
#define KONDA_SREZ_DEFINED
typedef struct { void *данные; size_t длина; } Срез;
#endif

/* Равенство строк: длины равны И побайтово совпадают (memcmp). 1 — равны. */
static inline int конда_строки_равно(Срез а, Срез б) {
    if (а.длина != б.длина) return 0;
    if (а.длина == 0) return 1;
    return memcmp(а.данные, б.данные, а.длина) == 0 ? 1 : 0;
}

/* Начинается ли `текст` с `префикс` (memcmp по длине префикса). 1 — да. */
static inline int конда_строки_начинается(Срез текст, Срез префикс) {
    if (префикс.длина > текст.длина) return 0;
    if (префикс.длина == 0) return 1;
    return memcmp(текст.данные, префикс.данные, префикс.длина) == 0 ? 1 : 0;
}
