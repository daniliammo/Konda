# санитайзер.sh — ASan/UBSan-фазы (транспилятор + сгенерированный C).
# Ожидает: ROOT, BIN, TMP (корпус .конда + cwd), SAN_MARKERS (common.sh).

# ─── Санитайзеры транспилятора: ASan + UBSan по всему корпусу ───────────────
# Все .конда выше уже созданы как фикстуры — переиспользуем их бесплатно, гоняя
# через сборку CLI с ASan+UBSan. Цель — ловить ошибки памяти В САМОМ
# ТРАНСПИЛЯТОРЕ (арена, AST-узлы, работа со строками, UTF-8): инвариант
# «безопасен и сам транспилятор». Прежде санитайзился только СГЕНЕРИРОВАННЫЙ C
# (напр. стек_срез выше) — фронт/семантика/кодоген самого компилятора не
# покрывались вовсе.
#
# ⚠ ПРЕДУПРЕЖДЕНИЕ про jemalloc: он НЕСОВМЕСТИМ с ASan — перехватывает
#   malloc/free мимо интерцепторов санитайзера. Поэтому санитайзер-прогон
#   ФОРСИРУЕТ --аллокатор=libc: иначе выходной .elf с jemalloc (дефолт CLI)
#   конфликтовал бы с ASan. Здесь берём --только-си (компиляции выхода нет),
#   но --аллокатор=libc задаём ЯВНО — как исполнение этого инварианта и
#   страховку, если режим прогона однажды сменят на компиляцию.
# Утечки (LSan) намеренно НЕ утверждаем: транспилятор короткоживущий
# (арена + выход), а цель здесь — use-after-free/overflow/переполнение;
# отсюда detect_leaks=0 (иначе — шум ложных «утечек» арены).
printf 'Санитайзер-прогон транспилятора (ASan+UBSan, аллокатор libc)…\n'
KASAN="$TMP/квасан"
cc -std=gnu23 -g -O0 -fsanitize=address,undefined \
    "$ROOT"/дин_массив.c "$ROOT"/токенизатор_лексер.c "$ROOT"/конвейер.c \
    "$ROOT"/ввод_вывод.c "$ROOT"/аст.c "$ROOT"/разбор.c "$ROOT"/обобщения.c \
    "$ROOT"/семантика.c "$ROOT"/владение.c "$ROOT"/кодоген.c "$ROOT"/заголовки.c \
    "$ROOT"/интерфейс.c "$ROOT"/макросы.c "$ROOT"/libkonda_ide.c "$ROOT"/основа.c \
    -o "$KASAN" 2>"$TMP/квасан_сборка.log" || {
    cat "$TMP/квасан_сборка.log" >&2
    fail "сборка транспилятора с ASan+UBSan должна проходить"
}

# Одиночные фикстуры (+ песочница тест.конда) — ПАРАЛЛЕЛЬНО (xargs -P): каждый
# прогон KASAN независим — пишет свой вывод/<имя>.c (уникальное имя) и свой лог.
# Прежде фаза была строго ПОСЛЕДОВАТЕЛЬНОЙ (~21 с из ~29 с санитайзеров, ~500
# фикстур × ASan-транспиляция ~40 мс); на N ядрах — ~3 с. Негативные фикстуры
# транспилятор отвергает ненулевым кодом (норма, || true); реагируем ТОЛЬКО на
# маркеры санитайзера. Ошибки копим в общий файл (мелкие O_APPEND атомарны).
: > "$TMP/сан_список"
for f in "$ROOT"/tests/тест.конда "$TMP"/*.конда; do
    [ -e "$f" ] || continue
    printf '%s\0' "$f" >> "$TMP/сан_список"   # NUL-разделитель: имя может нести «"»
done
NPROC=$(getconf _NPROCESSORS_ONLN 2>/dev/null || echo 4)
: > "$TMP/сан_ошибки"
xargs -0 -P "$NPROC" -I {} sh -c '
    f=$1; TMP=$2; SAN=$3; KASAN=$4; ROOT=$5
    base=$(basename "$f")
    ASAN_OPTIONS=detect_leaks=0 UBSAN_OPTIONS=print_stacktrace=1 \
        KONDA_STDLIB="$ROOT/stdlib/вывод" \
        "$KASAN" --только-си --аллокатор=libc "$f" >"$TMP/сан_${base}.log" 2>&1 || true
    if grep -qE "$SAN" "$TMP/сан_${base}.log"; then
        printf "FAIL: санитайзер сработал на %s\n" "$base" >&2
        cat "$TMP/сан_${base}.log" >&2
        printf "%s\n" "$base" >> "$TMP/сан_ошибки"
    fi
' _ {} "$TMP" "$SAN_MARKERS" "$KASAN" "$ROOT" < "$TMP/сан_список"

# Мультифайловые наборы: одиночный прогон выше НЕ трогает путь слияния
# (слить_программы) и cross-file обобщения — эти дефекты видны только когда
# файлы поданы вместе. Гоняем ровно те же комбинации (и перестановки порядка),
# что и $BIN в мультифайловых тестах выше; при добавлении нового мультифайл-
# теста продублируйте его набор сюда. Их немного — оставляем последовательными,
# копим в тот же файл ошибок. IFS по умолчанию (пробел) → $combo расщепляется на
# отдельные файлы-аргументы (кавычки намеренно опущены).
while IFS= read -r combo; do
    [ -n "$combo" ] || continue
    ASAN_OPTIONS=detect_leaks=0 UBSAN_OPTIONS=print_stacktrace=1 \
        "$KASAN" --только-си --аллокатор=libc $combo >"$TMP/сан_комбо.log" 2>&1 || true
    if grep -qE "$SAN_MARKERS" "$TMP/сан_комбо.log"; then
        printf 'FAIL: санитайзер сработал на мультифайле: %s\n' "$combo" >&2
        cat "$TMP/сан_комбо.log" >&2
        printf '%s\n' "$combo" >> "$TMP/сан_ошибки"
    fi
done <<'COMBOS'
файлы_главный.конда файлы_модуль.конда
файлы_модуль.конда файлы_главный.конда
файлы_использует_типы.конда файлы_типы.конда
обобщ_главный.конда обобщ_модуль.конда
обобщ_модуль.конда обобщ_главный.конда
файлы_использует_перечисление.конда файлы_перечисление.конда
файлы_перечисление.конда файлы_использует_перечисление.конда
возврат_структуры_файл_б.конда возврат_структуры_файл_а.конда
COMBOS

[ ! -s "$TMP/сан_ошибки" ] || fail "транспилятор должен быть чист под ASan+UBSan на всём корпусе"

# ─── ASan+UBSan для сгенерированного C (.elf): ловим ошибки КОДОГЕНА ─────────
# Прошлый прогон санитайзит САМ транспилятор; этот — его ВЫХОД. Транспилятор-
# санитайзер выше только что заново сгенерировал вывод/<имя>.c для КАЖДОЙ
# фикстуры (--только-си, поэтому в ОТЛАДОЧНОМ режиме — с guard'ами границ/
# деления/переполнения — и с libc). Пересобираем каждый такой .c напрямую через
# cc с ASan+UBSan и ЗАПУСКАЕМ — так ловятся ошибки памяти в СГЕНЕРИРОВАННОЙ
# программе (индексация, срезы, деструкция, потоки), которые прошли бы обычную
# компиляцию, но нарушали бы безопасность. Прежде так проверялась ровно одна
# фикстура (стек_срез) — теперь весь корпус.
#
# Почему ПОСЛЕ прогона транспилятора, а не по «как оставили» вывод/*.c: часть
# фикстур (переполнение_рантайм) выше пересобиралась с --релиз, а релиз ПО
# ДИЗАЙНУ снимает guard'ы (инвариант №1: скорость C) → сырое знаковое сложение
# переполняется, и UBSan штатно бы это поймал — но это не дефект кодогена, а
# принятый компромисс релиза. Прогон транспилятора нормализует всё обратно в
# отладку, где guard аккуратно abort'ит ДО UB (проверено: «переполнение целого»
# + SIGABRT, без маркера санитайзера).
#
# ⚠ jemalloc НЕСОВМЕСТИМ с ASan (перехват malloc/free мимо интерцепторов),
#   поэтому компилируем вывод/*.c НАПРЯМУЮ через cc (libc-аллокатор, без
#   -l:libjemalloc), минуя точку компиляции транспилятора с дефолтным jemalloc.
#
# Самоотбор без списков-дубликатов:
#   • исполняемые .c отличимы по эмитированному «int32_t main(» (точка_входа →
#     main в кодогене); библиотеки (--библиотека) main не имеют → отсеиваются
#     grep'ом ДО cc, без заведомо падающей компиляции;
#   • фикстуры-гарды (границы/деление/переполнение) штатно abort'ят через
#     конда_прервать — это НЕ маркер санитайзера, падение по коду выхода
#     игнорируем (|| true), реагируем ТОЛЬКО на маркеры;
#   • stdin из /dev/null и timeout — чтобы ни одна программа не блокировала
#     прогон (ввод/зависание); утечки не утверждаем (detect_leaks=0), цель —
#     use-after-free/overflow в кодогене.
# Распараллелено по числу ядер (xargs -P): компиляция и запуск .elf независимы
# между файлами. Стоимость фазы была ~40 с из ~62 с всего прогона (224 файла ×
# (cc ~60 мс + запуск под ASan ~107 мс), строго последовательно); на 12 ядрах —
# ~4 с. Ошибки копим в общий файл (мелкие O_APPEND-записи атомарны) и подводим
# итог после xargs; per-file лог — свой ($TMP/elf_сан_<имя>.out).
if command -v cc >/dev/null 2>&1; then
    printf 'ASan+UBSan сгенерированного C (.elf, кодоген; аллокатор libc)…\n'
    elf_err=0
    : > "$TMP/elf_список"
    for c in вывод/*.c; do
        [ -e "$c" ] || continue
        if grep -qE '^int32_t main\(' "$c"; then
            # NUL-разделитель: имя может содержать «"» (фикстура кавычка"внутри)
            printf '%s\0' "$c" >> "$TMP/elf_список"
        fi
    done
    if [ -s "$TMP/elf_список" ]; then
        NPROC=$(getconf _NPROCESSORS_ONLN 2>/dev/null || echo 4)
        : > "$TMP/elf_ошибки"
        xargs -0 -P "$NPROC" -I {} sh -c '
            c=$1; TMP=$2; SAN=$3
            base=$(basename "$c" .c)
            if cc -std=gnu23 -g -O0 -fsanitize=address,undefined "$c" \
                -o "$TMP/elf_${base}_asan" 2>/dev/null; then
                ASAN_OPTIONS=detect_leaks=0 UBSAN_OPTIONS=print_stacktrace=1 \
                    timeout 30 "$TMP/elf_${base}_asan" </dev/null \
                    >"$TMP/elf_сан_${base}.out" 2>&1 || true
                if grep -qE "$SAN" "$TMP/elf_сан_${base}.out"; then
                    printf "FAIL: санитайзер в сгенерированном .elf: %s\n" "$base" >&2
                    cat "$TMP/elf_сан_${base}.out" >&2
                    printf "%s\n" "$base" >> "$TMP/elf_ошибки"
                fi
            fi
        ' _ {} "$TMP" "$SAN_MARKERS" < "$TMP/elf_список"
        [ ! -s "$TMP/elf_ошибки" ] || fail "сгенерированный C должен быть чист под ASan+UBSan (ошибка кодогена)"
    fi
fi

printf 'OK: все тесты прошли\n'
