#!/bin/sh
# ═══════════════════════════════════════════════════════════════════════════
# ПОСЛЕДОВАТЕЛЬНЫЙ прогон набора (эталон, детерминированный порядок вывода —
# удобно для отладки одиночного падения). По умолчанию используйте ./run.sh
# (параллельный, ~в 1.6× быстрее; шардирует то же тело.sh, результат идентичен).
#
# Структура набора (модульная):
#   common.sh — хелперы (fail/assert_eq), SAN_MARKERS, проверка компилятора,
#               санитайзер-функции (build_kasan/sanitize_dir/sanitize_extra).
#   тело.sh   — все тест-секции (grep -nE '^# ─' tests/тело.sh).
# Добавляя тест — правь тело.sh (как раньше правили run.sh).
# ═══════════════════════════════════════════════════════════════════════════
set -eu

ROOT=$(CDPATH= cd -- "$(dirname "$0")/.." && pwd)
BIN="$ROOT/Собранное/ТранспиляторКонда"

. "$ROOT/tests/common.sh"
check_compiler

make -C "$ROOT"

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
cd "$TMP"

. "$ROOT/tests/тело.sh"

# Санитайзер-фазы — те же общие функции (common.sh), что и параллельный run.sh:
# единый код, без расхождений. sanitize_corpus внутри параллелит (xargs -P).
KASAN="$TMP/квасан"
build_kasan "$KASAN"
sanitize_corpus
printf 'OK: все тесты прошли\n'
