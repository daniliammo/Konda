#!/bin/sh
# ═══════════════════════════════════════════════════════════════════════════
# Прогон тест-набора (ПАРАЛЛЕЛЬНЫЙ — по умолчанию). Шардирует тело.sh на
# непересекающиеся НЕПРЕРЫВНЫЕ куски (split_shards.py режет только на безопасных
# границах — где ни одна фикстура не «переезжает» через разрез), гоняет их через
# xargs -P в ИЗОЛИРОВАННЫХ mktemp-каталогах (ноль гонок общего состояния), затем
# сводит фикстуры в общий корпус и запускает те же санитайзер-фазы.
#
# Структура набора (модульная, добавляя тест — правь тело.sh):
#   common.sh     — хелперы (fail/assert_eq), SAN_MARKERS, проверка компилятора
#                   и санитайзер-функции (build_kasan/sanitize_dir/sanitize_extra).
#   тело.sh       — все тест-секции (grep -nE '^# ─' tests/тело.sh).
#   split_shards.py — безопасная нарезка тела на шарды.
# Эталон (последовательный, детерминированный порядок вывода — для отладки):
#   ./run_seq.sh — результат ДОЛЖЕН совпадать (проверено: OK, ловля падений,
#   идентичный корпус санитайзера 514 фикстур).
# ═══════════════════════════════════════════════════════════════════════════
set -eu

ROOT=$(CDPATH= cd -- "$(dirname "$0")/.." && pwd)
BIN="$ROOT/Собранное/ТранспиляторКонда"

. "$ROOT/tests/common.sh"
check_compiler

# Параллельный прогон опирается на python3 (безопасная нарезка тела на шарды).
# Нет python3 → надёжный откат на последовательный эталон (набор работает всегда).
if ! command -v python3 >/dev/null 2>&1; then
    printf 'python3 не найден — последовательный прогон (run_seq.sh)\n' >&2
    exec "$ROOT/tests/run_seq.sh"
fi

make -C "$ROOT"

NPROC=$(getconf _NPROCESSORS_ONLN 2>/dev/null || echo 4)
CORPUS=$(mktemp -d)
SHARDS=$(mktemp -d)
trap 'rm -rf "$CORPUS" "$SHARDS"' EXIT

# ASan+UBSan-сборка транспилятора (KASAN) — ОДИН раз (нужна санитайзер-фазе на
# сведённом корпусе). Строим В ФОНЕ, пока идут шарды тела — перекрываем ~3 с.
KASAN="$SHARDS/квасан"
build_kasan "$KASAN" & KASAN_PID=$!

# Нарезка тела на безопасные шарды (кусков ~ 2× ядер — лучше балансировка при
# неравных секциях). Число реально созданных шардов печатает скрипт.
n=$(python3 "$ROOT/tests/split_shards.py" "$ROOT/tests/тело.sh" "$SHARDS" $((NPROC * 2)))
printf 'Параллельный прогон: %s шардов тела на %s ядрах…\n' "$n" "$NPROC"

# Шарды — параллельно. ROOT/BIN/CORPUS наследуются потомками через экспорт.
# Каждый шард: тело в ИЗОЛИРОВАННОМ каталоге + копия фикстур в корпус. Упавший
# шард печатает лог и отмечается в FAIL-файле; xargs идёт дальше.
export ROOT BIN CORPUS
FAILMARK="$SHARDS/_упавшие"
: > "$FAILMARK"
ls "$SHARDS"/shard_*.sh | xargs -P "$NPROC" -I {} sh -c '
    sh "$1" > "$1.log" 2>&1 || { cat "$1.log" >&2; printf "%s\n" "$1" >> "$2"; }
' _ {} "$FAILMARK"
[ ! -s "$FAILMARK" ] || fail "параллельный прогон: $(wc -l < "$FAILMARK") шард(ов) упало (логи выше)"

# Дождаться фоновой сборки KASAN (обычно уже готова к этому моменту).
wait "$KASAN_PID" || fail "сборка транспилятора с ASan+UBSan должна проходить"

# Санитайзер-фазы — ЦЕНТРАЛИЗОВАННО на СВЕДЁННОМ корпусе (xargs -P балансирует
# лучше пер-шардового дробления). Те же фазы, что в последовательном run_seq.sh.
cd "$CORPUS"
sanitize_corpus
printf 'OK: все тесты прошли\n'
