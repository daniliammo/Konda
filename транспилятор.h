// Растущая ёмкость таблиц (семантика/парсер/кодоген — пределов нет: реальные
// C-проекты — сотни структур/функций/вариантов). Обнуляет новую часть. Нужны
// <stdlib.h>/<string.h>. Указатели в таблицу живут до следующего роста — поэтому
// сборщики резервируют ёмкость ЗАРАНЕЕ (по числу узлов), рост в цикле — страховка.
#define ОБЕСПЕЧИТЬ_ЁМКОСТЬ(массив, ёмкость, нужно)                              \
    do {                                                                        \
        size_t _нужно = (size_t)(нужно);                                        \
        if (_нужно > (ёмкость)) {                                               \
            size_t _новая = (ёмкость) ? (ёмкость) : 16;                          \
            while (_новая < _нужно) _новая *= 2;                                \
            void *_блок = realloc((массив), _новая * sizeof *(массив));         \
            if (!_блок) { perror("realloc"); exit(1); }                         \
            memset((char *)_блок + (ёмкость) * sizeof *(массив), 0,             \
                   (_новая - (ёмкость)) * sizeof *(массив));                    \
            (массив) = _блок;                                                   \
            (ёмкость) = _новая;                                                 \
        }                                                                       \
    } while (0)
// Гарантирует ёмкость под ещё `сколько` элементов (одна realloc вместо
// многократных при добавлении блоком). Возвращает указатель на «хвост» —
// первый свободный слот, куда вызывающий может записать `сколько` элементов
// (после чего сам увеличивает `длина`).
