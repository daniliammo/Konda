// §133: примитивные типы Konda — ЕДИНСТВЕННАЯ таблица их имён, C-отображения и
// размера (строки ПРИМИТИВ в «токены.def», §134). Лексер, «.и», диагностики, мономорфизация,
// IDE и кодоген берут имя отсюда; новый примитив добавляется одной строкой списка.
typedef struct {
    ТипТокена тип;
    const char *имя;            // ключевое слово Konda («целое32»)
    const char *си;             // C-тип («int32_t»)
    const char *си_беззнаковый; // C-тип с модификатором «неподписанный»;
                                // nullptr — модификатор к типу не применяется
    int размер;                 // размер в байтах на LP64 (0 — «ничего»)
} ПримитивныйТип;

