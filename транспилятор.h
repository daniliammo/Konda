// §88 Раздельная компиляция + LTO: компилирует каждый .c в свой .o (тем же
// набором флагов, что и скомпилировать_си, плюс «-flto -c»), но ТОЛЬКО когда
// «изменился[i]» (файл или общий заголовок поменялись, или .o отсутствует), затем
// линкует все .o с «-flto» в итоговый бинарник/.so. Так изменение одного .конда
// пересобирает лишь его .o, а межпроцедурный инлайн между единицами трансляции
// восстанавливает LTO. «пути_c[число_tu]» — сгенерированные .c; «путь_вывода» —
// без суффикса (добавляется .elf/.so). Остальные параметры — как у
// скомпилировать_си (действуют на этап компиляции и/или линковки).
int скомпилировать_раздельно(const char (*пути_c)[512], const int *изменился,
                       size_t число_tu, const char *путь_вывода, int релиз,
                       int библиотека, const char *вкл_каталог,
                       const char **доп_so, size_t число_so, int потоки,
                       const char *компилятор, int jemalloc, int символы,
                       int статический, int использует_embed,
                       int предупреждения_как_ошибки, const char *march_флаг,
                       const ФлагиСи *флаги_си);
