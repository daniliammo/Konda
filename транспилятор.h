// доп_so — пути к .so-библиотекам для линковки (безопасный путь 2); для каждой
// добавляется позиционный путь + «-Wl,-rpath,<абс. каталог>», чтобы .elf нашёл
// её при запуске. Может быть nullptr/0.
// «потоки» — программа использует «поток<T>»: добавить «-pthread».
// «компилятор» — имя бинаря компилятора (execvp по PATH): «cc» по умолчанию или
// «<триплет>-gcc» для кросс-сборки. «jemalloc» — линковать аллокатор jemalloc
// (`-l:libjemalloc.so.2`, интерпозиция malloc); только для исполняемых файлов
// (не .so — аллокатор выбирает финальная программа). «символы» — добавить
// -rdynamic/-funwind-tables/-g для читаемого бэктрейса (только размер, не
// скорость; 0 = «--без-символов», трейс останется, но адресами вместо имён).
// «предупреждения_как_ошибки» — защита clean-билда СГЕНЕРИРОВАННОГО кода: 1 (по
// умолчанию) добавляет к сборке выхода «-Werror» (любое предупреждение компилятора
// = ошибка). Классы, отражающие ОСОЗНАННЫЙ кодоген Konda (sign-compare — длина как
// целое32 vs беззнаковый счётчик; unused-* — язык допускает неиспользуемое), из
// -Werror исключены (-Wno-…): это не баги, а наши намеренные конструкции. Всё
// корректностно-значимое (format, format-security, implicit-decl, несовпадение
// указателей, uninitialized и т.п.) остаётся жёстким. 0 = «--разрешить-предупреждения»
// (предупреждения печатаются, но не роняют сборку) — escape-hatch для пользовательского
// C (свой printf-формат, намеренная рекурсия) там, где отказ нежелателен.
// march_флаг — готовая строка «-march=<...>» для целевого ISA-уровня (или nullptr/
// пусто, чтобы не задавать -march). Формируется в основа.c (разрешить_march).
// флаги_си (§129, может быть nullptr) — пользовательские флаги C: cflags («-I…»,
// «-D…», «--cflags» pkg-config) — в компиляцию (и в опрос заголовков), libs
// («--libs» pkg-config) — в линковку после источника/библиотек.
typedef struct {
    const char **cflags; size_t число_cflags;
    const char **libs;   size_t число_libs;
} ФлагиСи;

