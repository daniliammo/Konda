static int путь_без_расширения(const char *вход, char *выход, size_t cap)
{
    const char *слэш = strrchr(вход, '/');
    const char *имя = слэш ? слэш + 1 : вход;
    const char *точка = strrchr(имя, '.');
    size_t len = точка ? (size_t)(точка - имя) : strlen(имя);
    if (len + 1 >= cap) {
        return 0;
    }
    memcpy(выход, имя, len);
    выход[len] = '\0';
    return 1;
}

// Рекурсивно создать каталог (как «mkdir -p»). Нужен для вложенного вывода
// «--вывод=вывод/<триплет>» при кросс-сборке: родитель «вывод» может ещё не
// существовать, а при ПАРАЛЛЕЛЬНОЙ сборке целей (konda build -j) хост-цель и
// кросс-цель гонятся за созданием «вывод» — нерекурсивный mkdir вложенного пути
// падал с ENOENT (флейки-гонка). Возврат 0 — успех (или уже существует), -1 —
// ошибка. Промежуточные каталоги создаются по одному.
static int создать_каталог_рекурсивно(const char *путь)
{
    char буф[1024];
    size_t n = strlen(путь);
    if (n == 0 || n >= sizeof(буф)) return -1;
    memcpy(буф, путь, n + 1);
    for (char *p = буф + 1; *p; p++) {
        if (*p == '/') {
            *p = '\0';
            if (mkdir(буф, 0755) != 0 && errno != EEXIST) return -1;
            *p = '/';
        }
    }
    if (mkdir(буф, 0755) != 0 && errno != EEXIST) return -1;
    return 0;
}

// ─── главная программа ─────────────────────────────────────────────────────

static int существует(const char *путь)
{
    struct stat с;
    return stat(путь, &с) == 0;
}

// §88: записать буфер в файл ТОЛЬКО если содержимое отличается от уже лежащего
// (или файла нет). Возвращает 1 — файл записан (изменился/новый), 0 — не
// тронут (совпал байт-в-байт), −1 — ошибка записи. Так при раздельной
// компиляции неизменившийся .c сохраняет mtime и его .o не пересобирается.
static int записать_если_изменилось(const char *путь, const char *данные, size_t длина)
{
    FILE *ст = fopen(путь, "rb");
    if (ст) {
        int совпало = 0;
        struct stat s;
        if (fstat(fileno(ст), &s) == 0 && s.st_size >= 0
            && (size_t)s.st_size == длина) {
            совпало = 1;
            char буф[8192];
            size_t осталось = длина, смещ = 0, чит;
            while (совпало && осталось > 0
                   && (чит = fread(буф, 1, sizeof буф < осталось ? sizeof буф : осталось, ст)) > 0) {
                if (memcmp(буф, данные + смещ, чит) != 0) совпало = 0;
                смещ += чит; осталось -= чит;
            }
        }
        fclose(ст);
        if (совпало) return 0;  // не изменился — не переписываем (mtime цел)
    }
    FILE *f = fopen(путь, "wb");
    if (!f) return -1;
    if (длина > 0 && fwrite(данные, 1, длина, f) != длина) { fclose(f); return -1; }
    fclose(f);
    return 1;
}

// Каталог стандартной библиотеки: рядом с исполняемым файлом транспилятора
// («<каталог_бинарника>/../stdlib/вывод»), либо переменная окружения
// KONDA_STDLIB (абсолютный путь к «вывод»-каталогу stdlib). Возвращает
// указатель на буфер с путём или NULL, если stdlib не найдена.
static const char *каталог_стандартной_библиотеки(const char *argv0)
{
    static char путь[4096];
    const char *из_окружения = getenv("KONDA_STDLIB");
    if (из_окружения && из_окружения[0]) {
        if (strlen(из_окружения) >= sizeof(путь) - 16)
            fprintf(stderr, "Предупреждение: KONDA_STDLIB длиннее %zu байт — "
                    "путь усечён, stdlib может не найтись\n", sizeof(путь) - 16);
        snprintf(путь, sizeof(путь), "%.4080s", из_окружения);
        char проверка[4096];
        snprintf(проверка, sizeof(проверка), "%.4080s/libkonda_std.и", путь);
        if (существует(проверка)) return путь;
        fprintf(stderr, "Предупреждение: KONDA_STDLIB=%s не содержит libkonda_std.и\n",
                из_окружения);
    }
    // Реальный путь к исполняемому файлу: «argv[0]» может быть относительным
    // и не попадать в PATH; /proc/self/exe надёжен на Linux.
    char путь_бинарника[1024];
    {
        ssize_t н = readlink("/proc/self/exe", путь_бинарника, sizeof(путь_бинарника) - 1);
        if (н <= 0 && argv0 && argv0[0]) {
            // Fallback: каталог из argv[0] (или CWD).
            const char *слэш = strrchr(argv0, '/');
            if (слэш) {
                size_t дл = (size_t)(слэш - argv0);
                if (дл >= sizeof(путь_бинарника)) дл = sizeof(путь_бинарника) - 1;
                memcpy(путь_бинарника, argv0, дл);
                путь_бинарника[дл] = '\0';
                н = (ssize_t)дл;
            }
        }
        if (н <= 0) snprintf(путь_бинарника, sizeof(путь_бинарника), ".");
        if (н > 0) {
            путь_бинарника[н] = '\0';
            // /proc/self/exe — путь к ИСПОЛНЯЕМОМУ файлу; нам нужен каталог.
            char *слэш2 = strrchr(путь_бинарника, '/');
            if (слэш2) *слэш2 = '\0';
        }
    }
    // Бинарник обычно в «Собранное/» → stdlib в «../stdlib/вывод».
    char вариант[4096];
    snprintf(вариант, sizeof(вариант), "%.1000s/../stdlib/вывод", путь_бинарника);
    snprintf(путь, sizeof(путь), "%.4080s/libkonda_std.и", вариант);
    if (существует(путь)) {
        snprintf(путь, sizeof(путь), "%.4080s", вариант);
        return путь;
    }
    // Рядом же («Собранное/stdlib/вывод»).
    snprintf(вариант, sizeof(вариант), "%.1000s/stdlib/вывод", путь_бинарника);
    snprintf(путь, sizeof(путь), "%.4080s/libkonda_std.и", вариант);
    if (существует(путь)) {
        snprintf(путь, sizeof(путь), "%.4080s", вариант);
        return путь;
    }
    return NULL;
}

static void печатать_использование(const char *имя_программы)
{
    fprintf(stderr,
            "Использование: %s [--релиз] [--библиотека] <файл.конда> [файл.конда ...]\n"
            "  Несколько файлов: транспилируются как одна программа,\n"
            "  имя выходных файлов берётся от первого аргумента.\n \n"

            "  --код=<исходник> (--code, -e <исходник>): транслировать исходный код\n"
            "    прямо из аргумента, без файла (быстрые тесты — меньше I/O). Имя\n"
            "    вывода — «--имя=<имя>» (по умолчанию «код»); нельзя с файлами.\n \n"

            "  --релиз (--release): снять арифм. проверки (скорость уровня C);\n"
            "    по умолчанию — отладочная сборка со всеми проверками.\n \n"

            "  --библиотека (--lib): собрать .so + заголовок .h без точки входа.\n \n"

            "  --вывод=<путь> (--output): папка для выходных файлов (по умолчанию\n"
            "    «вывод» в текущем каталоге).\n \n"

            "  --только-си (--only-c): выдать только .c, не компилировать его.\n \n"

            "  --версия-проекта=<строка> (--project-version): версия собираемого\n"
            "    проекта — вшивается в ELF (символ КОНДА_ВЕРСИЯ + .note.konda +\n"
            "    .comment). Обычно задаётся системой сборки из Konda.toml.\n \n"

            "  --раздельно (--separate): разбить вывод на общий «<база>.общ.h» +\n"
            "    по одному .c на входной файл, скомпилировать их раздельно и\n"
            "    слинковать с LTO. Инкремент: правка одного .конда пересобирает\n"
            "    лишь его .o (межпроцедурный инлайн восстанавливает LTO). Ускоряет\n"
            "    пересборку большого многофайлового проекта.\n \n"

            "  --аллокатор=jemalloc|libc (--allocator): аллокатор исполняемого\n"
            "    файла (дефолт jemalloc; на кроссе по умолчанию libc).\n \n"

            "  --целевая-архитектура=<триплет> (--target-arch): кросс-сборка\n"
            "    через «<триплет>-gcc» (напр. aarch64-linux-gnu). Пока только gcc.\n \n"

            "  --march=<нативный|в1|в2|в3|в4|строка>: целевой ISA-уровень генерируемого\n"
            "    кода. По умолчанию в3 (x86-64-v3 / эквивалент; авто-векторизация, но\n"
            "    НЕ на старых CPU — печатается предупреждение). «нативный» — под этот CPU,\n"
            "    «в1» — базовая переносимость. Учитывает --целевая-архитектура (ARM/RISC-V).\n \n"

            "  --без-символов (--no-symbols): убрать -rdynamic/-g/unwind-таблицы\n"
            "    (меньше размер; бэктрейс останется, но кадры адресами, не именами).\n \n"

            "  --статический (--static): статическая линковка исполняемого файла\n"
            "    (нет зависимости от .so; для jemalloc нужен libjemalloc-dev).\n \n"

            "  --предупреждать-рекурсию (--warn-recursion): пометить нехвостовую\n"
            "    прямую/взаимную рекурсию (возможное переполнение стека).\n \n"

            "  --разрешить-предупреждения (--allow-warnings): не превращать\n"
            "    предупреждения компилятора в ошибки при сборке ВЫХОДА (по умолчанию\n"
            "    сгенерированный код собирается строго, -Werror). Escape-hatch для\n"
            "    пользовательского C, где предупреждение осознанно.\n \n"

            "  --без-стандартной-библиотеки (--no-stdlib): не подключать\n"
            "    стандартную библиотеку (stdlib/) автоматически; имена и функции\n"
            "    stdlib не видны, автолинковка .so не выполняется.\n \n"

            "  --version (-v): показать версию и выйти.\n",
            имя_программы);
}

// Коллизия собственных функций/вариантов программы с именами stdlib: если у
// пользователя есть своя «записать» или своё перечисление с вариантом
// «Успех»/«Провал» (как в stdlib), синтетический include «libkonda_std.h» дал бы
// конфликтующие C-объявления, а реконструированные типы — повторное
// объявление вариантов. Имена читаем из «.и» (строки «Ф имя …», «Вар имя»).
// Возвращает 1 при конфликте.
static int коллизия_со_стандартной_библиотекой(const Узел *корень,
                                                const char *каталог)
{
    char модули[32][128];
    int число_модулей = перечислить_модули_stdlib(каталог, модули, 32);
    for (int i = 0; i < число_модулей; ++i) {
        char путь_и[4300];
        snprintf(путь_и, sizeof(путь_и), "%.4200s/%s.и", каталог, модули[i]);
        size_t размер = 0;
        char *текст = прочитать_файл(путь_и, &размер);
        if (!текст) continue;
        int конфликт = 0;
        char *строки = текст;
        while (*строки && !конфликт) {
            char *конец = строки;
            while (*конец && *конец != '\n') конец++;
            int есть_перевод = (*конец == '\n');
            if (есть_перевод) *конец = '\0';
            const char *имя = NULL;
            if (strncmp(строки, "Ф ", 3) == 0) {              // «Ф » = 2+1 байт
                имя = строки + 3;                       // функция: «Ф имя»
            } else if (strncmp(строки, "Вар ", 7) == 0) {   // «Вар » = 3×2+1 байт
                имя = строки + 7;                       // вариант: «Вар имя»
            } else {
                имя = NULL;
            }
            if (имя) {
                // Имя — до первого пробела: у «Ф имя» появилось второе поле
                // (бит «возврат заимствован», §37 п.6), а «Вар имя» — без него.
                size_t дл = 0;
                while (имя[дл] && имя[дл] != ' ' && имя[дл] != '\t'
                       && имя[дл] != '\r') дл++;
                for (size_t k = 0; k < узел_число_детей(корень) && !конфликт; ++k) {
                    const Узел *ф = узел_ребёнок(корень, k);
                    if (!ф) continue;
                    if (ф->тип == УЗЕЛ_ФУНКЦИЯ && ф->токен.длина == дл &&
                        strncmp(ф->токен.начало, имя, дл) == 0) {
                        конфликт = 1;
                        break;
                    }
                    if (ф->тип != УЗЕЛ_ПЕРЕЧИСЛЕНИЕ) continue;
                    for (size_t v = 0; v < узел_число_детей(ф); ++v) {
                        const Узел *вар = узел_ребёнок(ф, v);
                        if (вар && вар->тип == УЗЕЛ_ВАРИАНТ &&
                            вар->токен.длина == дл &&
                            strncmp(вар->токен.начало, имя, дл) == 0) {
                            конфликт = 1;
                            break;
                        }
                    }
                }
            }
            if (!есть_перевод) break;
            строки = конец + 1;
        }
        free(текст);
        if (конфликт) return 1;
    }
    return 0;
}

int main(int количество_аргументов, char **аргументы)
{
    // --version/-v обрабатывается раньше проверки числа аргументов: должно
    // работать само по себе, без файла.
    for (int i = 1; i < количество_аргументов; ++i) {
        if (strcmp(аргументы[i], "--version") == 0 || strcmp(аргументы[i], "-v") == 0) {
            printf("Konda: язык %s, транспилятор %s\n",
                   ВЕРСИЯ_ЯЗЫКА, ВЕРСИЯ_ТРАНСПИЛЯТОРА);
            return 0;
        }
    }

    if (количество_аргументов < 2) {
        печатать_использование(аргументы[0]);
        return 2;
    }

    // Разбор флагов: --релиз/--release включает релизную сборку; --библиотека/
    // --lib собирает разделяемую библиотеку (.so) с заголовком (.h) вместо
    // исполняемого файла. Остальные аргументы — входные файлы .конда (порядок
    // сохраняется, имя выхода — от первого файла). Аргумент, начинающийся с
    // «--», но не совпавший ни с одним известным флагом, — вероятная опечатка:
    // отклоняем понятной ошибкой, а не пытаемся прочитать его как имя файла
    // (иначе пользователь получает малопонятное «No such file or directory»).
    int релиз = 0;
    int библиотека = 0;
    int только_си = 0;               // --только-си: выдать .c, не компилировать
    const char *триплет = nullptr;   // --целевая-архитектура=<триплет> (кросс)
    const char *march_уровень = nullptr; // --march=<нативный|в1..в4|строка>: целевой
                                     // ISA-уровень. nullptr → дефолт «в3» (с
                                     // обязательным предупреждением о старых CPU).
    int march_задан = 0;             // пользователь указал --march явно (гасит
                                     // предупреждение о дефолтном в3)
    int аллокатор_jemalloc = 1;      // дефолт jemalloc (см. --аллокатор)
    int аллокатор_задан = 0;         // пользователь указал --аллокатор явно
    int символы = 1;                 // --без-символов: убрать -rdynamic/-g/unwind-
                                     // таблицы (бэктрейс останется, но адресами)
    int статический = 0;             // --статический: статическая линковка
    int разрешить_предупреждения = 0; // --разрешить-предупреждения: снять -Werror
                                     // со сборки выхода (escape-hatch: предупреждения
                                     // печатаются, но не роняют сборку). По умолчанию
                                     // выкл → сгенерированный код собирается clean.
    int предупреждать_рекурсию = 0;  // --предупреждать-рекурсию: пометить нехвост.
                                     // прямую/взаимную рекурсию (возможный overflow)
    int стандартная_библиотека = 1; // --без-стандартной-библиотеки: не подключать
                                     // stdlib автоматически (имена/функции/автолинк)
    const char *папка_вывода = "вывод";  // --вывод=<путь>: каталог для .c/.elf/.so/.h/.и
    const char *инлайн_код = nullptr;    // --код=<исходник>: исходник строкой-аргументом
    const char *инлайн_имя = "код";      // --имя=<имя>: базовое имя вывода (--код И
                                         // файловый режим: переопределяет имя от
                                         // первого файла — нужно для монолита stdlib).
    int имя_задан = 0;                   // пользователь указал --имя явно
    const char *версия_проекта = nullptr; // --версия-проекта=<строка>: версия
                                         // собираемого проекта (обычно из
                                         // Konda.toml через konda build). Идёт в
                                         // штамп ELF (символ КОНДА_ВЕРСИЯ +
                                         // .note.konda + .comment).
    int раздельно = 0;                   // --раздельно: разбить вывод на общий .h +
                                         // по одному .c на файл (§88). Включает LTO
                                         // и инкрементальную сборку (.c/.o только
                                         // для изменившихся файлов).
    const char **входные = calloc((size_t)количество_аргументов, sizeof(*входные));
    if (!входные) {
        fprintf(stderr, "Нет памяти под список файлов\n");
        return 1;
    }
    ТаблицаМакросов макросы;
    макросы_инициализировать(&макросы);
    size_t число_файлов = 0;
    for (int i = 1; i < количество_аргументов; ++i) {
        const char *арг = аргументы[i];
        if (strcmp(арг, "--релиз") == 0 || strcmp(арг, "--release") == 0) {
            релиз = 1;
        } else if (strcmp(арг, "--дебаг") == 0 || strcmp(арг, "--debug") == 0) {
            релиз = 0;
        } else if (strcmp(арг, "--библиотека") == 0 || strcmp(арг, "--lib") == 0
                   || strcmp(арг, "--library") == 0) {
            библиотека = 1;
        } else if (strcmp(арг, "--только-си") == 0 || strcmp(арг, "--only-c") == 0) {
            только_си = 1;
        } else if (strcmp(арг, "--без-символов") == 0 || strcmp(арг, "--no-symbols") == 0) {
            символы = 0;
        } else if (strcmp(арг, "--без-стандартной-библиотеки") == 0
                   || strcmp(арг, "--no-stdlib") == 0) {
            стандартная_библиотека = 0;
        } else if (strcmp(арг, "--статический") == 0 || strcmp(арг, "--static") == 0) {
            статический = 1;
        } else if (strcmp(арг, "--раздельно") == 0 || strcmp(арг, "--separate") == 0) {
            раздельно = 1;
        } else if (strcmp(арг, "--разрешить-предупреждения") == 0
                   || strcmp(арг, "--allow-warnings") == 0) {
            разрешить_предупреждения = 1;
        } else if (strcmp(арг, "--предупреждать-рекурсию") == 0
                   || strcmp(арг, "--warn-recursion") == 0) {
            предупреждать_рекурсию = 1;
        } else if (strncmp(арг, "--целевая-архитектура=", strlen("--целевая-архитектура=")) == 0) {
            триплет = арг + strlen("--целевая-архитектура=");
        } else if (strncmp(арг, "--target-arch=", strlen("--target-arch=")) == 0) {
            триплет = арг + strlen("--target-arch=");
        } else if (strncmp(арг, "--march=", strlen("--march=")) == 0) {
            // Целевой ISA-уровень для генерируемого кода: нативный|в1..в4 (x86-64-vN
            // и эквиваленты на ARM/RISC-V) либо явная строка для «cc -march=».
            march_уровень = арг + strlen("--march=");
            march_задан = 1;
        } else if (strcmp(арг, "--march") == 0) {
            if (i + 1 >= количество_аргументов) {
                fprintf(stderr, "«--march» ожидает значение следующим аргументом "
                                "(нативный|в1|в2|в3|в4|<строка>)\n");
                free(входные);
                return 2;
            }
            march_уровень = аргументы[++i];
            march_задан = 1;
        } else if (strncmp(арг, "--аллокатор=", strlen("--аллокатор=")) == 0
                   || strncmp(арг, "--allocator=", strlen("--allocator=")) == 0) {
            const char *знач = strchr(арг, '=') + 1;
            if (strcmp(знач, "jemalloc") == 0) {
                аллокатор_jemalloc = 1;
            } else if (strcmp(знач, "libc") == 0) {
                аллокатор_jemalloc = 0;
            } else {
                fprintf(stderr, "Неизвестный аллокатор «%s» (ожидалось jemalloc|libc)\n", знач);
                free(входные);
                return 2;
            }
            аллокатор_задан = 1;
        } else if (арг[0] == '-' && арг[1] == 'D') {
            // Определить макрос: «-DИМЯ», «-DИМЯ=знач» или «-D ИМЯ».
            const char *деф = арг + 2;
            if (*деф == '\0' && i + 1 < количество_аргументов) деф = аргументы[++i];
            if (*деф == '\0' || !макросы_определить_аргумент(&макросы, деф)) {
                fprintf(stderr, "Неверный «-D»: ожидалось ИМЯ или ИМЯ=значение\n");
                free(входные);
                return 2;
            }
        } else if (strncmp(арг, "--версия-проекта=", strlen("--версия-проекта=")) == 0) {
            версия_проекта = арг + strlen("--версия-проекта=");
        } else if (strncmp(арг, "--project-version=", strlen("--project-version=")) == 0) {
            версия_проекта = арг + strlen("--project-version=");
        } else if (strncmp(арг, "--вывод=", strlen("--вывод=")) == 0
                   || strncmp(арг, "--output=", strlen("--output=")) == 0) {
            папка_вывода = strchr(арг, '=') + 1;
        } else if (strncmp(арг, "--код=", strlen("--код=")) == 0
                   || strncmp(арг, "--code=", strlen("--code=")) == 0) {
            // Исходник строкой-аргументом (без временного файла): --код=<текст>.
            инлайн_код = strchr(арг, '=') + 1;
        } else if (strcmp(арг, "--код") == 0 || strcmp(арг, "--code") == 0
                   || strcmp(арг, "-e") == 0) {
            // Пробельная форма: --код <текст> / -e <текст> (следующий аргумент).
            if (i + 1 >= количество_аргументов) {
                fprintf(stderr, "«%s» ожидает исходный код следующим аргументом\n", арг);
                free(входные);
                return 2;
            }
            инлайн_код = аргументы[++i];
        } else if (strncmp(арг, "--имя=", strlen("--имя=")) == 0
                   || strncmp(арг, "--name=", strlen("--name=")) == 0) {
            // Базовое имя вывода (по умолчанию «код» для --код): вывод/<имя>.c и т.д.
            // В файловом режиме переопределяет имя от первого файла.
            инлайн_имя = strchr(арг, '=') + 1;
            имя_задан = 1;
        } else if (арг[0] == '-' && арг[1] == '-') {
            fprintf(stderr, "Неизвестный флаг: %s\n", арг);
            печатать_использование(аргументы[0]);
            free(входные);
            return 2;
        } else {
            входные[число_файлов++] = арг;
        }
    }
    // Исходник строкой-аргументом (--код): синтетический единственный «файл».
    // Имя вывода — из --имя (по умолчанию «код»); каталог базы — «.». Смешивать
    // с файловыми входами нельзя (неоднозначно, чем является программа).
    if (инлайн_код) {
        if (число_файлов > 0) {
            fprintf(stderr, "«--код» нельзя сочетать с файлами .конда "
                            "(укажите либо исходник строкой, либо файлы)\n");
            free(входные);
            return 2;
        }
        входные[число_файлов++] = инлайн_имя;  // служит и базой имени вывода
    }
    if (число_файлов == 0) {
        fprintf(stderr, "Не указан ни один файл .конда (или передайте «--код=<исходник>»)\n");
        free(входные);
        return 2;
    }

    // Предопределённые макросы для «#если …»: режим сборки (дебаг/релиз) и
    // платформа (ОС/архитектура/разрядность). Задаём ПОСЛЕ разбора аргументов
    // (нужны «релиз» и «триплет») и ДО «условная_компиляция». Явный «-D»
    // пользователя (уже в таблице) побеждает — предопределённые не перезаписывают.
    макросы_предопределить(&макросы, релиз, триплет);

    // Источники, токены и AST-корни каждого файла живут до конца кодогена:
    // токены и узлы держат указатели в исходные буферы (Токен.начало).
    char            **источники = calloc(число_файлов, sizeof(*источники));
    size_t           *длины_ист = calloc(число_файлов, sizeof(*длины_ист));
    МассивТокенов   *токены    = calloc(число_файлов, sizeof(*токены));
    Узел            **корни    = calloc(число_файлов, sizeof(*корни));
    if (!источники || !длины_ист || !токены || !корни) {
        fprintf(stderr, "Нет памяти под массивы файлов\n");
        free(источники); free(длины_ист); free(токены); free(корни); free(входные);
        return 1;
    }

    int код = 0;
    // Объявлено до первых goto очистка (nullptr-безопасно): живёт до линковки,
    // освобождается в «очистка». Хранит сигнатуры библиотек и пути их .so.
    ТаблицаИнтерфейса *интерфейсы = nullptr;
    // §101: захваченные исходники обобщённых шаблонов для дописи в «.и» (режим
    // библиотеки). Объявлено здесь — до первых goto очистка (там и освобождается).
    char *шаблоны_и = nullptr;

    // ── чтение + токенизация каждого файла ─────────────────────────────────
    for (size_t i = 0; i < число_файлов; ++i) {
        const char *путь = входные[i];
        size_t размер;
        if (инлайн_код && i == 0) {
            // Исходник уже в памяти (--код): копируем в собственный буфер (токены
            // держат указатели внутрь него; освобождается как источник в «очистка»).
            размер = strlen(инлайн_код);
            источники[i] = malloc(размер + 1);
            if (источники[i]) memcpy(источники[i], инлайн_код, размер + 1);
        } else {
            источники[i] = прочитать_файл((char *)путь, &размер);
        }
        if (!источники[i]) {
            fprintf(stderr, "Не удалось прочитать %s\n", путь);
            код = 1;
            goto очистка;
        }
        длины_ист[i] = размер;  // §88: границы буфера-источника для приписки тел
        токены[i] = токенизировать_код(размер, источники[i], 0);
        // Условная компиляция (#if/#ifdef/#ifndef/#else/#elif/#endif/#define):
        // фильтрует токены неактивных веток до разбора. Общая таблица макросов —
        // «#define» из ранних файлов видны в поздних (как единый проект).
        Диагностика мдиаг = {0};
        if (!условная_компиляция(&токены[i], &макросы, &мдиаг)) {
            печать_диагностики(0, путь, источники[i],
                               мдиаг.строка, мдиаг.колонка, мдиаг.сообщение);
            код = 1;
            goto очистка;
        }
    }

    // ── signature-pass для имён структур и перечислений: позволяет парсеру
    // файла X знать о структурах/перечислениях, объявленных в файле Y.
    // Семантика и так делает свой signature-pass для функций; для парсера
    // структуры/перечисления — частный случай из-за неоднозначности
    // «Имя п» vs обычный идентификатор.
    ИменаСтруктур *структуры_всех = имена_структур_создать();
    ИменаПеречислений *перечисления_всех = имена_перечислений_создать();
    ИменаОбобщённых *обобщённые_всех = имена_обобщённых_создать();
    // §90: квалифицированные имена функций-пространств из «.и» библиотек (набор —
    // строковый, повторно используем ИменаСтруктур). Заполняется ниже из
    // локальных «#содержит» и передаётся парсеру для разбора «Имя::член(…)».
    ИменаСтруктур *функции_пр_всех = имена_структур_создать();
    for (size_t i = 0; i < число_файлов; ++i) {
        собрать_имена_структур(&токены[i], структуры_всех);
        собрать_имена_перечислений(&токены[i], перечисления_всех);
        собрать_имена_обобщённых(&токены[i], обобщённые_всех);  // cross-file generics
    }

    // Каталог для «локальных.h» берём от первого входного файла. Нужен уже
    // здесь — имена типов из «.и» библиотек должны попасть в парсер.
    char база_каталог[256];
    {
        const char *слэш = strrchr(входные[0], '/');
        if (слэш) {
            size_t n = (size_t)(слэш - входные[0]);
            if (n >= sizeof(база_каталог)) n = sizeof(база_каталог) - 1;
            memcpy(база_каталог, входные[0], n);
            база_каталог[n] = '\0';
        } else {
            snprintf(база_каталог, sizeof(база_каталог), ".");
        }
    }
    // Библиотечные типы из «.и» — в списки имён ДО разбора: иначе «Имя п = …»
    // для структуры/перечисления библиотеки не распознаётся парсером как
    // объявление (узлы реконструируются только в собрать_интерфейсы, позже).
    for (size_t i = 0; i < число_файлов; ++i) {
        собрать_имена_типов_интерфейсов(&токены[i], база_каталог,
                                         структуры_всех, перечисления_всех);
        собрать_имена_функций_пр_интерфейсов(&токены[i], база_каталог,
                                              функции_пр_всех);  // §90
        // §101: имена обобщённых шаблонов из «.и» библиотек — чтобы
        // «Пара<символ> x» / «макс<символ>(…)» с шаблоном из библиотеки
        // распознавались парсером как инстанцирование, а не сравнение «<».
        собрать_имена_обобщённых_интерфейсов(&токены[i], база_каталог,
                                              обобщённые_всех);
    }

    // Стандартная библиотека (stdlib): имена её типов так же должны попасть
    // в парсер до разбора — пользователь не пишет «#содержит "libkonda_std.h"».
    const char *каталог_stdlib = NULL;
    if (стандартная_библиотека) {
        каталог_stdlib = каталог_стандартной_библиотеки(аргументы[0]);
        if (каталог_stdlib)
            собрать_имена_типов_из_каталога(каталог_stdlib,
                                             структуры_всех, перечисления_всех);
    }

    // ── разбор каждого файла с общим списком структур и перечислений ───────
    // Батч-режим парсера: как и семантика, разбор собирает ВСЕ синтаксические
    // ошибки файла за прогон (восстановление на границе верхнего уровня) —
    // IDE и циклы автоисправления видят весь список сразу.
    for (size_t i = 0; i < число_файлов; ++i) {
        const char *путь = входные[i];
        Диагностика диаг = {0};
        ДинМассив синт_ошибки;
        дин_массив_инициализировать(&синт_ошибки, sizeof(Диагностика));
        корни[i] = разобрать_с_именами_структур_обобщённых_батч(&токены[i], &диаг,
                                                  структуры_всех, перечисления_всех,
                                                  обобщённые_всех, функции_пр_всех,
                                                  &синт_ошибки);
        if (!корни[i]) {
            for (size_t j = 0; j < синт_ошибки.длина; ++j) {
                Диагностика *д = дин_массив_получить(&синт_ошибки, j);
                печать_диагностики(0, путь, источники[i],
                                   д->строка, д->колонка, д->сообщение);
            }
            if (синт_ошибки.длина == 0) {
                печать_диагностики(0, путь, источники[i],
                                   диаг.строка, диаг.колонка, диаг.сообщение);
            }
            if (синт_ошибки.длина > 1) {
                fprintf(stderr, "Всего ошибок: %zu\n", синт_ошибки.длина);
            }
            дин_массив_освободить(&синт_ошибки);
            имена_структур_освободить(структуры_всех);
            имена_перечислений_освободить(перечисления_всех);
            имена_обобщённых_освободить(обобщённые_всех);
            имена_структур_освободить(функции_пр_всех);
            код = 1;
            goto очистка;
        }
        дин_массив_освободить(&синт_ошибки);
    }
    имена_структур_освободить(структуры_всех);
    имена_перечислений_освободить(перечисления_всех);
    имена_обобщённых_освободить(обобщённые_всех);
    имена_структур_освободить(функции_пр_всех);

    // ── слияние и общий проход семантики + кодогена ───────────────────────
    Узел *общий = слить_программы(корни, число_файлов);
    // Использует ли программа «поток<T>» → нужен «-pthread» при вызове cc.
    // Снимаем признак до освобождения дерева (см. ниже).
    int нужен_pthread = 0;

    // Вывод тип-аргументов (гибрид): до мономорфизации типизируем аргументы
    // обобщённых вызовов и дописываем выведенные «<>» туда, где T следует из
    // конкретных аргументов («макс(1, 2)» ≡ «макс<целое32>(1, 2)»). Best-effort,
    // диагностики подавлены — реальные ошибки даст семантика ниже. Внешние/
    // интерфейсные таблицы ещё не построены (nullptr) — вывод опирается на типы
    // Konda-аргументов; результат вызова библиотеки как аргумент → нужны явные «<>».
    вывести_типоаргументы(общий, nullptr, nullptr);

    // Konda-интерфейсы библиотек (безопасный путь 2): для каждого локального
    // «#содержит "либа.h"» подгружаем соседний «либа.и» — вызовы к функциям
    // библиотеки проверяются по типам и владению, а не как непрозрачный C.
    // §101: собираем ДО мономорфизации — конкретные типы библиотеки (из_библиотеки)
    // должны быть в дереве, чтобы мономорфизация ДЕДУПлицировала специализацию-
    // структуру, которую потребитель инстанцирует и которую библиотека уже
    // экспортировала (иначе двойной typedef: свой + из «.h» библиотеки).
    интерфейсы = интерфейс_создать();
    if (интерфейсы) собрать_интерфейсы(общий, база_каталог, интерфейсы);

    // §101: внедрить исходники обобщённых ШАБЛОНОВ библиотек (из «.и») в дерево —
    // тоже ДО мономорфизации, чтобы она развернула нужную потребителю специализацию
    // локально (header-only). Тело обобщённой функции полевой сериализацией «.и»
    // непередаваемо → библиотека вложила дословный исходник, здесь он переразбирается.
    внедрить_шаблоны_библиотек(общий, база_каталог);

    // §101: при сборке библиотеки — захватить исходники обобщённых ШАБЛОНОВ ДО
    // мономорфизации (она их удалит из дерева). Допишем эти записи в «.и» после
    // эмиссии концевой части интерфейса (см. эмит_интерфейс ниже).
    шаблоны_и = библиотека ? эмит_шаблоны_в_строку(общий) : nullptr;

    // Мономорфизация обобщённых функций/структур: шаблоны «имя<T>(…)»/«Тип<T>»
    // разворачиваются в конкретные специализации ещё до семантики (та работает
    // с полностью конкретным деревом). Ошибки — арность/неизвестный шаблон.
    {
        Диагностика диаг_g = {0};
        if (!мономорфизировать(общий, &диаг_g)) {
            печать_диагностики(0,
                    число_файлов == 1 ? входные[0] : nullptr,
                    число_файлов == 1 ? источники[0] : nullptr,
                    диаг_g.строка, диаг_g.колонка, диаг_g.сообщение);
            // Признак потоков снимаем ДО освобождения дерева: линковка ниже читать
    // «общий» уже не может (это было бы use-after-free).
    нужен_pthread = программа_использует_потоки(общий);
    освободить_узел(общий);
            код = 1;
            goto очистка;
        }
    }

    // Внешние функции из подключённых заголовков: транспилятор «видит» libc и
    // прочие библиотеки, чтобы диагностировать неизвестные вызовы на уровне
    // Konda (с позицией в .конда), а не перекладывать всё на cc.
    ТаблицаВнешних *внешние = внешние_создать();
    if (внешние) собрать_внешние_функции(общий, база_каталог, внешние);

    // Стандартная библиотека — автоподключение: функции+типы+автолинк .so
    // (пользователь «#содержит» для неё не пишет). Только для программ, не
    // при сборке самой stdlib в режиме --библиотека (libkonda_std.и она породила сама).
    // При --статический не подключаем: libkonda_std.so — разделяемый, статически не
    // линкуется (пользователь увидит обычную ошибку «функция не объявлена»,
    // если вызовет stdlib-функцию).
    if (интерфейсы && стандартная_библиотека && !библиотека && !статический) {
        // Если в программе уже есть «#содержит "X.h"» (локальный заголовок,
// пользовательские .h/.и), синтетический include stdlib не вводим: его
        // typedef конфликтовал бы с typedef из собственного заголовка при
        // совпадении имён типов. Системные «<X.h>» (stdio и т.п.) этому не
        // мешают — локальность определяется по кавычкам «"…"».
        int есть_пользовательские_содержит = 0;
        for (size_t i = 0; i < узел_число_детей(общий); ++i) {
            const Узел *пр = узел_ребёнок(общий, i);
            if (!пр || пр->тип != УЗЕЛ_ПРЕПРОЦЕССОР) continue;
            if (memchr(пр->токен.начало, '"', пр->токен.длина)) {
                есть_пользовательские_содержит = 1;
                break;
            }
        }
        // Коллизия имён (собственная «записать»/вариант «Успех» vs stdlib): stdlib не
        // подключаем вовсе — иначе C-объявления из синтетического include
        // столкнутся с кодом программы, а типы — с её перечислениями. Явное
        // предупреждение с решением.
        int коллизия_имён = коллизия_со_стандартной_библиотекой(общий, каталог_stdlib);
        if (коллизия_имён) {
            fprintf(stderr,
                    "Предупреждение: стандартная библиотека не подключена — имя "
                    "её функции занято вашей функцией; переименуйте её или "
                    "подключайте stdlib явно: #содержит \"%.4060s/libkonda_std.h\"\n",
                    каталог_stdlib);
        }
        // Определения C-типов stdlib (typedef структуры/перечисления) приходят
        // из «X.h» КАЖДОГО модуля — у пользователя нет «#содержит», вводим их
        // синтетически по одному на модуль (кодоген напечатает #include с
        // абсолютным путём). Только когда пользовательских «#содержит» нет вовсе
        // и нет коллизии имён функций. Модули берём сканом каталога stdlib.
        if (!есть_пользовательские_содержит && !коллизия_имён) {
        if (каталог_stdlib && strlen(каталог_stdlib) > 4060)
            fprintf(stderr, "Предупреждение: путь к stdlib длиннее 4060 байт — "
                    "усечён; синтетический #содержит может не собраться\n");
        char модули[32][128];
        int число_модулей = перечислить_модули_stdlib(каталог_stdlib, модули, 32);
        for (int i = 0; i < число_модулей; ++i) {
            char синтетический_h[8192];
            snprintf(синтетический_h, sizeof(синтетический_h),
                     "#содержит \"%.4060s/%s.h\"", каталог_stdlib, модули[i]);
            Узел *узел_h = узел_создать(УЗЕЛ_ПРЕПРОЦЕССОР);
            if (!узел_h) continue;
            // Токен указывает на heap-буфер (живёт до конца процесса; узел
            // освобождается с деревом, но токен — только указатель). Утечка
            // намеренна: один-shot процесс вскоре завершится.
            char *буфер_включения = strdup(синтетический_h);
            if (буфер_включения) {
                узел_h->токен.начало = буфер_включения;
                узел_h->токен.длина = strlen(буфер_включения);
                узел_добавить_ребёнка(общий, узел_h);
            } else {
                free(узел_h);
            }
        }
        собрать_интерфейсы_из_каталога(общий, каталог_stdlib, интерфейсы);
        }
    }

    // Батч-режим: собираем ВСЕ ошибки за один проход (чтобы показать их сразу,
    // а не по одной за пересборку) и предупреждения.
    ДинМассив предупреждения, ошибки;
    дин_массив_инициализировать(&предупреждения, sizeof(Диагностика));
    дин_массив_инициализировать(&ошибки, sizeof(Диагностика));
    Диагностика диаг = {0};
    int семантика_ок = анализировать_полный_и(общий, &диаг, внешние, интерфейсы,
                                              &предупреждения, &ошибки);

    // Опциональная диагностика нехвостовой рекурсии (по флагу): добавляет свои
    // предупреждения в общий список — печатаются тем же путём ниже. Только при
    // успешном анализе (иначе дерево могло не достроиться).
    if (предупреждать_рекурсию && семантика_ок)
        предупредить_о_нехвостовой_рекурсии(общий, &предупреждения);

    // Предупреждения (не фатальные, напр. вызов необъявленной функции) — в
    // stderr, но сборку не прерывают.
    const char *ист_путь = число_файлов == 1 ? входные[0] : nullptr;
    const char *ист_текст = число_файлов == 1 ? источники[0] : nullptr;
    for (size_t i = 0; i < предупреждения.длина; ++i) {
        Диагностика *п = дин_массив_получить(&предупреждения, i);
        печать_диагностики(1, ист_путь, ист_текст,
                           п->строка, п->колонка, п->сообщение);
    }
    // Все ошибки — в stderr (не только первая).
    for (size_t i = 0; i < ошибки.длина; ++i) {
        Диагностика *о = дин_массив_получить(&ошибки, i);
        печать_диагностики(0, ист_путь, ист_текст,
                           о->строка, о->колонка, о->сообщение);
    }
    if (ошибки.длина > 0)
        fprintf(stderr, "Всего ошибок: %zu\n", ошибки.длина);
    дин_массив_освободить(&предупреждения);
    дин_массив_освободить(&ошибки);
    внешние_освободить(внешние);

    if (!семантика_ок) {
        // Признак потоков снимаем ДО освобождения дерева: линковка ниже читать
    // «общий» уже не может (это было бы use-after-free).
    нужен_pthread = программа_использует_потоки(общий);
    освободить_узел(общий);
        код = 1;
        goto очистка;
    }

    // Исполняемому файлу нужна «точка_входа» (main); библиотеке — нет. Раньше
    // при её отсутствии ошибку впервые видел линкер («undefined reference to
    // `main'») — сырое сообщение от cc вместо диагностики уровня Konda.
    if (!библиотека) {
        int есть_точка_входа = 0;
        for (size_t i = 0; i < узел_число_детей(общий); ++i) {
            Узел *ф = узел_ребёнок(общий, i);
            if (ф->тип == УЗЕЛ_ФУНКЦИЯ && ф->это_main) { есть_точка_входа = 1; break; }
        }
        if (!есть_точка_входа) {
            fprintf(stderr,
                    "Ошибка: в программе нет «точка_входа» — исполняемому файлу "
                    "нужна функция «целое32 точка_входа(...)». Если это "
                    "библиотека функций без точки входа, используйте флаг "
                    "--библиотека.\n");
            // Признак потоков снимаем ДО освобождения дерева: линковка ниже читать
    // «общий» уже не может (это было бы use-after-free).
    нужен_pthread = программа_использует_потоки(общий);
    освободить_узел(общий);
            код = 1;
            goto очистка;
        }
    }

    // ── §88 Раздельная компиляция: общий .h + по одному .c на файл ──────────
    // Целостный анализ уже завершён (Модель B); здесь только разбиваем ВЫВОД и
    // компилируем инкрементально. Библиотечный .h/.и по-прежнему монолитны.
    if (раздельно) {
        // База имени (как в монолите: --имя, иначе от первого файла).
        char база_р[256];
        if (имя_задан && !инлайн_код) {
            snprintf(база_р, sizeof(база_р), "%s", инлайн_имя);
        } else if (!путь_без_расширения(входные[0], база_р, sizeof(база_р))) {
            fprintf(stderr, "Слишком длинное имя файла\n");
            нужен_pthread = программа_использует_потоки(общий);
            освободить_узел(общий);
            код = 1; goto очистка;
        }
        if (создать_каталог_рекурсивно(папка_вывода) != 0) {
            fprintf(stderr, "Не удалось создать папку %s\n", папка_вывода);
            нужен_pthread = программа_использует_потоки(общий);
            освободить_узел(общий);
            код = 1; goto очистка;
        }

        // Базовые имена TU по файлам-источникам (для стабильных .c/.o между
        // сборками → корректный инкремент). Коллизия одинаковых basename в разных
        // каталогах разводится суффиксом «_<i>».
        char (*туимена)[256] = calloc(число_файлов, sizeof(*туимена));
        БуферКода *телабуф = calloc(число_файлов, sizeof(*телабуф));
        БуферКода **телаптр = calloc(число_файлов, sizeof(*телаптр));
        const char **начала = calloc(число_файлов, sizeof(*начала));
        const char **концы  = calloc(число_файлов, sizeof(*концы));
        if (!туимена || !телабуф || !телаптр || !начала || !концы) {
            fprintf(stderr, "Нет памяти под раздельную сборку\n");
            free(туимена); free(телабуф); free(телаптр); free(начала); free(концы);
            нужен_pthread = программа_использует_потоки(общий);
            освободить_узел(общий);
            код = 1; goto очистка;
        }
        for (size_t i = 0; i < число_файлов; ++i) {
            char имя_i[256];
            if (!путь_без_расширения(входные[i], имя_i, sizeof(имя_i)))
                snprintf(имя_i, sizeof(имя_i), "файл%zu", i);
            int дубль = 0;
            for (size_t j = 0; j < i; ++j)
                if (strcmp(туимена[j], имя_i) == 0) { дубль = 1; break; }
            if (дубль) snprintf(туимена[i], sizeof(туимена[i]), "%s_%zu", имя_i, i);
            else       snprintf(туимена[i], sizeof(туимена[i]), "%s", имя_i);
            начала[i] = источники[i];
            концы[i]  = источники[i] + длины_ист[i];
            буфер_кода_инициализировать(&телабуф[i]);
            телаптр[i] = &телабуф[i];
        }

        char имя_h[300];
        snprintf(имя_h, sizeof(имя_h), "%s.общ.h", база_р);

        БуферКода буфер_hр;
        буфер_кода_инициализировать(&буфер_hр);
        кодоген_раздельно(общий, &буфер_hр, телаптр, начала, концы,
                          число_файлов, имя_h, релиз, интерфейсы, версия_проекта);

        // Библиотечные .h/.и — из того же дерева, монолитно (как прежде).
        БуферКода буфер_hлиб, буфер_иР;
        буфер_кода_инициализировать(&буфер_hлиб);
        буфер_кода_инициализировать(&буфер_иР);
        if (библиотека) {
            кодоген_заголовок(общий, &буфер_hлиб);
            эмит_интерфейс(общий, &буфер_иР);
            if (шаблоны_и) буфер_кода_добавить(&буфер_иР, шаблоны_и);  // §101
        }

        нужен_pthread = программа_использует_потоки(общий);
        int использует_embed_р = программа_использует_встроить(общий);
        освободить_узел(общий);

        // Записываем общий .h; при его изменении ВСЕ TU пересобираются.
        char путь_h_общ[512];
        snprintf(путь_h_общ, sizeof(путь_h_общ), "%s/%s", папка_вывода, имя_h);
        const char *h_стр = буфер_кода_строка(&буфер_hр);
        size_t h_дл = буфер_hр.базовый.длина > 0 ? буфер_hр.базовый.длина - 1 : 0;
        int заголовок_изменился = записать_если_изменилось(путь_h_общ, h_стр, h_дл);
        буфер_кода_освободить(&буфер_hр);
        if (заголовок_изменился < 0) {
            fprintf(stderr, "Не удалось записать %s\n", путь_h_общ);
            буфер_кода_освободить(&буфер_hлиб); буфер_кода_освободить(&буфер_иР);
            for (size_t i = 0; i < число_файлов; ++i) буфер_кода_освободить(&телабуф[i]);
            free(туимена); free(телабуф); free(телаптр); free(начала); free(концы);
            код = 1; goto очистка;
        }
        printf("%s %s (%zu байт)\n", заголовок_изменился ? "Записан" : "Без изменений",
               путь_h_общ, h_дл);

        // Каждый TU .c — only-if-changed; собираем пути и флаги «изменился».
        char (*пути_c)[512] = calloc(число_файлов, sizeof(*пути_c));
        int *изменился = calloc(число_файлов, sizeof(*изменился));
        int ошибка_записи = 0;
        for (size_t i = 0; пути_c && изменился && i < число_файлов; ++i) {
            snprintf(пути_c[i], sizeof(пути_c[i]), "%s/%s.c", папка_вывода, туимена[i]);
            const char *ст = буфер_кода_строка(&телабуф[i]);
            size_t дл = телабуф[i].базовый.длина > 0 ? телабуф[i].базовый.длина - 1 : 0;
            int изм = записать_если_изменилось(пути_c[i], ст, дл);
            if (изм < 0) { ошибка_записи = 1; break; }
            // Заголовок общий изменился → форсируем пересборку каждого TU.
            изменился[i] = изм || заголовок_изменился;
            printf("%s %s (%zu байт)\n", изм ? "Записан" : "Без изменений",
                   пути_c[i], дл);
            буфер_кода_освободить(&телабуф[i]);
        }

        // Библиотечные .h/.и рядом (монолитно, only-if-changed).
        if (библиотека && !ошибка_записи) {
            char путь_hл[512], путь_ил[512];
            snprintf(путь_hл, sizeof(путь_hл), "%s/%s.h", папка_вывода, база_р);
            snprintf(путь_ил, sizeof(путь_ил), "%s/%s.и", папка_вывода, база_р);
            const char *hст = буфер_кода_строка(&буфер_hлиб);
            size_t hдл = буфер_hлиб.базовый.длина > 0 ? буфер_hлиб.базовый.длина - 1 : 0;
            записать_если_изменилось(путь_hл, hст, hдл);
            const char *ист = буфер_кода_строка(&буфер_иР);
            size_t идл = буфер_иР.базовый.длина > 0 ? буфер_иР.базовый.длина - 1 : 0;
            записать_если_изменилось(путь_ил, ист, идл);
        }
        буфер_кода_освободить(&буфер_hлиб);
        буфер_кода_освободить(&буфер_иР);

        // Автолинковка Konda-библиотек потребителя (как в монолите).
        const char *доп_so_р[64];
        size_t число_so_р = 0;
        if (!библиотека && интерфейсы) {
            size_t m = интерфейс_число_библиотек(интерфейсы);
            for (size_t i = 0; i < m && число_so_р < 64; ++i)
                доп_so_р[число_so_р++] = интерфейс_библиотека(интерфейсы, i);
        }

        if (ошибка_записи || !пути_c || !изменился) {
            if (ошибка_записи) fprintf(stderr, "Не удалось записать .c раздельной сборки\n");
            else fprintf(stderr, "Нет памяти под раздельную сборку\n");
            код = 1;
        } else if (только_си) {
            printf("Только .c: компиляция пропущена (--только-си)\n");
            код = 0;
        } else {
            char компилятор_буф[160];
            const char *компилятор = "cc";
            if (триплет && триплет[0]) {
                snprintf(компилятор_буф, sizeof(компилятор_буф), "%s-gcc", триплет);
                компилятор = компилятор_буф;
                if (!аллокатор_задан) аллокатор_jemalloc = 0;
            }
            const char *march_флаг = разрешить_march(триплет, march_уровень, march_задан);
            char путь_бин_р[512];
            snprintf(путь_бин_р, sizeof(путь_бин_р), "%s/%s", папка_вывода, база_р);
            код = скомпилировать_раздельно(
                    (const char (*)[512])пути_c, изменился, число_файлов,
                    путь_бин_р, релиз, библиотека, база_каталог,
                    доп_so_р, число_so_р, нужен_pthread, компилятор,
                    аллокатор_jemalloc, символы, статический, использует_embed_р,
                    !разрешить_предупреждения, march_флаг);
        }

        free(пути_c); free(изменился);
        free(туимена); free(телабуф); free(телаптр); free(начала); free(концы);
        goto очистка;
    }

    БуферКода буфер;
    буфер_кода_инициализировать(&буфер);
    кодоген_и(общий, &буфер, релиз, интерфейсы, версия_проекта);

    // Для библиотеки — публичный заголовок И Konda-интерфейс из того же AST
    // (до освобождения). Интерфейс несёт полные Konda-сигнатуры для потребителя.
    БуферКода буфер_h;
    буфер_кода_инициализировать(&буфер_h);
    БуферКода буфер_и;
    буфер_кода_инициализировать(&буфер_и);
    if (библиотека) {
        кодоген_заголовок(общий, &буфер_h);
        эмит_интерфейс(общий, &буфер_и);
        if (шаблоны_и) буфер_кода_добавить(&буфер_и, шаблоны_и);  // §101
    }
    // Признак потоков/встраивания снимаем ДО освобождения дерева: линковка ниже
    // читать «общий» уже не может (это было бы use-after-free).
    нужен_pthread = программа_использует_потоки(общий);
    int использует_embed = программа_использует_встроить(общий);
    освободить_узел(общий);

    // ── имя выхода — от первого файла, либо явно через --имя ────────────────
    // (--имя нужно для монолита stdlib: несколько модулей → один libkonda_std.*).
    char база[256];
    if (имя_задан && !инлайн_код) {
        if (strlen(инлайн_имя) >= sizeof(база)) {
            fprintf(stderr, "Слишком длинное имя (--имя)\n");
            буфер_кода_освободить(&буфер);
            буфер_кода_освободить(&буфер_h);
            буфер_кода_освободить(&буфер_и);
            код = 1;
            goto очистка;
        }
        snprintf(база, sizeof(база), "%s", инлайн_имя);
    } else if (!путь_без_расширения(входные[0], база, sizeof(база))) {
        fprintf(stderr, "Слишком длинное имя файла\n");
        буфер_кода_освободить(&буфер);
        буфер_кода_освободить(&буфер_h);
        буфер_кода_освободить(&буфер_и);
        код = 1;
        goto очистка;
    }

    if (создать_каталог_рекурсивно(папка_вывода) != 0) {
        fprintf(stderr, "Не удалось создать папку %s\n", папка_вывода);
        буфер_кода_освободить(&буфер);
        буфер_кода_освободить(&буфер_h);
        буфер_кода_освободить(&буфер_и);
        код = 1;
        goto очистка;
    }

    char путь_си[512];
    char путь_бин[512];
    snprintf(путь_си, sizeof(путь_си), "%s/%s.c", папка_вывода, база);
    snprintf(путь_бин, sizeof(путь_бин), "%s/%s", папка_вывода, база);

    FILE *f = fopen(путь_си, "wb");
    if (!f) {
        fprintf(stderr, "Не удалось создать %s\n", путь_си);
        буфер_кода_освободить(&буфер);
        буфер_кода_освободить(&буфер_h);
        буфер_кода_освободить(&буфер_и);
        код = 1;
        goto очистка;
    }
    const char *код_строка = буфер_кода_строка(&буфер);
    size_t код_длина = буфер.базовый.длина > 0 ? буфер.базовый.длина - 1 : 0;
    fwrite(код_строка, 1, код_длина, f);
    fclose(f);
    printf("Записан %s (%zu байт)\n", путь_си, код_длина);
    буфер_кода_освободить(&буфер);

    // Заголовок библиотеки рядом с .c.
    if (библиотека) {
        char путь_h[512];
        snprintf(путь_h, sizeof(путь_h), "%s/%s.h", папка_вывода, база);
        FILE *fh = fopen(путь_h, "wb");
        if (!fh) {
            fprintf(stderr, "Не удалось создать %s\n", путь_h);
            буфер_кода_освободить(&буфер_h);
            код = 1;
            goto очистка;
        }
        const char *h_строка = буфер_кода_строка(&буфер_h);
        size_t h_длина = буфер_h.базовый.длина > 0 ? буфер_h.базовый.длина - 1 : 0;
        fwrite(h_строка, 1, h_длина, fh);
        fclose(fh);
        printf("Записан %s (%zu байт)\n", путь_h, h_длина);

        // Konda-интерфейс рядом с .h/.so — для безопасного пути 2.
        char путь_и[512];
        snprintf(путь_и, sizeof(путь_и), "%s/%s.и", папка_вывода, база);
        FILE *fи = fopen(путь_и, "wb");
        if (fи) {
            const char *и_строка = буфер_кода_строка(&буфер_и);
            size_t и_длина = буфер_и.базовый.длина > 0 ? буфер_и.базовый.длина - 1 : 0;
            fwrite(и_строка, 1, и_длина, fи);
            fclose(fи);
            printf("Записан %s (%zu байт)\n", путь_и, и_длина);
        }
    }
    буфер_кода_освободить(&буфер_h);
    буфер_кода_освободить(&буфер_и);

    // Автолинковка Konda-библиотек потребителя (безопасный путь 2).
    const char *доп_so[64];
    size_t число_so = 0;
    if (!библиотека && интерфейсы) {
        size_t m = интерфейс_число_библиотек(интерфейсы);
        for (size_t i = 0; i < m && число_so < 64; ++i)
            доп_so[число_so++] = интерфейс_библиотека(интерфейсы, i);
    }
    if (только_си) {
        // --только-си: код на C уже записан выше; компиляцию пропускаем.
        printf("Только .c: компиляция пропущена (--только-си)\n");
        код = 0;
    } else {
        // Кросс-компиляция: компилятор — «<триплет>-gcc» (пока только gcc);
        // без триплета — обычный «cc» (execvp ищет по PATH).
        char компилятор_буф[160];
        const char *компилятор = "cc";
        if (триплет && триплет[0]) {
            snprintf(компилятор_буф, sizeof(компилятор_буф), "%s-gcc", триплет);
            компилятор = компилятор_буф;
            // На кроссе host-jemalloc в target-sysroot нет: если аллокатор явно
            // не задан — переносимый fallback libc.
            if (!аллокатор_задан) аллокатор_jemalloc = 0;
        }
        // Целевой ISA-уровень: строка «-march=<...>» (или пусто). Предупреждение о
        // дефолтном «в3» печатается здесь — только на реальной компиляции (при
        // --только-си сюда не заходим), один раз на вызов.
        const char *march_флаг = разрешить_march(триплет, march_уровень, march_задан);
        код = скомпилировать_си(путь_си, путь_бин, релиз, библиотека,
                                база_каталог, доп_so, число_so, нужен_pthread,
                                компилятор, аллокатор_jemalloc, символы,
                                статический, использует_embed,
                                !разрешить_предупреждения, march_флаг);
    }

очистка:
    free(шаблоны_и);
    интерфейс_освободить(интерфейсы);
    for (size_t i = 0; i < число_файлов; ++i) {
        if (корни[i]) освободить_узел(корни[i]);
        массив_токенов_освободить(&токены[i]);
        free(источники[i]);
    }
    free(корни);
    free(токены);
    free(источники);
    free(длины_ист);
    free(входные);
    return код;
}
