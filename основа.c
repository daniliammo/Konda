// ─── цветной вывод диагностик ───────────────────────────────────────────────
//
// ANSI-цвета — только когда stderr действительно терминал и не задан NO_COLOR
// (https://no-color.org). При перенаправлении в файл/пайп (в т.ч. в тестах)
// коды не печатаются — вывод остаётся «чистым» текстом, а тесты грепают его
// как раньше. Формат заголовка не меняем (тесты грепают «Ошибка транспиляции»/
// «Предупреждение»), лишь подсвечиваем и добавляем строку-источник с кареткой.
#define ЦВ_КРАСНЫЙ "\033[31m"
#define ЦВ_ЖЁЛТЫЙ  "\033[33m"
#define ЦВ_СБРОС   "\033[0m"

static int цвет_включён(void)
{
    static int кэш = -1;
    if (кэш < 0)
        кэш = isatty(fileno(stderr)) && getenv("NO_COLOR") == nullptr;
    return кэш;
}

// ─── целевой ISA-уровень (--march) ──────────────────────────────────────────
//
// Разрешает флаг «--march» в готовую строку «-march=<...>» для внутреннего cc.
// Уровни в1..в4 отражают микроархитектурные уровни платформы (на x86-64 — это
// стандартные x86-64-v1..v4; на ARM64/RISC-V — приближённые эквиваленты по году
// расширений), «нативный» → -march=native (под конкретный CPU сборки), а любая
// иная строка пробрасывается в cc как есть (escape-hatch, напр. «skylake» или
// «rv64gcv_zba»). Семейство арх берём из триплета кросс-сборки (важнее хоста —
// код компилируется ПОД цель), без триплета — из макросов хост-компилятора.
// По умолчанию (уровень не задан) целимся в «в3»: заметно быстрее baseline
// (авто-векторизация AVX2/BMI2 и т.п.), но НЕ запустится на старых CPU — поэтому
// печатаем ОБЯЗАТЕЛЬНОЕ подробное предупреждение (гасится явным --march или
// переменной окружения KONDA_NO_ISA_WARN — для тестового харнесса/встраивания).
static const char *ЦВ_(const char *код) { return цвет_включён() ? код : ""; }

static const char *разрешить_march(const char *триплет, const char *уровень,
                                   int задан)
{
    // Семейство архитектуры: 0=x86_64, 1=arm64, 2=riscv64, 3=riscv32, 4=arm32.
    int семья;
    if (триплет && триплет[0]) {
        if (strstr(триплет, "x86_64") || strstr(триплет, "amd64")) семья = 0;
        else if (strstr(триплет, "aarch64") || strstr(триплет, "arm64")) семья = 1;
        else if (strstr(триплет, "riscv64")) семья = 2;
        else if (strstr(триплет, "riscv32")) семья = 3;
        else if (strstr(триплет, "arm")) семья = 4;
        else семья = -1;  // неизвестная цель — не навязываем -march
    } else {
#if defined(__x86_64__)
        семья = 0;
#elif defined(__aarch64__)
        семья = 1;
#elif defined(__riscv) && (__riscv_xlen == 64)
        семья = 2;
#elif defined(__riscv)
        семья = 3;
#elif defined(__arm__)
        семья = 4;
#else
        семья = -1;
#endif
    }

    // Глобальный дефолт из окружения: если --march не задан, но задан KONDA_MARCH —
    // берём его как ЯВНЫЙ уровень (без предупреждения). Позволяет дистрибутиву/CI/
    // тестовому харнессу зафиксировать ISA без правки каждого вызова (напр. «в1»
    // для переносимой сборки корпуса), не трогая пользовательский дефолт «в3».
    if (!уровень || !уровень[0]) {
        const char *env = getenv("KONDA_MARCH");
        if (env && env[0]) { уровень = env; задан = 1; }
    }

    // Нормализуем уровень: 1..4, 0 = «нативный», -1 = «явная строка / нет».
    int ур;  const char *явная = nullptr;
    if (!уровень || !уровень[0]) {
        ур = 3;  // дефолт
    } else if (strcmp(уровень, "нативный") == 0 || strcmp(уровень, "native") == 0) {
        ур = 0;
    } else if ((strcmp(уровень, "в1") == 0 || strcmp(уровень, "v1") == 0)) {
        ур = 1;  // «в» — кириллица (2 байта UTF-8); принимаем и ASCII «v».
    } else if ((strcmp(уровень, "в2") == 0 || strcmp(уровень, "v2") == 0)) {
        ур = 2;
    } else if ((strcmp(уровень, "в3") == 0 || strcmp(уровень, "v3") == 0)) {
        ур = 3;
    } else if ((strcmp(уровень, "в4") == 0 || strcmp(уровень, "v4") == 0)) {
        ур = 4;
    } else {
        ур = -1;  явная = уровень;  // проброс как есть
    }

    static char буфер[96];
    буфер[0] = '\0';
    if (явная) {
        snprintf(буфер, sizeof буфер, "-march=%s", явная);
        return буфер;
    }
    if (семья < 0 && ур != 0) return буфер;  // неизвестная цель, не native → пусто

    const char *арх = "";
    if (ур == 0) {
        арх = "native";
    } else switch (семья) {
        case 0: { const char *t[] = {"x86-64","x86-64-v2","x86-64-v3","x86-64-v4"};
                  арх = t[ур-1]; } break;
        case 1: { const char *t[] = {"armv8-a","armv8.2-a","armv8.4-a","armv8.6-a"};
                  арх = t[ур-1]; } break;
        case 2: { const char *t[] = {"rv64gc","rv64gc","rv64gcv","rv64gcv"};
                  арх = t[ур-1]; } break;
        case 3: { const char *t[] = {"rv32gc","rv32gc","rv32gcv","rv32gcv"};
                  арх = t[ур-1]; } break;
        case 4: арх = "armv7-a"; break;
        default: return буфер;
    }
    snprintf(буфер, sizeof буфер, "-march=%s", арх);

    // Обязательное предупреждение о дефолтном «в3» (заметная смена поведения:
    // бинарник не запустится на старых CPU). Только когда уровень НЕ задан явно.
    if (!задан && ур == 3 && !getenv("KONDA_NO_ISA_WARN")) {
        const char *ж = ЦВ_(ЦВ_ЖЁЛТЫЙ), *с = ЦВ_(ЦВ_СБРОС);
        const char *треб = семья == 0 ? "AVX2, BMI2, FMA и др. (уровень x86-64-v3)"
                          : семья == 1 ? "ARMv8.4-A"
                          : (семья == 2 || семья == 3) ? "векторное расширение RISC-V «V»"
                          : "расширения ARMv7-A";
        const char *старьё = семья == 0
            ? "процессорах до ~2015 г. (Intel Haswell 2013 / AMD Excavator 2015 и новее — ок)"
            : "процессорах без указанных расширений";
        fprintf(stderr,
            "%sПредупреждение:%s сборка целится в ISA-уровень «в3» (%s) — задан ПО УМОЛЧАНИЮ.\n"
            "  Бинарник НЕ запустится на %s.\n"
            "  Явно выберите уровень флагом --march: «в1» — максимальная переносимость\n"
            "  (базовый %s), «нативный» — максимум скорости на ЭТОЙ машине,\n"
            "  «в2»/«в4» — промежуточный/новейший. Это сообщение гасится явным --march.\n",
            ж, с, треб, старьё,
            семья == 0 ? "x86-64" : семья == 1 ? "ARMv8-A"
                       : семья == 2 ? "rv64gc" : семья == 3 ? "rv32gc" : "ARMv7-A");
    }
    return буфер;
}

// Начало строки №N (1-based) в тексте; *длина — её длина без '\n'.
// nullptr, если такой строки нет.
static const char *строка_источника(const char *текст, int номер, size_t *длина)
{
    *длина = 0;
    if (!текст || номер < 1) return nullptr;
    const char *п = текст;
    for (int i = 1; i < номер; ++i) {
        const char *nl = strchr(п, '\n');
        if (!nl) return nullptr;
        п = nl + 1;
    }
    const char *конец = strchr(п, '\n');
    *длина = конец ? (size_t)(конец - п) : strlen(п);
    return п;
}

// Печатает строку-источник с подсветкой (красной для ошибки, жёлтой для
// предупреждения) и каретку «^» под колонкой. Ничего не делает без источника.
static void печать_строки_источника(const char *источник, int строка,
                                    int колонка, int предупреждение)
{
    if (!источник || строка < 1) return;
    size_t дл;
    const char *ст = строка_источника(источник, строка, &дл);
    if (!ст) return;
    int цв = цвет_включён();
    const char *цвет = предупреждение ? ЦВ_ЖЁЛТЫЙ : ЦВ_КРАСНЫЙ;
    // «  <номер> | <вся строка, подсвечена>»
    fprintf(stderr, "  %5d | %s%.*s%s\n",
            строка, цв ? цвет : "", (int)дл, ст, цв ? ЦВ_СБРОС : "");
    // «        | <отступ>^» — каретка под колонкой. Отступ считаем по СИМВОЛАМ
    // (как лексер: продолжающие байты UTF-8 10xxxxxx столбец не двигают),
    // иначе кириллица (2 байта/символ) сдвигала бы каретку. Табы сохраняем.
    fprintf(stderr, "        | ");
    int цель = колонка > 1 ? колонка - 1 : 0;
    int столбец = 0;
    for (size_t i = 0; i < дл && столбец < цель; ) {
        unsigned char c = (unsigned char)ст[i];
        fputc(c == '\t' ? '\t' : ' ', stderr);
        столбец++;
        // Перешагнуть все байты текущего символа (ведущий + продолжающие).
        for (++i; i < дл && ((unsigned char)ст[i] & 0xC0) == 0x80; ++i) { }
    }
    fprintf(stderr, "%s^%s\n", цв ? цвет : "", цв ? ЦВ_СБРОС : "");
}

// Единая печать диагностики: заголовок в прежнем формате (со цветом слова
// «Ошибка транспиляции»/«Предупреждение») + строка-источник с кареткой.
// путь может быть nullptr (пост-слияние: файл-локальность потеряна для
// multi-file); источник — текст файла для сниппета (nullptr → без сниппета).
static void печать_диагностики(int предупреждение, const char *путь,
                               const char *источник, int строка, int колонка,
                               const char *сообщение)
{
    int цв = цвет_включён();
    const char *цвет = предупреждение ? ЦВ_ЖЁЛТЫЙ : ЦВ_КРАСНЫЙ;
    const char *слово = предупреждение ? "Предупреждение" : "Ошибка транспиляции";
    fprintf(stderr, "%s%s%s", цв ? цвет : "", слово, цв ? ЦВ_СБРОС : "");
    if (путь) fprintf(stderr, " %s", путь);
    fprintf(stderr, " (строка %d, колонка %d): %s\n", строка, колонка, сообщение);
    печать_строки_источника(источник, строка, колонка, предупреждение);
}

// ─── слияние программ ───────────────────────────────────────────────────────
//
// Несколько входных .конда файлов транспилируются как одна программа: каждый
// файл парсится отдельно (так линии в диагностиках остаются файл-локальными),
// затем top-level дети всех корней переносятся в общий УЗЕЛ_ПРОГРАММА.
// Семантика и кодоген работают с этим общим деревом — никаких заголовков и
// extern-деклараций не нужно, signature-pass семантики видит все функции и
// структуры сразу.
//
// Перенос: дети источника становятся детьми общего, источник «обнуляется»
// (длина = 0) и затем освобождается как пустая оболочка.
static Узел *слить_программы(Узел **корни, size_t число)
{
    Узел *общий = узел_создать(УЗЕЛ_ПРОГРАММА);
    for (size_t i = 0; i < число; ++i) {
        Узел *r = корни[i];
        if (!r) continue;
        size_t n = узел_число_детей(r);
        for (size_t j = 0; j < n; ++j) {
            узел_добавить_ребёнка(общий, узел_ребёнок(r, j));
        }
        // Дети переехали — источнику оставляем пустой массив, освободить_узел
        // не пройдётся по перенесённым указателям повторно.
        r->дети.длина = 0;
        освободить_узел(r);
        корни[i] = nullptr;
    }
    return общий;
}

