// Носитель-тип (поле/параметр/возврат) пригоден для «.и»? Именованные типы
// должны быть НАПЕЧАТАНЫ ранее (иначе потребитель не восстановит ссылку); для
// структур/перечислений смотрим их описание в корне. v1: запрещены
// поля-массивы (размер не сериализуется) и срезы с именованным элементом.
static const Узел *узел_именованного_типа(const Узел *корень, const Узел *н)
{
    if ((н->тип_данных != ТОКЕН_СТРУКТУРА
         && н->тип_данных != ТОКЕН_ПЕРЕЧИСЛЕНИЕ)
        || н->имя_типа.длина == 0) return nullptr;
    for (size_t i = 0; i < узел_число_детей(корень); ++i) {
        const Узел *т = узел_ребёнок(корень, i);
        if (!т) continue;
        if ((н->тип_данных == ТОКЕН_СТРУКТУРА && т->тип != УЗЕЛ_СТРУКТУРА)
            || (н->тип_данных == ТОКЕН_ПЕРЕЧИСЛЕНИЕ && т->тип != УЗЕЛ_ПЕРЕЧИСЛЕНИЕ))
            continue;
        if (т->токен.длина == н->имя_типа.длина
            && memcmp(т->токен.начало, н->имя_типа.начало, н->имя_типа.длина) == 0)
            return т;
    }
    return nullptr;
}

// Поле-примитив (с указателями): срезы/массивы/именованные типы не пересекают
// границу .и (v1 — владение/размеры через границу не передаются).
static int поле_примитивно(const Узел *п)
{
    if (п->срез || п->массив) return 0;
    if (п->тип_данных == ТОКЕН_СТРУКТУРА
        || п->тип_данных == ТОКЕН_ПЕРЕЧИСЛЕНИЕ
        || п->тип_данных == ТОКЕН_ФУНКУКАЗАТЕЛЬ) return 0;
    return п->тип_данных != ТОКЕН_НЕИЗВЕСТНЫЙ;
}

static int структура_года(const Узел *корень, const Узел *с, int глубина);
static int перечисление_года(const Узел *п);

// Поле структуры экспортируемо в «.и», если оно (§83/§108):
//  * примитив (в т.ч. указатель), ЛИБО
//  * §108 массив примитива «T поле[N]» — владения нет, C-layout inline, размер
//    несёт «.h»; на границе — только тип+размерность (для типизации доступа), ЛИБО
//  * §83 срез примитива/указателя — деструкция у потребителя = free(.данные), ЛИБО
//  * §108 срез<структура>/срез<перечисление> — ЭЛЕМЕНТ гарантированно БЕЗ владеющих
//    полей (§22: срез структур с владеющими полями — ошибка ЯЗЫКА, потому если
//    библиотека собралась, элемент POD), значит деструкция та же free(.данные).
//    Элемент-тип должен быть напечатан и сам года (иначе layout завязан на
//    непрозрачный тип). Глубина ограничивает взаимную рекурсию (само-ссылка).
static int поле_экспортируемо(const Узел *корень, const Узел *п, int глубина)
{
    if (поле_примитивно(п)) return 1;
    // §108: массив примитива (не срез, не указатель, не именованный/fp).
    if (п->массив && !п->срез && !п->указатели
        && п->тип_данных != ТОКЕН_СТРУКТУРА
        && п->тип_данных != ТОКЕН_ПЕРЕЧИСЛЕНИЕ
        && п->тип_данных != ТОКЕН_ФУНКУКАЗАТЕЛЬ
        && п->тип_данных != ТОКЕН_НЕИЗВЕСТНЫЙ)
        return 1;
    // §83: срез примитива/указателя.
    if (п->срез && !п->массив
        && п->тип_данных != ТОКЕН_СТРУКТУРА
        && п->тип_данных != ТОКЕН_ПЕРЕЧИСЛЕНИЕ
        && п->тип_данных != ТОКЕН_ФУНКУКАЗАТЕЛЬ
        && п->тип_данных != ТОКЕН_НЕИЗВЕСТНЫЙ)
        return 1;
    // §108: срез<структура>/срез<перечисление> — элемент POD (см. выше), года.
    if (п->срез && !п->массив && глубина < 6
        && (п->тип_данных == ТОКЕН_СТРУКТУРА
            || п->тип_данных == ТОКЕН_ПЕРЕЧИСЛЕНИЕ)) {
        const Узел *т = узел_именованного_типа(корень, п);
        if (!т) return 0;
        return т->тип == УЗЕЛ_СТРУКТУРА ? структура_года(корень, т, глубина + 1)
                                        : перечисление_года(т);
    }
    return 0;
}

// Структура экспортируется, если каждое поле экспортируемо и она не внешний
// тип/союз. Иначе C-layout завязан на непрозрачные внутренние типы — структура
// остаётся непрозрачной.
static int структура_года(const Узел *корень, const Узел *с, int глубина)
{
    if (с->внешняя || с->это_союз) return 0;
    for (size_t j = 0; j < узел_число_детей(с); ++j) {
        const Узел *поле = узел_ребёнок(с, j);
        if (!поле || поле->тип != УЗЕЛ_ПАРАМЕТР) continue;
        if (!поле_экспортируемо(корень, поле, глубина)) return 0;
    }
    return 1;
}

// Sum-перечисление экспортируется, если payload всех вариантов примитивен
// (варианты без данных допустимы).
static int перечисление_года(const Узел *п)
{
    int sum = 0;
    for (size_t v = 0; v < узел_число_детей(п); ++v) {
        const Узел *вар = узел_ребёнок(п, v);
        if (!вар || вар->тип != УЗЕЛ_ВАРИАНТ) continue;
        for (size_t k = 0; k < узел_число_детей(вар); ++k) {
            const Узел *пл = узел_ребёнок(вар, k);
            if (!пл || пл->тип != УЗЕЛ_ПАРАМЕТР) continue;
            // §99: поле-«строка» (срез=2) экспортируемо — C-носитель «Срез»,
            // borrow-вид, флаг среза (2) round-trip'ится через «ВП <носитель>».
            if (!поле_примитивно(пл) && пл->срез != 2) return 0;
            sum = 1;
        }
    }
    return sum;   // только sum-перечисления (простое C-enum остаётся в .h)
}

// §106: УЗЕЛ_ТИПФУНКЦИИ верхнего уровня с данным именем (для fp-псевдонимов).
static const Узел *узел_типфункции_по_имени(const Узел *корень,
                                            const Токен *имя)
{
    if (!имя || имя->длина == 0) return nullptr;
    for (size_t i = 0; i < узел_число_детей(корень); ++i) {
        const Узел *у = узел_ребёнок(корень, i);
        if (!у || у->тип != УЗЕЛ_ТИПФУНКЦИИ) continue;
        if (у->токен.длина == имя->длина
            && memcmp(у->токен.начало, имя->начало, имя->длина) == 0)
            return у;
    }
    return nullptr;
}

// §106: один носитель (возврат/параметр fp или функции) годен для «.и»?
// Примитив/указатель/срез-примитива — да; именованный тип — если он напечатан
// и года; fp внутри fp и срез именованного — нет (как в функция_экспортируема).
static int носитель_года(const Узел *корень, const Узел *у)
{
    if (у->тип_данных == ТОКЕН_ФУНКУКАЗАТЕЛЬ) return 0;  // fp-в-fp — не v1
    if (у->тип_данных == ТОКЕН_СТРУКТУРА || у->тип_данных == ТОКЕН_ПЕРЕЧИСЛЕНИЕ) {
        if (у->срез) return 0;
        const Узел *т = узел_именованного_типа(корень, у);
        if (!т) return 0;
        return т->тип == УЗЕЛ_СТРУКТУРА ? структура_года(корень, т, 0) : перечисление_года(т);
    }
    return 1;  // примитив / указатель / срез-примитива
}

// §106: типфункции-псевдоним целиком выразим в «.и» (возврат + все параметры
// годны)? Тогда его можно экспортировать записью «ТФ …», а функции с fp этого
// типа — перестают быть непрозрачными.
static int типфункции_года(const Узел *корень, const Узел *тф)
{
    if (!тф || тф->токен.длина == 0) return 0;
    if (!носитель_года(корень, тф)) return 0;   // тип возврата fp
    for (size_t j = 0; j < узел_число_детей(тф); ++j) {
        const Узел *п = узел_ребёнок(тф, j);
        if (!п || п->тип != УЗЕЛ_ПАРАМЕТР) continue;
        if (!носитель_года(корень, п)) return 0;
    }
    return 1;
}

// §106: fp-носитель функции (возврат/параметр) экспортируем? Его псевдоним
// «типфункции» должен быть объявлен в корне и целиком годен.
static int фп_экспортируем(const Узел *корень, const Узел *у)
{
    if (у->тип_данных != ТОКЕН_ФУНКУКАЗАТЕЛЬ) return 1;   // не fp — не наша забота
    const Узел *тф = узел_типфункции_по_имени(корень, &у->имя_типа);
    return тф && типфункции_года(корень, тф);
}

// Проверка: функцию можно выразить в «.и». Указатели на функцию (§106) — если их
// «типфункции»-псевдоним объявлен и годен (иначе непрозрачны); структуры и
// sum-перечисления поддержаны (несут имя типа).
static int функция_экспортируема(const Узел *корень, const Узел *ф)
{
    // Перегрузки-операторы: на СТРУКТУРАХ не экспортируем (их манглированный ключ
    // завязан на имя структуры, локальной для программы). НО перегрузки на
    // срез<T>/буфер<T> (§9-расширение) экспортируемы: ключ детерминирован по типу
    // элемента («ср_т<код>з<знак>»), поэтому потребитель строит ТО ЖЕ имя и
    // резолвит перегрузку из «.и» (лексикографические «<»/«>»/«<=»/«>=» строк из
    // stdlib доступны как встроенный оператор без объявления у потребителя).
    if (ф->это_оператор) {
        int есть_срез = 0;
        size_t всего_п = узел_число_детей(ф);
        for (size_t j = 0; j + 1 < всего_п; ++j) {
            const Узел *п = узел_ребёнок(ф, j);
            if (п && п->тип == УЗЕЛ_ПАРАМЕТР && п->срез) { есть_срез = 1; break; }
        }
        if (!есть_срез) return 0;       // оператор на структуре — не экспортируем (v1)
    }
    if (!фп_экспортируем(корень, ф)) return 0;   // §106: fp-возврат
    // Возврат: именованный тип обязан быть напечатан и годен (см. параметры).
    if (ф->тип_данных == ТОКЕН_СТРУКТУРА || ф->тип_данных == ТОКЕН_ПЕРЕЧИСЛЕНИЕ) {
        const Узел *т = узел_именованного_типа(корень, ф);
        if (!т) return 0;
        if (т->тип == УЗЕЛ_СТРУКТУРА ? !структура_года(корень, т, 0) : !перечисление_года(т))
            return 0;
    }
    size_t всего = узел_число_детей(ф);
    for (size_t j = 0; j + 1 < всего; ++j) {
        const Узел *п = узел_ребёнок(ф, j);
        if (!п || п->тип != УЗЕЛ_ПАРАМЕТР) continue;
        if (!фп_экспортируем(корень, п)) return 0;   // §106: fp-параметр
        if (п->срез && (п->тип_данных == ТОКЕН_СТРУКТУРА
                        || п->тип_данных == ТОКЕН_ПЕРЕЧИСЛЕНИЕ)) return 0;
        if (п->тип_данных == ТОКЕН_СТРУКТУРА
            || п->тип_данных == ТОКЕН_ПЕРЕЧИСЛЕНИЕ) {
            const Узел *т = узел_именованного_типа(корень, п);
            if (!т) return 0;
            if (т->тип == УЗЕЛ_СТРУКТУРА ? !структура_года(корень, т, 0) : !перечисление_года(т))
                return 0;
        }
    }
    return 1;
}

// Имя-или-«-»: для именованных типов пишем имя_типа узла, иначе «-».
static void эмит_имя_типа(БуферКода *б, const Узел *у)
{
    if (именованный_тип(у->тип_данных) && у->имя_типа.длина > 0) {
        буфер_кода_добавить(б, " ");
        буфер_кода_добавить_отрезок(б, у->имя_типа.начало, у->имя_типа.длина);
    } else {
        буфер_кода_добавить(б, " -");
    }
}

// Сериализация одного носителя-типа (возврат функции / параметр / поле):
// «<тип-кейворд> <беззн> <указ> <срез> [<массив>] <имя-типа|->».
static void эмит_носитель_типа(БуферКода *б, const Узел *у, int с_массивом)
{
    буфер_кода_добавить(б, тип_в_кейворд_имен(у->тип_данных));
    буфер_кода_добавить(б, " "); эмит_число(б, у->беззнаковый);
    буфер_кода_добавить(б, " "); эмит_число(б, у->указатели);
    буфер_кода_добавить(б, " "); эмит_число(б, у->срез);
    if (с_массивом) { буфер_кода_добавить(б, " "); эмит_число(б, у->массив); }
}

// §107: целочисленный/символьный примитив (годен как конст-размер §97 и атом).
static int тип_целый_или_символ(ТипТокена т)
{
    return т == ТОКЕН_ЦЕЛОЕ8 || т == ТОКЕН_ЦЕЛОЕ16 || т == ТОКЕН_ЦЕЛОЕ32
        || т == ТОКЕН_ЦЕЛОЕ64 || т == ТОКЕН_БАЙТ || т == ТОКЕН_ЛОГИЧЕСКИЙ
        || т == ТОКЕН_ТИП_СИМВОЛ;
}

// §107: инициализатор глобальной «конст» — целочисленный литерал (или унарный
// минус над ним)? Тогда пишем его ТЕКСТ в буф (потребитель переразберёт и свернёт
// сам — 0x/0b/разделители «_» обрабатывает его лексер, §66). Иначе 0 (строки/
// структуры/вещественные/выражения — вне охвата v1, остаются непрозрачными).
static int глобал_конст_литерал(const Узел *узел, char *буф, size_t размер)
{
    if (узел_число_детей(узел) != 1) return 0;
    const Узел *и = узел_ребёнок(узел, 0);
    int минус = 0;
    if (и->тип == УЗЕЛ_УНОП && узел_число_детей(и) == 1
        && и->токен.длина == 1 && и->токен.начало[0] == '-') {
        минус = 1;
        и = узел_ребёнок(и, 0);
    }
    if (!и || и->тип != УЗЕЛ_ЧИСЛО || и->токен.длина == 0) return 0;
    for (size_t k = 0; k < и->токен.длина; ++k)
        if (и->токен.начало[k] == '.') return 0;   // вещественное — не v1
    size_t n = и->токен.длина;
    if (n + (size_t)(минус ? 1 : 0) + 1 > размер) return 0;
    size_t p = 0;
    if (минус) буф[p++] = '-';
    memcpy(буф + p, и->токен.начало, n);
    буф[p + n] = '\0';
    return 1;
}

void эмит_интерфейс(const Узел *корень, БуферКода *буфер)
{
    буфер_кода_добавить(буфер, "konda-интерфейс 3\n");

    // 1. Sum-перечисления — только «годные» (payload примитивен). Порядок
    //    неважен загрузчику, но важен документации: типы раньше функций.
    //    «Е <имя>» / «Вар <имя>» / «ВП <носитель> <имя-поля>» / «КЕ».
    for (size_t i = 0; i < узел_число_детей(корень); ++i) {
        const Узел *п = узел_ребёнок(корень, i);
        if (!п || п->тип != УЗЕЛ_ПЕРЕЧИСЛЕНИЕ || п->токен.длина == 0) continue;
        if (!перечисление_года(п)) continue;
        буфер_кода_добавить(буфер, "Е ");
        буфер_кода_добавить_отрезок(буфер, п->токен.начало, п->токен.длина);
        буфер_кода_добавить(буфер, "\n");
        for (size_t v = 0; v < узел_число_детей(п); ++v) {
            const Узел *вар = узел_ребёнок(п, v);
            if (!вар || вар->тип != УЗЕЛ_ВАРИАНТ) continue;
            буфер_кода_добавить(буфер, "Вар ");
            буфер_кода_добавить_отрезок(буфер, вар->токен.начало, вар->токен.длина);
            буфер_кода_добавить(буфер, "\n");
            for (size_t k = 0; k < узел_число_детей(вар); ++k) {
                const Узел *пл = узел_ребёнок(вар, k);
                if (!пл || пл->тип != УЗЕЛ_ПАРАМЕТР) continue;
                буфер_кода_добавить(буфер, "ВП ");
                эмит_носитель_типа(буфер, пл, 0);
                эмит_имя_типа(буфер, пл);
                буфер_кода_добавить(буфер, " ");
                буфер_кода_добавить_отрезок(буфер, пл->токен.начало, пл->токен.длина);
                буфер_кода_добавить(буфер, " "); эмит_число(буфер, пл->возможно); // §1
                буфер_кода_добавить(буфер, "\n");
            }
        }
        буфер_кода_добавить(буфер, "КЕ\n");
    }

    // 2. Структуры (только годные: без союзов/внешних, поля примитивны):
    //    «С <имя> <деструктор|->» / «Поле <носитель+массив> <имя-типа|->
    //    <имя-поля>» / «КС». Деструктор нужен для RAII у потребителя.
    for (size_t i = 0; i < узел_число_детей(корень); ++i) {
        const Узел *с = узел_ребёнок(корень, i);
        if (!с || с->тип != УЗЕЛ_СТРУКТУРА || с->токен.длина == 0) continue;
        if (!структура_года(корень, с, 0)) continue;
        буфер_кода_добавить(буфер, "С ");
        буфер_кода_добавить_отрезок(буфер, с->токен.начало, с->токен.длина);
        if (с->имя_типа.длина > 0) {  // деструктор [удалить=…]
            буфер_кода_добавить(буфер, " ");
            буфер_кода_добавить_отрезок(буфер, с->имя_типа.начало, с->имя_типа.длина);
        } else {
            буфер_кода_добавить(буфер, " -");
        }
        буфер_кода_добавить(буфер, "\n");
        for (size_t j = 0; j < узел_число_детей(с); ++j) {
            const Узел *поле = узел_ребёнок(с, j);
            if (!поле || поле->тип != УЗЕЛ_ПАРАМЕТР) continue;
            буфер_кода_добавить(буфер, "Поле ");
            эмит_носитель_типа(буфер, поле, 1);       // с массивом (ФЛАГ)
            эмит_имя_типа(буфер, поле);
            буфер_кода_добавить(буфер, " ");
            буфер_кода_добавить_отрезок(буфер, поле->токен.начало, поле->токен.длина);
            буфер_кода_добавить(буфер, " "); эмит_число(буфер, поле->возможно); // §1
            // §108: размерность поля-массива N (нужна потребителю для границ доступа;
            // трейлинг — только у «Поле», иначе 0). C-размер зашит в typedef «.h».
            буфер_кода_добавить(буфер, " ");
            эмит_число(буфер, поле->массив ? (int)поле->размер_массива : 0);
            буфер_кода_добавить(буфер, "\n");
        }
        буфер_кода_добавить(буфер, "КС\n");
    }

    // 2.5. §106 Типы-указатели на функцию — ПЕРЕД функциями (те ссылаются на них
    //      по имени-псевдониму). «ТФ <имя> <носитель-возврата> <имя-типа|->
    //      <возможно>» / «ТФП <носитель> <имя-типа|-> <возможно>» / «КТФ».
    for (size_t i = 0; i < узел_число_детей(корень); ++i) {
        const Узел *тф = узел_ребёнок(корень, i);
        if (!тф || тф->тип != УЗЕЛ_ТИПФУНКЦИИ || тф->токен.длина == 0) continue;
        if (!типфункции_года(корень, тф)) continue;
        буфер_кода_добавить(буфер, "ТФ ");
        буфер_кода_добавить_отрезок(буфер, тф->токен.начало, тф->токен.длина);
        буфер_кода_добавить(буфер, " ");
        эмит_носитель_типа(буфер, тф, 0);
        эмит_имя_типа(буфер, тф);
        буфер_кода_добавить(буфер, " "); эмит_число(буфер, тф->возможно);
        буфер_кода_добавить(буфер, "\n");
        for (size_t j = 0; j < узел_число_детей(тф); ++j) {
            const Узел *п = узел_ребёнок(тф, j);
            if (!п || п->тип != УЗЕЛ_ПАРАМЕТР) continue;
            буфер_кода_добавить(буфер, "ТФП ");
            эмит_носитель_типа(буфер, п, 0);
            эмит_имя_типа(буфер, п);
            буфер_кода_добавить(буфер, " "); эмит_число(буфер, п->возможно);
            буфер_кода_добавить(буфер, "\n");
        }
        буфер_кода_добавить(буфер, "КТФ\n");
    }

    // 2.7. §107 Глобальные конст/атомики (скаляр-целочисленные). «Конст <имя>
    //      <носитель> <значение>» — потребитель эмитит свой static const (значение
    //      свёрнуто, коллизий нет). «Атом <имя> <носитель>» — ВНЕШНИЙ разделяемый
    //      символ .so (потребитель лишь регистрирует имя; extern-декларация в «X.h»).
    for (size_t i = 0; i < узел_число_детей(корень); ++i) {
        const Узел *г = узел_ребёнок(корень, i);
        if (!г || г->тип != УЗЕЛ_ОБЪЯВЛЕНИЕ || г->токен.длина == 0) continue;
        if (г->массив || г->указатели || г->срез) continue;   // v1: только скаляр
        if (!тип_целый_или_символ(г->тип_данных)) continue;
        if (г->атом) {
            буфер_кода_добавить(буфер, "Атом ");
            буфер_кода_добавить_отрезок(буфер, г->токен.начало, г->токен.длина);
            буфер_кода_добавить(буфер, " ");
            эмит_носитель_типа(буфер, г, 0);
            буфер_кода_добавить(буфер, "\n");
        } else if (г->неизменяемый) {
            char лит[64];
            if (!глобал_конст_литерал(г, лит, sizeof(лит))) continue;
            буфер_кода_добавить(буфер, "Конст ");
            буфер_кода_добавить_отрезок(буфер, г->токен.начало, г->токен.длина);
            буфер_кода_добавить(буфер, " ");
            эмит_носитель_типа(буфер, г, 0);
            буфер_кода_добавить(буфер, " ");
            буфер_кода_добавить(буфер, лит);
            буфер_кода_добавить(буфер, "\n");
        }
    }

    // 3. Функции. «Ф имя» / «В <носитель> <имя-типа|->» / «П <носитель+массив>
    //    <владеет> <по_ссылке> <имя-типа|->» / «К».
    for (size_t i = 0; i < узел_число_детей(корень); ++i) {
        const Узел *ф = узел_ребёнок(корень, i);
        if (!ф || ф->тип != УЗЕЛ_ФУНКЦИЯ) continue;
        if (ф->статический || ф->это_main) continue;      // не экспортируется
        if (ф->токен.длина == 0) continue;
        if (!функция_экспортируема(корень, ф)) continue;

        буфер_кода_добавить(буфер, "Ф ");
        буфер_кода_добавить_отрезок(буфер, ф->токен.начало, ф->токен.длина);
        // §37 п.6 — бит «возврат заимствован» вторым полем (потребитель тогда не
        // освобождает результат). Пишем всегда; старые «.и» без него → 0 (владеет).
        буфер_кода_добавить(буфер, " ");
        эмит_число(буфер, ф->возврат_заимствован);
        буфер_кода_добавить(буфер, "\n");

        буфер_кода_добавить(буфер, "В ");
        эмит_носитель_типа(буфер, ф, 0);
        эмит_имя_типа(буфер, ф);
        буфер_кода_добавить(буфер, " "); эмит_число(буфер, ф->возможно); // §1
        буфер_кода_добавить(буфер, "\n");

        size_t всего = узел_число_детей(ф);
        for (size_t j = 0; j + 1 < всего; ++j) {
            const Узел *п = узел_ребёнок(ф, j);
            if (!п || п->тип != УЗЕЛ_ПАРАМЕТР) continue;
            буфер_кода_добавить(буфер, "П ");
            эмит_носитель_типа(буфер, п, 1);              // с массивом
            буфер_кода_добавить(буфер, " "); эмит_число(буфер, п->владеет);
            буфер_кода_добавить(буфер, " "); эмит_число(буфер, п->по_ссылке);
            эмит_имя_типа(буфер, п);
            буфер_кода_добавить(буфер, " "); эмит_число(буфер, п->возможно); // §1
            буфер_кода_добавить(буфер, "\n");
        }
        буфер_кода_добавить(буфер, "К\n");
    }
}

// ─── §101: экспорт обобщённых шаблонов (исходник в «.и») ─────────────────────

// Узел — обобщённый ШАБЛОН верхнего уровня (ведущий ребёнок — УЗЕЛ_ТИПОПАРАМЕТР)?
// Возвращает 1 и пишет односимвольный вид «f»/«s»/«e» (функция/структура/enum).
static int узел_вид_шаблона(const Узел *у, const char **вид)
{
    if (!у || узел_число_детей(у) == 0) return 0;
    const Узел *п = узел_ребёнок(у, 0);
    if (!п || п->тип != УЗЕЛ_ТИПОПАРАМЕТР) return 0;
    if (у->тип == УЗЕЛ_ФУНКЦИЯ)      { *вид = "f"; return 1; }
    if (у->тип == УЗЕЛ_СТРУКТУРА)    { *вид = "s"; return 1; }
    if (у->тип == УЗЕЛ_ПЕРЕЧИСЛЕНИЕ) { *вид = "e"; return 1; }
    return 0;
}

char *эмит_шаблоны_в_строку(const Узел *корень)
{
    if (!корень) return nullptr;
    БуферКода б;
    буфер_кода_инициализировать(&б);
    int сколько = 0;
    for (size_t i = 0; i < узел_число_детей(корень); ++i) {
        const Узел *у = узел_ребёнок(корень, i);
        const char *вид = nullptr;
        if (!узел_вид_шаблона(у, &вид)) continue;
        if (!у->исходник || у->исходник_длина == 0 || у->токен.длина == 0) continue;
        // «Шаблон <вид> <имя> <длина>\n<исходник (длина байт)>\n». Длина-префикс —
        // чтобы дословный (с переводами строк) исходник читался как единый блок.
        char число[32];
        snprintf(число, sizeof число, "%zu", у->исходник_длина);
        буфер_кода_добавить(&б, "Шаблон ");
        буфер_кода_добавить(&б, вид);
        буфер_кода_добавить(&б, " ");
        буфер_кода_добавить_отрезок(&б, у->токен.начало, у->токен.длина);
        буфер_кода_добавить(&б, " ");
        буфер_кода_добавить(&б, число);
        буфер_кода_добавить(&б, "\n");
        буфер_кода_добавить_отрезок(&б, у->исходник, у->исходник_длина);
        буфер_кода_добавить(&б, "\n");
        сколько++;
    }
    if (сколько == 0) { буфер_кода_освободить(&б); return nullptr; }
    const char *с = буфер_кода_строка(&б);
    char *рез = с ? strdup(с) : nullptr;
    буфер_кода_освободить(&б);
    return рез;
}

// §101: строка «.и» — заголовок блока шаблона «Шаблон вид имя длина»? Тогда за ней
// идёт дословное тело шаблона (длина байт, с переводами строк). Возвращает
// указатель СТРОКИ за телом (пропустить его целиком), иначе nullptr. «сост» —
// состояние strtok_r после извлечения первого токена «Шаблон». Все построчные
// читатели «.и» ДОЛЖНЫ звать это на «Шаблон», иначе тело шаблона попало бы под
// разбор построчно (строка вида «С …» внутри исходника сбила бы читатель).
static char *пропустить_блок_шаблона(char **сост, char *конец, int есть_перевод,
                                     const char *текст, size_t размер)
{
    strtok_r(nullptr, " \t\r", сост);              // вид
    strtok_r(nullptr, " \t\r", сост);              // имя
    char *дл = strtok_r(nullptr, " \t\r", сост);   // длина
    long n = дл ? atol(дл) : -1;
    if (!есть_перевод || n < 0) return nullptr;
    char *тело = конец + 1;                          // байт после '\n' заголовка
    const char *предел = текст + размер;
    if (тело > предел) тело = (char *)предел;
    if (тело + n > предел) n = (long)(предел - тело);
    return тело + n;                                 // '\n' за телом (пропустится)
}

// ─── чтение ──────────────────────────────────────────────────────────────────

static int файл_есть(const char *путь)
{
    struct stat st;
    return stat(путь, &st) == 0 && S_ISREG(st.st_mode);
}

// Токен{начало,длина} из имени в стабильной памяти (таблица «.и» — фиксированный
// массив типы[], адреса не двигаются всё время жизни таблицы).
static void токен_из_буфера(Токен *т, const char *имя)
{
    т->начало = имя;
    т->длина = strlen(имя);
}

// ИнтПоле (поле структуры / payload варианта) → AST-узел УЗЕЛ_ПАРАМЕТР.
static Узел *параметр_из_инт(const ИнтПоле *п)
{
    Узел *у = узел_создать(УЗЕЛ_ПАРАМЕТР);
    у->тип_данных = п->тип;
    у->беззнаковый = п->беззнаковый;
    у->указатели = п->указатели;
    у->срез = п->срез;
    у->массив = п->массив;             // §108: флаг «поле — массив»
    у->размер_массива = п->размер_массива;  // §108: размерность (для границ доступа)
    у->возможно = п->возможно;   // §1: nullable-указатель через границу библиотеки
    токен_из_буфера(&у->токен, п->имя);
    if (п->имя_типа[0]) токен_из_буфера(&у->имя_типа, п->имя_типа);
    return у;
}

// Реконструкция именованного типа библиотеки в полноценный AST-узел
// (из_библиотеки): семантика/кодоген работают штатно, но C-определение не
// эмитится — typedef приходит из «#содержит»-заголовка библиотеки.
static Узел *узел_из_инт_типа(const ИнтТип *и)
{
    Узел *у = узел_создать(и->это_структура ? УЗЕЛ_СТРУКТУРА : УЗЕЛ_ПЕРЕЧИСЛЕНИЕ);
    у->из_библиотеки = 1;
    токен_из_буфера(&у->токен, и->имя);
    if (и->это_структура) {
        // «[удалить = Имя]» несёт с->имя_типа (как у обычной декларации).
        if (и->деструктор[0]) токен_из_буфера(&у->имя_типа, и->деструктор);
        for (size_t k = 0; k < и->число_полей; ++k)
            узел_добавить_ребёнка(у, параметр_из_инт(&и->поля[k]));
    } else {
        for (size_t v = 0; v < и->число_вариантов; ++v) {
            const ИнтВариант *в = &и->варианты[v];
            Узел *вар = узел_создать(УЗЕЛ_ВАРИАНТ);
            токен_из_буфера(&вар->токен, в->имя);
            for (size_t k = 0; k < в->число_полей; ++k)
                узел_добавить_ребёнка(вар, параметр_из_инт(&в->поля[k]));
            узел_добавить_ребёнка(у, вар);
        }
    }
    return у;
}

// §106: реконструкция fp-псевдонима «.и» → УЗЕЛ_ТИПФУНКЦИИ (из_библиотеки):
// собрать_типыфункций регистрирует сигнатуру, кодоген НЕ эмитит typedef (он в «X.h»).
static Узел *узел_из_инт_типфункции(const ИнтТипфункции *тф)
{
    Узел *у = узел_создать(УЗЕЛ_ТИПФУНКЦИИ);
    у->из_библиотеки = 1;
    токен_из_буфера(&у->токен, тф->имя);
    у->тип_данных = тф->тип_возврата;
    у->беззнаковый = тф->беззнаковый_возврата;
    у->указатели = тф->указатели_возврата;
    у->срез = тф->срез_возврата;
    у->возможно = тф->возможно_возврата;
    if (тф->имя_типа_возврата[0]) токен_из_буфера(&у->имя_типа, тф->имя_типа_возврата);
    for (size_t k = 0; k < тф->число_параметров; ++k)
        узел_добавить_ребёнка(у, параметр_из_инт(&тф->параметры[k]));
    return у;
}

// §107: реконструкция глобального конст/атома «.и» → УЗЕЛ_ОБЪЯВЛЕНИЕ. Конст —
// со значением-литералом (потребитель свернёт и эмитит СВОЙ static const). Атом —
// из_библиотеки (определение в .so, декларация «extern _Atomic» в «X.h»): кодоген
// НЕ эмитит, собрать_глобальные_константы лишь регистрирует имя как атомик.
static Узел *узел_из_инт_глобала(const ИнтГлобал *г)
{
    Узел *у = узел_создать(УЗЕЛ_ОБЪЯВЛЕНИЕ);
    токен_из_буфера(&у->токен, г->имя);
    у->тип_данных = г->тип;
    у->беззнаковый = г->беззнаковый;
    у->указатели = г->указатели;
    у->срез = г->срез;
    if (г->атом) {
        у->атом = 1;
        у->из_библиотеки = 1;
    } else {
        у->неизменяемый = 1;
        Узел *чис = узел_создать(УЗЕЛ_ЧИСЛО);
        токен_из_буфера(&чис->токен, г->значение);
        узел_добавить_ребёнка(у, чис);
    }
    return у;
}

// Разбор построчного «.и». Команды: «Е/Вар/ВП/КЕ» — sum-перечисление,
// «С/Поле/КС» — структура, «Ф/В/П/К» — функция; тип-строка «имя-типа|-» есть
// в v2 (версия из заголовка «konda-интерфейс N»; v1: «В» — 4 токена, «П» — 7).
// Прочее (старые версии, доки) — пропускается.
static void загрузить_интерфейс(const char *путь, ТаблицаИнтерфейса *куда)
{
    size_t размер = 0;
    char *текст = прочитать_файл((char *)путь, &размер);
    if (!текст) return;

    int версия = 1;          // «konda-интерфейс N»; без заголовка — как v1
    ИнтФункция тек;
    memset(&тек, 0, sizeof(тек));
    ИнтТип *тек_тип = nullptr;   // накапливаемый именованный тип
    ИнтВариант *тек_вар = nullptr;
    ИнтТипфункции *тек_тф = nullptr;  // §106: накапливаемый fp-псевдоним
    int в_функции = 0;

    char *строки = текст;
    while (*строки) {
        char *конец = строки;
        while (*конец && *конец != '\n') конец++;
        int есть_перевод = (*конец == '\n');
        if (есть_перевод) *конец = '\0';
        char *л = строки;
        while (*л == ' ' || *л == '\t') л++;
        if (*л) {
            char *сост = nullptr;
            char *т = strtok_r(л, " \t\r", &сост);
            if (т && strcmp(т, "Шаблон") == 0) {
                // §101: блок обобщённого шаблона — тело пропускаем целиком
                // (загрузку/переразбор делает внедрить_шаблоны_библиотек отдельно).
                char *след = пропустить_блок_шаблона(&сост, конец, есть_перевод,
                                                      текст, размер);
                if (след) { строки = след; continue; }
            } else if (т && strcmp(т, "konda-интерфейс") == 0) {
                char *v = strtok_r(nullptr, " \t\r", &сост);
                if (v) версия = atoi(v);
            } else if (т && strcmp(т, "Е") == 0) {
                if (тек_тип) continue;  // битый файл — не диагностируем
                if (куда->число_типов >= ИНТ_МАКС_ТИПОВ) continue;
                тек_тип = &куда->типы[куда->число_типов++];
                memset(тек_тип, 0, sizeof(*тек_тип));
                char *имя = strtok_r(nullptr, " \t\r", &сост);
                if (имя) {
                    snprintf(тек_тип->имя, sizeof(тек_тип->имя), "%s", имя);
                }
            } else if (т && strcmp(т, "Вар") == 0 && тек_тип && !тек_тип->это_структура) {
                if (тек_тип->число_вариантов < ИНТ_МАКС_ВАРИАНТОВ) {
                    тек_вар = &тек_тип->варианты[тек_тип->число_вариантов++];
                    memset(тек_вар, 0, sizeof(*тек_вар));
                    char *имя = strtok_r(nullptr, " \t\r", &сост);
                    if (имя) snprintf(тек_вар->имя, sizeof(тек_вар->имя), "%s", имя);
                }
            } else if (т && strcmp(т, "ВП") == 0 && тек_вар
                       && тек_вар->число_полей < ИНТ_МАКС_ПОЛЕЙ_ВАРИАНТА) {
                char *p[6]; int ок = 1;
                for (int k = 0; k < 6; ++k) { p[k] = strtok_r(nullptr, " \t\r", &сост); if (!p[k]) ок = 0; }
                if (ок) {
                    ИнтПоле *пл = &тек_вар->поля[тек_вар->число_полей++];
                    пл->тип = тип_из_кейворда(p[0]);
                    пл->беззнаковый = atoi(p[1]);
                    пл->указатели = atoi(p[2]);
                    пл->срез = atoi(p[3]);
                    if (strcmp(p[4], "-") != 0)
                        snprintf(пл->имя_типа, sizeof(пл->имя_типа), "%s", p[4]);
                    snprintf(пл->имя, sizeof(пл->имя), "%s", p[5]);
                    if (версия >= 3) {   // §1: трейлинг-бит «возможно»
                        char *в = strtok_r(nullptr, " \t\r", &сост);
                        пл->возможно = в ? atoi(в) : 0;
                    }
                }
            } else if (т && strcmp(т, "КЕ") == 0) {
                тек_тип = nullptr; тек_вар = nullptr;
            } else if (т && strcmp(т, "С") == 0) {
                if (тек_тип) continue;
                if (куда->число_типов >= ИНТ_МАКС_ТИПОВ) continue;
                тек_тип = &куда->типы[куда->число_типов++];
                memset(тек_тип, 0, sizeof(*тек_тип));
                тек_тип->это_структура = 1;
                char *имя = strtok_r(nullptr, " \t\r", &сост);
                if (имя) snprintf(тек_тип->имя, sizeof(тек_тип->имя), "%s", имя);
                char *дестр = strtok_r(nullptr, " \t\r", &сост);
                if (дестр && strcmp(дестр, "-") != 0)
                    snprintf(тек_тип->деструктор, sizeof(тек_тип->деструктор), "%s", дестр);
            } else if (т && strcmp(т, "Поле") == 0 && тек_тип && тек_тип->это_структура
                       && тек_тип->число_полей < ИНТ_МАКС_ПОЛЕЙ) {
                char *p[7]; int ок = 1;
                for (int k = 0; k < 7; ++k) { p[k] = strtok_r(nullptr, " \t\r", &сост); if (!p[k]) ок = 0; }
                if (ок) {
                    ИнтПоле *пл = &тек_тип->поля[тек_тип->число_полей++];
                    пл->тип = тип_из_кейворда(p[0]);
                    пл->беззнаковый = atoi(p[1]);
                    пл->указатели = atoi(p[2]);
                    пл->срез = atoi(p[3]);
                    пл->массив = atoi(p[4]);   // §108: размер поля-массива
                    if (strcmp(p[5], "-") != 0)
                        snprintf(пл->имя_типа, sizeof(пл->имя_типа), "%s", p[5]);
                    snprintf(пл->имя, sizeof(пл->имя), "%s", p[6]);
                    if (версия >= 3) {   // §1: трейлинг-бит «возможно»
                        char *в = strtok_r(nullptr, " \t\r", &сост);
                        пл->возможно = в ? atoi(в) : 0;
                        char *рм = strtok_r(nullptr, " \t\r", &сост); // §108: размер массива
                        пл->размер_массива = рм ? atol(рм) : 0;
                    }
                }
            } else if (т && strcmp(т, "КС") == 0) {
                тек_тип = nullptr;
            } else if (т && strcmp(т, "ТФ") == 0) {   // §106: fp-псевдоним
                тек_тф = nullptr;
                if (куда->число_типфункций < ИНТ_МАКС_ТИПОВ) {
                    тек_тф = &куда->типфункции[куда->число_типфункций++];
                    memset(тек_тф, 0, sizeof(*тек_тф));
                    char *p[7]; int ок = 1;
                    for (int k = 0; k < 7; ++k) { p[k] = strtok_r(nullptr, " \t\r", &сост); if (!p[k]) ок = 0; }
                    if (ок) {
                        snprintf(тек_тф->имя, sizeof(тек_тф->имя), "%s", p[0]);
                        тек_тф->тип_возврата = тип_из_кейворда(p[1]);
                        тек_тф->беззнаковый_возврата = atoi(p[2]);
                        тек_тф->указатели_возврата = atoi(p[3]);
                        тек_тф->срез_возврата = atoi(p[4]);
                        if (strcmp(p[5], "-") != 0)
                            snprintf(тек_тф->имя_типа_возврата,
                                     sizeof(тек_тф->имя_типа_возврата), "%s", p[5]);
                        тек_тф->возможно_возврата = atoi(p[6]);
                    } else {
                        куда->число_типфункций--;   // битая запись — откат
                        тек_тф = nullptr;
                    }
                }
            } else if (т && strcmp(т, "ТФП") == 0 && тек_тф
                       && тек_тф->число_параметров < ИНТ_МАКС_ПОЛЕЙ) {
                char *p[6]; int ок = 1;
                for (int k = 0; k < 6; ++k) { p[k] = strtok_r(nullptr, " \t\r", &сост); if (!p[k]) ок = 0; }
                if (ок) {
                    ИнтПоле *ип = &тек_тф->параметры[тек_тф->число_параметров++];
                    ип->тип = тип_из_кейворда(p[0]);
                    ип->беззнаковый = atoi(p[1]);
                    ип->указатели = atoi(p[2]);
                    ип->срез = atoi(p[3]);
                    if (strcmp(p[4], "-") != 0)
                        snprintf(ип->имя_типа, sizeof(ип->имя_типа), "%s", p[4]);
                    ип->возможно = atoi(p[5]);
                }
            } else if (т && strcmp(т, "КТФ") == 0) {
                тек_тф = nullptr;
            } else if (т && (strcmp(т, "Конст") == 0 || strcmp(т, "Атом") == 0)) {
                int это_атом = (strcmp(т, "Атом") == 0);   // §107
                int нужно = это_атом ? 5 : 6;              // Атом: без значения
                char *p[6]; int ок = 1;
                for (int k = 0; k < нужно; ++k) { p[k] = strtok_r(nullptr, " \t\r", &сост); if (!p[k]) ок = 0; }
                if (ок && куда->число_глобалов < ИНТ_МАКС_ТИПОВ) {
                    ИнтГлобал *г = &куда->глобалы[куда->число_глобалов++];
                    memset(г, 0, sizeof(*г));
                    snprintf(г->имя, sizeof(г->имя), "%s", p[0]);
                    г->тип = тип_из_кейворда(p[1]);
                    г->беззнаковый = atoi(p[2]);
                    г->указатели = atoi(p[3]);
                    г->срез = atoi(p[4]);
                    г->атом = это_атом;
                    if (!это_атом) snprintf(г->значение, sizeof(г->значение), "%s", p[5]);
                }
            } else if (т && strcmp(т, "Ф") == 0) {
                if (в_функции) дин_массив_добавить(&куда->функции, &тек);
                memset(&тек, 0, sizeof(тек));
                в_функции = 1;
                char *имя = strtok_r(nullptr, " \t\r", &сост);
                if (имя) {
                    size_t n = strlen(имя);
                    if (n >= sizeof(тек.имя)) n = sizeof(тек.имя) - 1;
                    memcpy(тек.имя, имя, n);
                    тек.имя[n] = '\0';
                }
                // §37 п.6 — опциональный бит «возврат заимствован» (старые «.и»
                // без него → 0, владеющий; совместимость сохранена).
                char *заим = strtok_r(nullptr, " \t\r", &сост);
                тек.возврат_заимствован = заим ? atoi(заим) : 0;
            } else if (т && strcmp(т, "В") == 0) {
                char *p[5]; int ок = 1;
                int всего = (версия >= 2) ? 5 : 4;
                for (int k = 0; k < всего; ++k) { p[k] = strtok_r(nullptr, " \t\r", &сост); if (!p[k]) ок = 0; }
                if (ок && всего >= 4) {
                    тек.тип_возврата = тип_из_кейворда(p[0]);
                    тек.беззнаковый_возврата = atoi(p[1]);
                    тек.указатели_возврата = atoi(p[2]);
                    тек.срез_возврата = atoi(p[3]);
                    if (всего >= 5 && strcmp(p[4], "-") != 0)
                        snprintf(тек.имя_типа_возврата, sizeof(тек.имя_типа_возврата), "%s", p[4]);
                    if (версия >= 3) {   // §1: трейлинг-бит «возможно» возврата
                        char *в = strtok_r(nullptr, " \t\r", &сост);
                        тек.возможно_возврата = в ? atoi(в) : 0;
                    }
                }
            } else if (т && strcmp(т, "П") == 0) {
                char *p[8]; int ок = 1;
                int всего = (версия >= 2) ? 8 : 7;
                for (int k = 0; k < всего; ++k) { p[k] = strtok_r(nullptr, " \t\r", &сост); if (!p[k]) ок = 0; }
                if (ок && тек.число_параметров < ИНТ_МАКС_ПАРАМ) {
                    ИнтПараметр *ип = &тек.параметры[тек.число_параметров++];
                    ип->тип = тип_из_кейворда(p[0]);
                    ип->беззнаковый = atoi(p[1]);
                    ип->указатели = atoi(p[2]);
                    ип->срез = atoi(p[3]);
                    ип->массив = atoi(p[4]);
                    ип->владеет = atoi(p[5]);
                    ип->по_ссылке = atoi(p[6]);
                    if (всего >= 8 && strcmp(p[7], "-") != 0)
                        snprintf(ип->имя_типа, sizeof(ип->имя_типа), "%s", p[7]);
                    if (версия >= 3) {   // §1: трейлинг-бит «возможно»
                        char *в = strtok_r(nullptr, " \t\r", &сост);
                        ип->возможно = в ? atoi(в) : 0;
                    }
                }
            } else if (т && strcmp(т, "К") == 0) {
                if (в_функции) { дин_массив_добавить(&куда->функции, &тек); в_функции = 0; }
                memset(&тек, 0, sizeof(тек));
            }
        }
        строки = конец + 1;
        if (!есть_перевод) break;   // файл кончился без перевода строки
    }
    if (в_функции) дин_массив_добавить(&куда->функции, &тек);
    free(текст);
    (void)размер;
}

