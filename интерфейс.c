int собрать_интерфейсы_из_каталога(Узел *корень, const char *каталог,
                                    ТаблицаИнтерфейса *куда)
{
    if (!корень || !каталог || !каталог[0] || !куда) return 0;
    char путь_и[1024], путь_so[1024];
    char модули[32][128];
    int число = перечислить_модули_stdlib(каталог, модули, 32);
    for (int i = 0; i < число; ++i) {
        const char *основа = модули[i];
        snprintf(путь_и, sizeof(путь_и), "%s/%s.и", каталог, основа);
        if (!файл_есть(путь_и)) continue;
        // Реконструируем ТОЛЬКО новые типы; слоты НЕ переиспользуем (см. §72-
        // комментарий в собрать_интерфейсы): токен узла алиасит куда->типы[k].имя,
        // а сброс+перезагрузка следующим модулем затёрли бы имя.
        size_t было_типов = куда->число_типов;
        size_t было_тф = куда->число_типфункций;
        size_t было_глоб = куда->число_глобалов;
        загрузить_интерфейс(путь_и, куда);
        for (size_t k = было_типов; k < куда->число_типов; ++k) {
            if (!имя_типа_уже_в_корне(корень, куда->типы[k].имя))
                узел_добавить_ребёнка(корень, узел_из_инт_типа(&куда->типы[k]));
        }
        for (size_t k = было_тф; k < куда->число_типфункций; ++k) {  // §106
            if (!имя_типфункции_уже_в_корне(корень, куда->типфункции[k].имя))
                узел_добавить_ребёнка(корень, узел_из_инт_типфункции(&куда->типфункции[k]));
        }
        for (size_t k = было_глоб; k < куда->число_глобалов; ++k) {  // §107
            if (!имя_глобала_уже_в_корне(корень, куда->глобалы[k].имя))
                узел_добавить_ребёнка(корень, узел_из_инт_глобала(&куда->глобалы[k]));
        }
        snprintf(путь_so, sizeof(путь_so), "%s/%s." КОНДА_СУФФИКС_БИБЛ, каталог, основа);
        if (файл_есть(путь_so)) {
            char абс[1024];
            snprintf(абс, sizeof(абс), "%.1023s", путь_so);
            дин_массив_добавить(&куда->библиотеки, абс);
        }
    }
    return 1;
}
