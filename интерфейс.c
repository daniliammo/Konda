// Konda-интерфейс библиотек: эмиссия «.и», чтение и сбор у потребителя.
// Синтаксически простой построчный формат — отдельный маленький ридер, чтобы не
// трогать основной парсер (он не умеет прототипы без тела).

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/stat.h>
#include <dirent.h>

#include "интерфейс.h"

// Перечислить модули stdlib в каталоге вывода: базовые имена всех «*.и» (без
// суффикса). Каждый модуль stdlib порождает «X.и/X.h/X.so/X.c» — опознаём по
// «X.и». Заменяет прежний хардкод-список {"файл"} в трёх местах: новый модуль
// (строки/хеш/…) подхватывается автоматически, без правок загрузчика. Возвращает
// число найденных (≤ макс); имена (UTF-8, до 127 байт) копируются в out.
int перечислить_модули_stdlib(const char *каталог, char (*out)[128], int макс)
{
    if (!каталог || !каталог[0] || !out || макс <= 0) return 0;
    DIR *дир = opendir(каталог);
    if (!дир) return 0;
    const char суффикс[] = ".и";              // UTF-8: '.'(1) + «и»(2) = 3 байта
    const size_t дл_суф = sizeof(суффикс) - 1;
    int число = 0;
    struct dirent *вход;
    while (число < макс && (вход = readdir(дир)) != NULL) {
        const char *имя = вход->d_name;
        size_t дл = strlen(имя);
        if (дл <= дл_суф) continue;
        if (memcmp(имя + дл - дл_суф, суффикс, дл_суф) != 0) continue;
        size_t база = дл - дл_суф;
        if (база >= 128) continue;            // слишком длинное имя — пропуск
        memcpy(out[число], имя, база);
        out[число][база] = '\0';
        число++;
    }
    closedir(дир);
    return число;
}

