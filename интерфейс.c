// Konda-интерфейс библиотек: эмиссия «.и», чтение и сбор у потребителя.
// Синтаксически простой построчный формат — отдельный маленький ридер, чтобы не
// трогать основной парсер (он не умеет прототипы без тела).

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/stat.h>

#include "интерфейс.h"

// ─── таблица ─────────────────────────────────────────────────────────────────

struct ТаблицаИнтерфейса {
    ДинМассив функции;     // ИнтФункция
    ДинМассив библиотеки;  // char[512] — пути к .so для линковки
    // Именованные типы — ФИКСИРОВАННЫЙ массив (не ДинМассив): ридер строит на
    // нём AST-узлы, чьи Токены указывают внутрь записей; адреса обязаны быть
    // стабильны на всё время жизни таблицы. Ограничение в 32 типа на интерфейс.
    ИнтТип типы[ИНТ_МАКС_ТИПОВ];
    size_t число_типов;
};

ТаблицаИнтерфейса *интерфейс_создать(void)
{
    ТаблицаИнтерфейса *т = calloc(1, sizeof(*т));
    if (!т) { perror("calloc"); exit(1); }
    дин_массив_инициализировать(&т->функции, sizeof(ИнтФункция));
    дин_массив_инициализировать(&т->библиотеки, 512);
    return т;
}

void интерфейс_освободить(ТаблицаИнтерфейса *т)
{
    if (!т) return;
    дин_массив_освободить(&т->функции);
    дин_массив_освободить(&т->библиотеки);
    free(т);
}

size_t интерфейс_число(const ТаблицаИнтерфейса *т) { return т ? т->функции.длина : 0; }

const ИнтФункция *интерфейс_получить(const ТаблицаИнтерфейса *т, size_t i)
{
    if (!т || i >= т->функции.длина) return nullptr;
    return (const ИнтФункция *)((char *)т->функции.данные + i * т->функции.размер_элемента);
}

size_t интерфейс_тип_число(const ТаблицаИнтерфейса *т) { return т ? т->число_типов : 0; }

const ИнтТип *интерфейс_тип_получить(const ТаблицаИнтерфейса *т, size_t i)
{
    if (!т || i >= т->число_типов) return nullptr;
    return &т->типы[i];
}

const ИнтТип *интерфейс_тип_найти(const ТаблицаИнтерфейса *т, const char *имя,
                                   size_t длина)
{
    if (!т) return nullptr;
    for (size_t i = 0; i < т->число_типов; ++i) {
        if (strlen(т->типы[i].имя) == длина
            && memcmp(т->типы[i].имя, имя, длина) == 0)
            return &т->типы[i];
    }
    return nullptr;
}

size_t интерфейс_число_библиотек(const ТаблицаИнтерфейса *т) { return т ? т->библиотеки.длина : 0; }

const char *интерфейс_библиотека(const ТаблицаИнтерфейса *т, size_t i)
{
    if (!т || i >= т->библиотеки.длина) return nullptr;
    return (const char *)((char *)т->библиотеки.данные + i * т->библиотеки.размер_элемента);
}

// ─── отображение тип ↔ ключевое слово ───────────────────────────────────────

static const char *тип_в_кейворд(ТипТокена т)
{
    switch (т) {
        case ТОКЕН_ЦЕЛОЕ8:  return "целое8";
        case ТОКЕН_ЦЕЛОЕ16: return "целое16";
        case ТОКЕН_ЦЕЛОЕ32: return "целое32";
        case ТОКЕН_ЦЕЛОЕ64: return "целое64";
        case ТОКЕН_БАЙТ:        return "байт";
        case ТОКЕН_ВЕЩЕСТВЕННОЕ: return "вещественное";
        case ТОКЕН_ВЕЩЕСТВЕННОЕ64: return "вещественное64";
        case ТОКЕН_ТИП_СИМВОЛ: return "символ";
        case ТОКЕН_ЛОГИЧЕСКИЙ: return "логический";
        case ТОКЕН_НИЧЕГО:     return "ничего";
        case ТОКЕН_СТРУКТУРА:   return "структура";
        case ТОКЕН_ПЕРЕЧИСЛЕНИЕ: return "перечисление";
        default: return "целое32";  // прочие сюда не доходят (пропускаются)
    }
}

static ТипТокена тип_из_кейворда(const char *с)
{
    if (strcmp(с, "целое8") == 0)  return ТОКЕН_ЦЕЛОЕ8;
    if (strcmp(с, "целое16") == 0) return ТОКЕН_ЦЕЛОЕ16;
    if (strcmp(с, "целое32") == 0) return ТОКЕН_ЦЕЛОЕ32;
    if (strcmp(с, "целое64") == 0) return ТОКЕН_ЦЕЛОЕ64;
    if (strcmp(с, "байт") == 0)         return ТОКЕН_БАЙТ;
    if (strcmp(с, "вещественное") == 0)   return ТОКЕН_ВЕЩЕСТВЕННОЕ;
    if (strcmp(с, "вещественное64") == 0) return ТОКЕН_ВЕЩЕСТВЕННОЕ64;
    if (strcmp(с, "символ") == 0)     return ТОКЕН_ТИП_СИМВОЛ;
    if (strcmp(с, "логический") == 0) return ТОКЕН_ЛОГИЧЕСКИЙ;
    if (strcmp(с, "ничего") == 0)     return ТОКЕН_НИЧЕГО;
    if (strcmp(с, "структура") == 0)    return ТОКЕН_СТРУКТУРА;
    if (strcmp(с, "перечисление") == 0) return ТОКЕН_ПЕРЕЧИСЛЕНИЕ;
    return ТОКЕН_НЕИЗВЕСТНЫЙ;
}

// Ключевое слово типа с учётом именованных (структура/перечисление). Для эмиссии
// сигнатур: имя самого типа идёт отдельным полем следом.
static const char *тип_в_кейворд_имен(ТипТокена т)
{
    if (т == ТОКЕН_СТРУКТУРА)    return "структура";
    if (т == ТОКЕН_ПЕРЕЧИСЛЕНИЕ) return "перечисление";
    return тип_в_кейворд(т);
}

static int именованный_тип(ТипТокена т)
{
    return т == ТОКЕН_СТРУКТУРА || т == ТОКЕН_ПЕРЕЧИСЛЕНИЕ || т == ТОКЕН_ФУНКУКАЗАТЕЛЬ;
}

// ─── эмиссия ─────────────────────────────────────────────────────────────────

static void эмит_число(БуферКода *б, int v)
{
    char буф[16];
    snprintf(буф, sizeof(буф), "%d", v);
    буфер_кода_добавить(б, буф);
}

// Носитель-тип (поле/параметр/возврат) пригоден для «.и»? Именованные типы
// должны быть НАПЕЧАТАНЫ ранее (иначе потребитель не восстановит ссылку); для
// структур/перечислений смотрим их описание в корне. v1: запрещены
// поля-массивы (размер не сериализуется) и срезы с именованным элементом.
static const Узел *узел_именованного_типа(const Узел *корень, const Узел *н)
{
    if ((н->тип_данных != ТОКЕН_СТРУКТУРА
         && н->тип_данных != ТОКЕН_ПЕРЕЧИСЛЕНИЕ)
        || н->имя_типа.длина == 0) return nullptr;
    for (size_t i = 0; i < узел_число_детей(корень); ++i) {
        const Узел *т = узел_ребёнок(корень, i);
        if (!т) continue;
        if ((н->тип_данных == ТОКЕН_СТРУКТУРА && т->тип != УЗЕЛ_СТРУКТУРА)
            || (н->тип_данных == ТОКЕН_ПЕРЕЧИСЛЕНИЕ && т->тип != УЗЕЛ_ПЕРЕЧИСЛЕНИЕ))
            continue;
        if (т->токен.длина == н->имя_типа.длина
            && memcmp(т->токен.начало, н->имя_типа.начало, н->имя_типа.длина) == 0)
            return т;
    }
    return nullptr;
}

// Поле-примитив (с указателями): срезы/массивы/именованные типы не пересекают
// границу .и (v1 — владение/размеры через границу не передаются).
static int поле_примитивно(const Узел *п)
{
    if (п->срез || п->массив) return 0;
    if (п->тип_данных == ТОКЕН_СТРУКТУРА
        || п->тип_данных == ТОКЕН_ПЕРЕЧИСЛЕНИЕ
        || п->тип_данных == ТОКЕН_ФУНКУКАЗАТЕЛЬ) return 0;
    return п->тип_данных != ТОКЕН_НЕИЗВЕСТНЫЙ;
}

// Структура экспортируется, если все её поля примитивны (и она не внешний
// тип/союз). Иначе C-layout завязан на внутренние типы — остаётся непрозрачной.
static int структура_года(const Узел *с)
{
    if (с->внешняя || с->это_союз) return 0;
    for (size_t j = 0; j < узел_число_детей(с); ++j) {
        const Узел *поле = узел_ребёнок(с, j);
        if (!поле || поле->тип != УЗЕЛ_ПАРАМЕТР) continue;
        if (!поле_примитивно(поле)) return 0;
    }
    return 1;
}

// Sum-перечисление экспортируется, если payload всех вариантов примитивен
// (варианты без данных допустимы).
static int перечисление_года(const Узел *п)
{
    int sum = 0;
    for (size_t v = 0; v < узел_число_детей(п); ++v) {
        const Узел *вар = узел_ребёнок(п, v);
        if (!вар || вар->тип != УЗЕЛ_ВАРИАНТ) continue;
        for (size_t k = 0; k < узел_число_детей(вар); ++k) {
            const Узел *пл = узел_ребёнок(вар, k);
            if (!пл || пл->тип != УЗЕЛ_ПАРАМЕТР) continue;
            if (!поле_примитивно(пл)) return 0;
            sum = 1;
        }
    }
    return sum;   // только sum-перечисления (простое C-enum остаётся в .h)
}

// Проверка: функцию можно выразить в «.и» (v2). Указатели на функцию как тип
// возврата/параметра пока непрозрачны (сложная сериализация) — такие пропускаем;
// структуры и sum-перечисления поддержаны (несут имя типа).
static int функция_экспортируема(const Узел *корень, const Узел *ф)
{
    if (ф->тип_данных == ТОКЕН_ФУНКУКАЗАТЕЛЬ) return 0;
    if (ф->это_оператор) return 0;      // перегрузки манглятся — не экспортируются
    // Возврат: именованный тип обязан быть напечатан и годен (см. параметры).
    if (ф->тип_данных == ТОКЕН_СТРУКТУРА || ф->тип_данных == ТОКЕН_ПЕРЕЧИСЛЕНИЕ) {
        const Узел *т = узел_именованного_типа(корень, ф);
        if (!т) return 0;
        if (т->тип == УЗЕЛ_СТРУКТУРА ? !структура_года(т) : !перечисление_года(т))
            return 0;
    }
    size_t всего = узел_число_детей(ф);
    for (size_t j = 0; j + 1 < всего; ++j) {
        const Узел *п = узел_ребёнок(ф, j);
        if (!п || п->тип != УЗЕЛ_ПАРАМЕТР) continue;
        if (п->тип_данных == ТОКЕН_ФУНКУКАЗАТЕЛЬ) return 0;
        if (п->срез && (п->тип_данных == ТОКЕН_СТРУКТУРА
                        || п->тип_данных == ТОКЕН_ПЕРЕЧИСЛЕНИЕ)) return 0;
        if (п->тип_данных == ТОКЕН_СТРУКТУРА
            || п->тип_данных == ТОКЕН_ПЕРЕЧИСЛЕНИЕ) {
            const Узел *т = узел_именованного_типа(корень, п);
            if (!т) return 0;
            if (т->тип == УЗЕЛ_СТРУКТУРА ? !структура_года(т) : !перечисление_года(т))
                return 0;
        }
    }
    return 1;
}

// Имя-или-«-»: для именованных типов пишем имя_типа узла, иначе «-».
static void эмит_имя_типа(БуферКода *б, const Узел *у)
{
    if (именованный_тип(у->тип_данных) && у->имя_типа.длина > 0) {
        буфер_кода_добавить(б, " ");
        буфер_кода_добавить_отрезок(б, у->имя_типа.начало, у->имя_типа.длина);
    } else {
        буфер_кода_добавить(б, " -");
    }
}

// Сериализация одного носителя-типа (возврат функции / параметр / поле):
// «<тип-кейворд> <беззн> <указ> <срез> [<массив>] <имя-типа|->».
static void эмит_носитель_типа(БуферКода *б, const Узел *у, int с_массивом)
{
    буфер_кода_добавить(б, тип_в_кейворд_имен(у->тип_данных));
    буфер_кода_добавить(б, " "); эмит_число(б, у->беззнаковый);
    буфер_кода_добавить(б, " "); эмит_число(б, у->указатели);
    буфер_кода_добавить(б, " "); эмит_число(б, у->срез);
    if (с_массивом) { буфер_кода_добавить(б, " "); эмит_число(б, у->массив); }
}

void эмит_интерфейс(const Узел *корень, БуферКода *буфер)
{
    буфер_кода_добавить(буфер, "konda-интерфейс 2\n");

    // 1. Sum-перечисления — только «годные» (payload примитивен). Порядок
    //    неважен загрузчику, но важен документации: типы раньше функций.
    //    «Е <имя>» / «Вар <имя>» / «ВП <носитель> <имя-поля>» / «КЕ».
    for (size_t i = 0; i < узел_число_детей(корень); ++i) {
        const Узел *п = узел_ребёнок(корень, i);
        if (!п || п->тип != УЗЕЛ_ПЕРЕЧИСЛЕНИЕ || п->токен.длина == 0) continue;
        if (!перечисление_года(п)) continue;
        буфер_кода_добавить(буфер, "Е ");
        буфер_кода_добавить_отрезок(буфер, п->токен.начало, п->токен.длина);
        буфер_кода_добавить(буфер, "\n");
        for (size_t v = 0; v < узел_число_детей(п); ++v) {
            const Узел *вар = узел_ребёнок(п, v);
            if (!вар || вар->тип != УЗЕЛ_ВАРИАНТ) continue;
            буфер_кода_добавить(буфер, "Вар ");
            буфер_кода_добавить_отрезок(буфер, вар->токен.начало, вар->токен.длина);
            буфер_кода_добавить(буфер, "\n");
            for (size_t k = 0; k < узел_число_детей(вар); ++k) {
                const Узел *пл = узел_ребёнок(вар, k);
                if (!пл || пл->тип != УЗЕЛ_ПАРАМЕТР) continue;
                буфер_кода_добавить(буфер, "ВП ");
                эмит_носитель_типа(буфер, пл, 0);
                эмит_имя_типа(буфер, пл);
                буфер_кода_добавить(буфер, " ");
                буфер_кода_добавить_отрезок(буфер, пл->токен.начало, пл->токен.длина);
                буфер_кода_добавить(буфер, "\n");
            }
        }
        буфер_кода_добавить(буфер, "КЕ\n");
    }

    // 2. Структуры (только годные: без союзов/внешних, поля примитивны):
    //    «С <имя> <деструктор|->» / «Поле <носитель+массив> <имя-типа|->
    //    <имя-поля>» / «КС». Деструктор нужен для RAII у потребителя.
    for (size_t i = 0; i < узел_число_детей(корень); ++i) {
        const Узел *с = узел_ребёнок(корень, i);
        if (!с || с->тип != УЗЕЛ_СТРУКТУРА || с->токен.длина == 0) continue;
        if (!структура_года(с)) continue;
        буфер_кода_добавить(буфер, "С ");
        буфер_кода_добавить_отрезок(буфер, с->токен.начало, с->токен.длина);
        if (с->имя_типа.длина > 0) {  // деструктор [удалить=…]
            буфер_кода_добавить(буфер, " ");
            буфер_кода_добавить_отрезок(буфер, с->имя_типа.начало, с->имя_типа.длина);
        } else {
            буфер_кода_добавить(буфер, " -");
        }
        буфер_кода_добавить(буфер, "\n");
        for (size_t j = 0; j < узел_число_детей(с); ++j) {
            const Узел *поле = узел_ребёнок(с, j);
            if (!поле || поле->тип != УЗЕЛ_ПАРАМЕТР) continue;
            буфер_кода_добавить(буфер, "Поле ");
            эмит_носитель_типа(буфер, поле, 1);       // с массивом
            эмит_имя_типа(буфер, поле);
            буфер_кода_добавить(буфер, " ");
            буфер_кода_добавить_отрезок(буфер, поле->токен.начало, поле->токен.длина);
            буфер_кода_добавить(буфер, "\n");
        }
        буфер_кода_добавить(буфер, "КС\n");
    }

    // 3. Функции. «Ф имя» / «В <носитель> <имя-типа|->» / «П <носитель+массив>
    //    <владеет> <по_ссылке> <имя-типа|->» / «К».
    for (size_t i = 0; i < узел_число_детей(корень); ++i) {
        const Узел *ф = узел_ребёнок(корень, i);
        if (!ф || ф->тип != УЗЕЛ_ФУНКЦИЯ) continue;
        if (ф->статический || ф->это_main) continue;      // не экспортируется
        if (ф->токен.длина == 0) continue;
        if (!функция_экспортируема(корень, ф)) continue;

        буфер_кода_добавить(буфер, "Ф ");
        буфер_кода_добавить_отрезок(буфер, ф->токен.начало, ф->токен.длина);
        буфер_кода_добавить(буфер, "\n");

        буфер_кода_добавить(буфер, "В ");
        эмит_носитель_типа(буфер, ф, 0);
        эмит_имя_типа(буфер, ф);
        буфер_кода_добавить(буфер, "\n");

        size_t всего = узел_число_детей(ф);
        for (size_t j = 0; j + 1 < всего; ++j) {
            const Узел *п = узел_ребёнок(ф, j);
            if (!п || п->тип != УЗЕЛ_ПАРАМЕТР) continue;
            буфер_кода_добавить(буфер, "П ");
            эмит_носитель_типа(буфер, п, 1);              // с массивом
            буфер_кода_добавить(буфер, " "); эмит_число(буфер, п->владеет);
            буфер_кода_добавить(буфер, " "); эмит_число(буфер, п->по_ссылке);
            эмит_имя_типа(буфер, п);
            буфер_кода_добавить(буфер, "\n");
        }
        буфер_кода_добавить(буфер, "К\n");
    }
}

// ─── чтение ──────────────────────────────────────────────────────────────────

static int файл_есть(const char *путь)
{
    struct stat st;
    return stat(путь, &st) == 0 && S_ISREG(st.st_mode);
}

// Токен{начало,длина} из имени в стабильной памяти (таблица «.и» — фиксированный
// массив типы[], адреса не двигаются всё время жизни таблицы).
static void токен_из_буфера(Токен *т, const char *имя)
{
    т->начало = имя;
    т->длина = strlen(имя);
}

// ИнтПоле (поле структуры / payload варианта) → AST-узел УЗЕЛ_ПАРАМЕТР.
static Узел *параметр_из_инт(const ИнтПоле *п)
{
    Узел *у = узел_создать(УЗЕЛ_ПАРАМЕТР);
    у->тип_данных = п->тип;
    у->беззнаковый = п->беззнаковый;
    у->указатели = п->указатели;
    у->срез = п->срез;
    токен_из_буфера(&у->токен, п->имя);
    if (п->имя_типа[0]) токен_из_буфера(&у->имя_типа, п->имя_типа);
    return у;
}

// Реконструкция именованного типа библиотеки в полноценный AST-узел
// (из_библиотеки): семантика/кодоген работают штатно, но C-определение не
// эмитится — typedef приходит из «#содержит»-заголовка библиотеки.
static Узел *узел_из_инт_типа(const ИнтТип *и)
{
    Узел *у = узел_создать(и->это_структура ? УЗЕЛ_СТРУКТУРА : УЗЕЛ_ПЕРЕЧИСЛЕНИЕ);
    у->из_библиотеки = 1;
    токен_из_буфера(&у->токен, и->имя);
    if (и->это_структура) {
        // «[удалить = Имя]» несёт с->имя_типа (как у обычной декларации).
        if (и->деструктор[0]) токен_из_буфера(&у->имя_типа, и->деструктор);
        for (size_t k = 0; k < и->число_полей; ++k)
            узел_добавить_ребёнка(у, параметр_из_инт(&и->поля[k]));
    } else {
        for (size_t v = 0; v < и->число_вариантов; ++v) {
            const ИнтВариант *в = &и->варианты[v];
            Узел *вар = узел_создать(УЗЕЛ_ВАРИАНТ);
            токен_из_буфера(&вар->токен, в->имя);
            for (size_t k = 0; k < в->число_полей; ++k)
                узел_добавить_ребёнка(вар, параметр_из_инт(&в->поля[k]));
            узел_добавить_ребёнка(у, вар);
        }
    }
    return у;
}

// Разбор построчного «.и». Команды: «Е/Вар/ВП/КЕ» — sum-перечисление,
// «С/Поле/КС» — структура, «Ф/В/П/К» — функция; тип-строка «имя-типа|-» есть
// в v2 (версия из заголовка «konda-интерфейс N»; v1: «В» — 4 токена, «П» — 7).
// Прочее (старые версии, доки) — пропускается.
static void загрузить_интерфейс(const char *путь, ТаблицаИнтерфейса *куда)
{
    size_t размер = 0;
    char *текст = прочитать_файл((char *)путь, &размер);
    if (!текст) return;

    int версия = 1;          // «konda-интерфейс N»; без заголовка — как v1
    ИнтФункция тек;
    memset(&тек, 0, sizeof(тек));
    ИнтТип *тек_тип = nullptr;   // накапливаемый именованный тип
    ИнтВариант *тек_вар = nullptr;
    int в_функции = 0;

    char *строки = текст;
    while (*строки) {
        char *конец = строки;
        while (*конец && *конец != '\n') конец++;
        int есть_перевод = (*конец == '\n');
        if (есть_перевод) *конец = '\0';
        char *л = строки;
        while (*л == ' ' || *л == '\t') л++;
        if (*л) {
            char *сост = nullptr;
            char *т = strtok_r(л, " \t\r", &сост);
            if (т && strcmp(т, "konda-интерфейс") == 0) {
                char *v = strtok_r(nullptr, " \t\r", &сост);
                if (v) версия = atoi(v);
            } else if (т && strcmp(т, "Е") == 0) {
                if (тек_тип) continue;  // битый файл — не диагностируем
                if (куда->число_типов >= ИНТ_МАКС_ТИПОВ) continue;
                тек_тип = &куда->типы[куда->число_типов++];
                memset(тек_тип, 0, sizeof(*тек_тип));
                char *имя = strtok_r(nullptr, " \t\r", &сост);
                if (имя) {
                    snprintf(тек_тип->имя, sizeof(тек_тип->имя), "%s", имя);
                }
            } else if (т && strcmp(т, "Вар") == 0 && тек_тип && !тек_тип->это_структура) {
                if (тек_тип->число_вариантов < ИНТ_МАКС_ВАРИАНТОВ) {
                    тек_вар = &тек_тип->варианты[тек_тип->число_вариантов++];
                    memset(тек_вар, 0, sizeof(*тек_вар));
                    char *имя = strtok_r(nullptr, " \t\r", &сост);
                    if (имя) snprintf(тек_вар->имя, sizeof(тек_вар->имя), "%s", имя);
                }
            } else if (т && strcmp(т, "ВП") == 0 && тек_вар
                       && тек_вар->число_полей < ИНТ_МАКС_ПОЛЕЙ_ВАРИАНТА) {
                char *p[6]; int ок = 1;
                for (int k = 0; k < 6; ++k) { p[k] = strtok_r(nullptr, " \t\r", &сост); if (!p[k]) ок = 0; }
                if (ок) {
                    ИнтПоле *пл = &тек_вар->поля[тек_вар->число_полей++];
                    пл->тип = тип_из_кейворда(p[0]);
                    пл->беззнаковый = atoi(p[1]);
                    пл->указатели = atoi(p[2]);
                    пл->срез = atoi(p[3]);
                    if (strcmp(p[4], "-") != 0)
                        snprintf(пл->имя_типа, sizeof(пл->имя_типа), "%s", p[4]);
                    snprintf(пл->имя, sizeof(пл->имя), "%s", p[5]);
                }
            } else if (т && strcmp(т, "КЕ") == 0) {
                тек_тип = nullptr; тек_вар = nullptr;
            } else if (т && strcmp(т, "С") == 0) {
                if (тек_тип) continue;
                if (куда->число_типов >= ИНТ_МАКС_ТИПОВ) continue;
                тек_тип = &куда->типы[куда->число_типов++];
                memset(тек_тип, 0, sizeof(*тек_тип));
                тек_тип->это_структура = 1;
                char *имя = strtok_r(nullptr, " \t\r", &сост);
                if (имя) snprintf(тек_тип->имя, sizeof(тек_тип->имя), "%s", имя);
                char *дестр = strtok_r(nullptr, " \t\r", &сост);
                if (дестр && strcmp(дестр, "-") != 0)
                    snprintf(тек_тип->деструктор, sizeof(тек_тип->деструктор), "%s", дестр);
            } else if (т && strcmp(т, "Поле") == 0 && тек_тип && тек_тип->это_структура
                       && тек_тип->число_полей < ИНТ_МАКС_ПОЛЕЙ) {
                char *p[7]; int ок = 1;
                for (int k = 0; k < 7; ++k) { p[k] = strtok_r(nullptr, " \t\r", &сост); if (!p[k]) ок = 0; }
                if (ок) {
                    ИнтПоле *пл = &тек_тип->поля[тек_тип->число_полей++];
                    пл->тип = тип_из_кейворда(p[0]);
                    пл->беззнаковый = atoi(p[1]);
                    пл->указатели = atoi(p[2]);
                    пл->срез = atoi(p[3]);
                    if (strcmp(p[5], "-") != 0)
                        snprintf(пл->имя_типа, sizeof(пл->имя_типа), "%s", p[5]);
                    snprintf(пл->имя, sizeof(пл->имя), "%s", p[6]);
                }
            } else if (т && strcmp(т, "КС") == 0) {
                тек_тип = nullptr;
            } else if (т && strcmp(т, "Ф") == 0) {
                if (в_функции) дин_массив_добавить(&куда->функции, &тек);
                memset(&тек, 0, sizeof(тек));
                в_функции = 1;
                char *имя = strtok_r(nullptr, " \t\r", &сост);
                if (имя) {
                    size_t n = strlen(имя);
                    if (n >= sizeof(тек.имя)) n = sizeof(тек.имя) - 1;
                    memcpy(тек.имя, имя, n);
                    тек.имя[n] = '\0';
                }
            } else if (т && strcmp(т, "В") == 0) {
                char *p[5]; int ок = 1;
                int всего = (версия >= 2) ? 5 : 4;
                for (int k = 0; k < всего; ++k) { p[k] = strtok_r(nullptr, " \t\r", &сост); if (!p[k]) ок = 0; }
                if (ок && всего >= 4) {
                    тек.тип_возврата = тип_из_кейворда(p[0]);
                    тек.беззнаковый_возврата = atoi(p[1]);
                    тек.указатели_возврата = atoi(p[2]);
                    тек.срез_возврата = atoi(p[3]);
                    if (всего >= 5 && strcmp(p[4], "-") != 0)
                        snprintf(тек.имя_типа_возврата, sizeof(тек.имя_типа_возврата), "%s", p[4]);
                }
            } else if (т && strcmp(т, "П") == 0) {
                char *p[8]; int ок = 1;
                int всего = (версия >= 2) ? 8 : 7;
                for (int k = 0; k < всего; ++k) { p[k] = strtok_r(nullptr, " \t\r", &сост); if (!p[k]) ок = 0; }
                if (ок && тек.число_параметров < ИНТ_МАКС_ПАРАМ) {
                    ИнтПараметр *ип = &тек.параметры[тек.число_параметров++];
                    ип->тип = тип_из_кейворда(p[0]);
                    ип->беззнаковый = atoi(p[1]);
                    ип->указатели = atoi(p[2]);
                    ип->срез = atoi(p[3]);
                    ип->массив = atoi(p[4]);
                    ип->владеет = atoi(p[5]);
                    ип->по_ссылке = atoi(p[6]);
                    if (всего >= 8 && strcmp(p[7], "-") != 0)
                        snprintf(ип->имя_типа, sizeof(ип->имя_типа), "%s", p[7]);
                }
            } else if (т && strcmp(т, "К") == 0) {
                if (в_функции) { дин_массив_добавить(&куда->функции, &тек); в_функции = 0; }
                memset(&тек, 0, sizeof(тек));
            }
        }
        строки = конец + 1;
        if (!есть_перевод) break;   // файл кончился без перевода строки
    }
    if (в_функции) дин_массив_добавить(&куда->функции, &тек);
    free(текст);
    (void)размер;
}

// ─── сбор у потребителя ─────────────────────────────────────────────────────

// Извлекает из токена препроцессора «#содержит "имя"» локальное имя заголовка
// (не системное «<>»). Ядро — общая для Узел (УЗЕЛ_ПРЕПРОЦЕССОР) и Токен.
static int локальный_заголовок_из_текста(const char *начало, size_t длина,
                                          char *имя, size_t cap)
{
    char строка[1024];
    size_t дл = длина < sizeof(строка) - 1 ? длина : sizeof(строка) - 1;
    memcpy(строка, начало, дл);
    строка[дл] = '\0';
    const char *p = строка;
    while (*p == ' ' || *p == '\t') p++;
    if (*p != '#') return 0;
    p++;
    while (*p == ' ' || *p == '\t') p++;
    // «содержит» или «include»
    if (strncmp(p, "содержит", strlen("содержит")) == 0) p += strlen("содержит");
    else if (strncmp(p, "include", 7) == 0) p += 7;
    else return 0;
    while (*p == ' ' || *p == '\t') p++;
    if (*p != '"') return 0;  // только локальные «"…"»
    p++;
    size_t k = 0;
    while (*p && *p != '"' && *p != '\n' && k + 1 < cap) имя[k++] = *p++;
    имя[k] = '\0';
    return k > 0;
}

// Извлекает из «#содержит "имя"» локальное имя заголовка (не системное «<>»).
static int локальный_заголовок(const Узел *узел, char *имя, size_t cap)
{
    return локальный_заголовок_из_текста(узел->токен.начало, узел->токен.длина,
                                          имя, cap);
}

// Имена именованных типов (структур/перечислений) из «.и» библиотеки.
// Вызывается ДО разбора: парсер должен распознавать «Имя п = …» для типов,
// которые придут из интерфейсов (реконструкция узлов — позже, в
// собрать_интерфейсы).
void интерфейс_имена_типов(const char *путь, ИменаСтруктур *структуры,
                            ИменаПеречислений *перечисления)
{
    size_t размер = 0;
    char *текст = прочитать_файл((char *)путь, &размер);
    if (!текст) return;
    char *строки = текст;
    while (*строки) {
        char *конец = строки;
        while (*конец && *конец != '\n') конец++;
        int есть_перевод = (*конец == '\n');
        if (есть_перевод) *конец = '\0';
        char *л = строки;
        while (*л == ' ' || *л == '\t') л++;
        char *сост = nullptr;
        char *т = strtok_r(л, " \t\r", &сост);
        if (т && (strcmp(т, "Е") == 0 || strcmp(т, "С") == 0)) {
            char *имя = strtok_r(nullptr, " \t\r", &сост);
            if (имя) {
                if (strcmp(т, "С") == 0)
                    имена_структур_добавить(структуры, имя, strlen(имя));
                else
                    имена_перечислений_добавить(перечисления, имя, strlen(имя));
            }
        }
        if (!есть_перевод) break;
        строки = конец + 1;
    }
    free(текст);
}

// Сканирует токены файла на локальные «#содержит "X.h"»; для каждого соседнего
// «X.и» добавляет имена содержащихся типов в списки парсера (см. выше).
void собрать_имена_типов_интерфейсов(МассивТокенов *токены, const char *база_путей,
                                      ИменаСтруктур *структуры,
                                      ИменаПеречислений *перечисления)
{
    if (!токены || !структуры || !перечисления) return;
    const char *база = (база_путей && база_путей[0]) ? база_путей : ".";
    size_t n = токены->базовый.длина;
    for (size_t i = 0; i < n; ++i) {
        Токен *t = дин_массив_получить(&токены->базовый, i);
        if (!t || t->тип != ТОКЕН_ПРЕПРОЦЕССОР) continue;
        char имя[512];
        if (!локальный_заголовок_из_текста(t->начало, t->длина, имя, sizeof(имя)))
            continue;
        char основа[512];
        snprintf(основа, sizeof(основа), "%s", имя);
        char *точка = strrchr(основа, '.');
        if (точка && strcmp(точка, ".h") == 0) *точка = '\0';
        char путь_и[1024];
        snprintf(путь_и, sizeof(путь_и), "%s/%s.и", база, основа);
        if (файл_есть(путь_и))
            интерфейс_имена_типов(путь_и, структуры, перечисления);
    }
}

int собрать_интерфейсы(Узел *корень, const char *база_путей,
                       ТаблицаИнтерфейса *куда)
{
    if (!корень || !куда) return 0;
    const char *база = (база_путей && база_путей[0]) ? база_путей : ".";
    for (size_t i = 0; i < узел_число_детей(корень); ++i) {
        Узел *узел = узел_ребёнок(корень, i);
        if (!узел || узел->тип != УЗЕЛ_ПРЕПРОЦЕССОР) continue;
        char имя[512];
        if (!локальный_заголовок(узел, имя, sizeof(имя))) continue;

        // «X.h» → базовое «X»; ищем «X.и» и «X.so» рядом.
        char основа[512];
        snprintf(основа, sizeof(основа), "%s", имя);
        char *точка = strrchr(основа, '.');
        if (точка && strcmp(точка, ".h") == 0) *точка = '\0';

        char путь_и[1024], путь_so[1024];
        snprintf(путь_и, sizeof(путь_и), "%s/%s.и", база, основа);
        snprintf(путь_so, sizeof(путь_so), "%s/%s.so", база, основа);

        if (файл_есть(путь_и)) {
            загрузить_интерфейс(путь_и, куда);
            // Реконструированные типы (структуры/sum-перечисления) становятся
            // обычными детьми корня: семантика видит их при поиске индекса типа,
            // кодоген не эмитит (из_библиотеки) — typedef придёт из «X.h».
            for (size_t k = 0; k < куда->число_типов; ++k)
                узел_добавить_ребёнка(корень, узел_из_инт_типа(&куда->типы[k]));
            куда->число_типов = 0;   // уже перенесены в корень
            if (файл_есть(путь_so)) {
                char абс[512];
                snprintf(абс, sizeof(абс), "%.511s", путь_so);
                дин_массив_добавить(&куда->библиотеки, абс);
            }
        }
    }
    return 1;
}

// ─── Авто-подключение каталога стандартной библиотеки ───────────────────────
// Пользователь не пишет «#содержит "файл.h"»: каталог содержит готовые
// артефакты stdlib («X.и» + «X.h» + «X.so»). Имена типов — ДО разбора (парсер
// должен распознавать «Файл ф = …»), функции/типы/автолинковка — после
// слияния, симметрично собрать_интерфейсы, но с дедупом: если пользователь
// подключил ту же библиотеку вручную («#содержит "вывод/файл.h"» рядом лежит
// собственный «файл.и»), тип не схлопывается дважды.

// Есть ли уже в корне УЗЕЛ_СТРУКТУРА/УЗЕЛ_ПЕРЕЧИСЛЕНИЕ с таким именем?
static int имя_типа_уже_в_корне(const Узел *корень, const char *имя)
{
    if (!корень || !имя) return 0;
    size_t длина = strlen(имя);
    for (size_t i = 0; i < узел_число_детей(корень); ++i) {
        const Узел *у = узел_ребёнок(корень, i);
        if (!у) continue;
        if (у->тип != УЗЕЛ_СТРУКТУРА && у->тип != УЗЕЛ_ПЕРЕЧИСЛЕНИЕ) continue;
        if (у->токен.длина == длина &&
            strncmp(у->токен.начало, имя, длина) == 0)
            return 1;
    }
    return 0;
}

void собрать_имена_типов_из_каталога(const char *каталог,
                                      ИменаСтруктур *структуры,
                                      ИменаПеречислений *перечисления)
{
    if (!каталог || !каталог[0] || !структуры || !перечисления) return;
    char путь_и[1024];
    for (int i = 0; ; ++i) {
        // Пока stdlib = один модуль «файл»; при добавлении модулей — расширить.
        const char *модули[] = {"файл", nullptr};
        const char *основа = модули[i];
        if (!основа) break;
        snprintf(путь_и, sizeof(путь_и), "%s/%s.и", каталог, основа);
        if (файл_есть(путь_и))
            интерфейс_имена_типов(путь_и, структуры, перечисления);
    }
}

int собрать_интерфейсы_из_каталога(Узел *корень, const char *каталог,
                                    ТаблицаИнтерфейса *куда)
{
    if (!корень || !каталог || !каталог[0] || !куда) return 0;
    char путь_и[1024], путь_so[1024];
    const char *модули[] = {"файл", nullptr};
    for (int i = 0; ; ++i) {
        const char *основа = модули[i];
        if (!основа) break;
        snprintf(путь_и, sizeof(путь_и), "%s/%s.и", каталог, основа);
        if (!файл_есть(путь_и)) continue;
        загрузить_интерфейс(путь_и, куда);
        for (size_t k = 0; k < куда->число_типов; ++k) {
            if (!имя_типа_уже_в_корне(корень, куда->типы[k].имя))
                узел_добавить_ребёнка(корень, узел_из_инт_типа(&куда->типы[k]));
        }
        куда->число_типов = 0;
        snprintf(путь_so, sizeof(путь_so), "%s/%s.so", каталог, основа);
        if (файл_есть(путь_so)) {
            char абс[1024];
            snprintf(абс, sizeof(абс), "%.1023s", путь_so);
            дин_массив_добавить(&куда->библиотеки, абс);
        }
    }
    return 1;
}
