// §110-коллизия: у программы уже есть СВОЁ (не библиотечное) определение верхнего
// уровня — функция/структура/перечисление — с этим именем? Тогда одноимённый
// шаблон библиотеки не внедряем: определение пользователя побеждает (та же линия,
// что пропуск синтетического include при коллизии имён, см. основа.c). Иначе
// обобщённый, напр., «заполнить<T>» из stdlib затенил бы локальную «заполнить», и
// её вызов без тип-аргументов сломался бы («нельзя вызвать без тип-аргументов»).
// Сравнение — только с кодом пользователя (шаблон_библиотеки==0); дедуп двух
// библиотечных шаблонов одного имени по-прежнему делает мономорфизация.
static int имя_определено_пользователем(const Узел *корень, const Узел *ш)
{
    if (!(ш->тип == УЗЕЛ_ФУНКЦИЯ || ш->тип == УЗЕЛ_СТРУКТУРА
          || ш->тип == УЗЕЛ_ПЕРЕЧИСЛЕНИЕ))
        return 0;
    const char *имя = ш->токен.начало;
    size_t дл = ш->токен.длина;
    if (!имя || дл == 0) return 0;
    for (size_t i = 0; i < узел_число_детей(корень); ++i) {
        const Узел *у = узел_ребёнок(корень, i);
        if (!у || у->шаблон_библиотеки) continue;   // только собственный код программы
        if (!(у->тип == УЗЕЛ_ФУНКЦИЯ || у->тип == УЗЕЛ_СТРУКТУРА
              || у->тип == УЗЕЛ_ПЕРЕЧИСЛЕНИЕ))
            continue;
        if (у->токен.длина == дл && у->токен.начало
            && memcmp(у->токен.начало, имя, дл) == 0)
            return 1;
    }
    return 0;
}

// §101/§110: переразобрать СОБРАННЫЕ дословные исходники шаблонов и внедрить их
// узлы (шаблон_библиотеки=1) в «корень» ДО мономорфизации. Общий хвост для
// #содержит-варианта (внедрить_шаблоны_библиотек) и каталожного (§110). Возвращает
// число внедрённых. Буфер исходника утекает НАМЕРЕННО: токены/узлы держат в него
// указатели до конца процесса (как синтетические #содержит).
static int внедрить_собранные_шаблоны(Узел *корень, БуферКода *исходники,
                                      ИменаСтруктур *стр, ИменаПеречислений *пер,
                                      ИменаОбобщённых *ген)
{
    int внедрено = 0;
    const char *текст_исх = буфер_кода_строка(исходники);
    if (!текст_исх || !текст_исх[0]) return 0;
    char *копия = strdup(текст_исх);
    if (!копия) return 0;
    size_t дл = strlen(копия);
    МассивТокенов ток = токенизировать_код(дл, копия, 0);
    Диагностика диаг = {0};
    ДинМассив ошибки;
    дин_массив_инициализировать(&ошибки, sizeof(Диагностика));
    Узел *прог = разобрать_с_именами_структур_обобщённых_батч(
        &ток, &диаг, стр, пер, ген, nullptr, &ошибки);
    дин_массив_освободить(&ошибки);
    if (прог) {
        for (size_t i = 0; i < узел_число_детей(прог); ++i) {
            Узел *ш = узел_ребёнок(прог, i);
            if (!ш || ш->тип == УЗЕЛ_ПРЕПРОЦЕССОР) continue;
            if (имя_определено_пользователем(корень, ш)) {
                // Пользователь определил это имя сам — не затеняем его шаблоном
                // библиотеки. Узел освобождаем; в прог->дети остаётся висячий
                // указатель, но ниже прог->дети.длина := 0 не даст его тронуть.
                освободить_узел(ш);
                continue;
            }
            ш->шаблон_библиотеки = 1;
            узел_добавить_ребёнка(корень, ш);
            внедрено++;
        }
        прог->дети.длина = 0;   // дети перенесены в корень — не освобождать их
        освободить_узел(прог);
    }
    массив_токенов_освободить(&ток);  // узлы скопировали Токен по значению
    return внедрено;
}

int внедрить_шаблоны_библиотек(Узел *корень, const char *база)
{
    if (!корень) return 0;
    const char *b = (база && база[0]) ? база : ".";
    ИменаОбобщённых *ген = имена_обобщённых_создать();
    ИменаСтруктур *стр = имена_структур_создать();
    ИменаПеречислений *пер = имена_перечислений_создать();
    БуферКода исходники;
    буфер_кода_инициализировать(&исходники);
    int внедрено = 0;
    if (!ген || !стр || !пер) goto выход;

    for (size_t i = 0; i < узел_число_детей(корень); ++i) {
        Узел *узел = узел_ребёнок(корень, i);
        if (!узел || узел->тип != УЗЕЛ_ПРЕПРОЦЕССОР) continue;
        char имя[512];
        if (!локальный_заголовок(узел, имя, sizeof(имя))) continue;
        char основа[512];
        snprintf(основа, sizeof(основа), "%s", имя);
        char *точка = strrchr(основа, '.');
        if (точка && strcmp(точка, ".h") == 0) *точка = '\0';
        char путь_и[1024];
        snprintf(путь_и, sizeof(путь_и), "%s/%s.и", b, основа);
        if (файл_есть(путь_и))
            собрать_шаблоны_из_и(путь_и, &исходники, ген, стр, пер);
    }

    внедрено = внедрить_собранные_шаблоны(корень, &исходники, стр, пер, ген);

выход:
    буфер_кода_освободить(&исходники);
    имена_обобщённых_освободить(ген);
    имена_структур_освободить(стр);
    имена_перечислений_освободить(пер);
    return внедрено;
}

