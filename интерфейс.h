#ifndef ИНТЕРФЕЙС_H
#define ИНТЕРФЕЙС_H

#include <stddef.h>

#include "аст.h"   // Узел, БуферКода (через транспилятор.h), ТипТокена

// ─── Konda-интерфейс библиотек (безопасный путь 2) ──────────────────────────
//
// При сборке «--библиотека» рядом с .so/.h эмитится файл «.и» с ПОЛНЫМИ
// Konda-сигнатурами экспортируемых функций (типы + владение). Потребитель,
// подключающий «#содержит "либа.h"», авто-загружает соседний «либа.и» и
// проверяет вызовы как внутрипроектные (типы, владеет/изменяемый/вывод), а не
// как непрозрачный внешний C. C-заголовок этого выразить не может.
//
// Охват v2: примитивы, срез<примитив>, указатели + ИМЕНОВАННЫЕ ТИПЫ —
// структуры (с деструктором [удалить=…]) и перечисления (в т.ч. sum-типы с
// payload). Описания типов несутся в том же файле; потребитель реконструирует
// их как полноценные AST-узлы (флаг из_библиотеки): семантика/кодоген
// работают штатно (RAII, выбор, конструкция, поля), но C-определения не
// эмитятся — они приходят из «#содержит»-заголовка (двойной typedef иначе
// не собрался бы). v1-ограничения: поля структур и payload вариантов —
// примитивы/указатели (структуры/перечисления/срезы/массивы в полях не
// пересекают границу; такие функции остаются непрозрачными).

#define ИНТ_МАКС_ПАРАМ 16
#define ИНТ_МАКС_ТИПОВ 32
#define ИНТ_МАКС_ПОЛЕЙ 32
#define ИНТ_МАКС_ВАРИАНТОВ 64
#define ИНТ_МАКС_ПОЛЕЙ_ВАРИАНТА 8

typedef struct {
    ТипТокена тип;      // для срез — тип элемента
    int беззнаковый;
    int указатели;
    int срез;
    int массив;
    int возможно;       // §1: тип-указатель объявлен «возможно<T*>» (nullable);
                        // формат «.и» ≥ 3 (трейлинг-токен). 0 — ненулевой указатель.
    int владеет;        // «владеет» — передача = move
    int по_ссылке;      // 0 — значение; 1 — изменяемый (ref); 2 — вывод (out)
    char имя_типа[128]; // для тип==СТРУКТУРА/ПЕРЕЧИСЛЕНИЕ: имя именованного типа
} ИнтПараметр;

typedef struct {
    char имя[128];
    ТипТокена тип_возврата;
    int беззнаковый_возврата;
    int указатели_возврата;
    int срез_возврата;
    int возврат_заимствован;     // §37 п.6: срез-возврат ЗАИМСТВОВАН (не владеет) —
                                 // потребитель НЕ освобождает результат. 0 (дефолт,
                                 // в т.ч. для старых «.и») — владеющий, потребитель
                                 // free'ит (совместимо: старые библиотеки владеющие).
    int возможно_возврата;       // §1: тип возврата — «возможно<T*>» (nullable);
                                 // формат «.и» ≥ 3. Потребитель разыменовывает
                                 // результат только под охранником (иначе теряется
                                 // null-безопасность через границу библиотеки).
    char имя_типа_возврата[128]; // для именованного возврата (структура/перечисление)
    ИнтПараметр параметры[ИНТ_МАКС_ПАРАМ];
    size_t число_параметров;
} ИнтФункция;

// Поле структуры или payload-поле варианта sum-перечисления.
typedef struct {
    ТипТокена тип;
    int беззнаковый;
    int указатели;
    int срез;           // перечисление не могут: payload требует примитив/указатель
    int массив;         // §108: ФЛАГ «поле — массив T[N]» (0 — не массив)
    long размер_массива; // §108: размерность N поля-массива (нужна для границ доступа)
    int возможно;       // §1: поле-указатель «возможно<T*>» (формат «.и» ≥ 3)
    char имя[128];      // имя поля
    char имя_типа[128]; // §108: имя элемента для срез<структура>/срез<перечисление>
                        // (или именованного скаляр-поля); пусто для примитивов
} ИнтПоле;

typedef struct {
    char имя[128];
    ИнтПоле поля[ИНТ_МАКС_ПОЛЕЙ_ВАРИАНТА];
    size_t число_полей; // >0 — вариант несёт данные (sum-тип)
} ИнтВариант;

// Именованный тип библиотеки (реконструируется потребителем в AST-узел).
typedef struct {
    char имя[128];
    int это_структура;   // 1 — структура; 0 — перечисление
    char деструктор[128]; // структура: «[удалить = …]»; пусто — деструктора нет
    ИнтПоле поля[ИНТ_МАКС_ПОЛЕЙ];             // структура (v1: примитивы/указатели)
    size_t число_полей;
    ИнтВариант варианты[ИНТ_МАКС_ВАРИАНТОВ]; // перечисление
    size_t число_вариантов;
} ИнтТип;

// §106: именованный тип-указатель на функцию («типфункции RET Имя(…)») из «.и».
// Реконструируется потребителем в УЗЕЛ_ТИПФУНКЦИИ (из_библиотеки): собрать_типыфункций
// регистрирует сигнатуру, внедрить_интерфейс_сигнатуры связывает fp-параметры/возврат
// библиотечных функций с её индексом. C-typedef приходит из «X.h» (не эмитим).
typedef struct {
    char имя[128];
    ТипТокена тип_возврата;
    int беззнаковый_возврата;
    int указатели_возврата;
    int срез_возврата;
    int возможно_возврата;
    char имя_типа_возврата[128];      // для именованного возврата (структура/перечисление)
    ИнтПоле параметры[ИНТ_МАКС_ПОЛЕЙ]; // носитель типа параметра (поле «имя» не используется)
    size_t число_параметров;
} ИнтТипфункции;

// §107: глобал верхнего уровня из «.и» — иммутабельная «конст» ЛИБО «атом<T>».
// Конст: значение (текст литерала) переносится, потребитель эмитит СВОЙ
// «static const» (внутренняя связь, значение свёрнуто — коллизий нет; годно как
// размер массива §97). Атом: разделяемый ВНЕШНИЙ символ .so — потребитель НЕ
// эмитит определение (декларация «extern _Atomic» приходит из «X.h»), лишь
// регистрирует имя как изменяемый атомик.
typedef struct {
    char имя[128];
    ТипТокена тип;
    int беззнаковый;
    int указатели;
    int срез;
    int атом;            // 1 — атомик (внешний символ); 0 — конст (значение)
    char значение[64];   // текст целочисленного литерала (только конст; иначе пусто)
} ИнтГлобал;

typedef struct ТаблицаИнтерфейса ТаблицаИнтерфейса;

ТаблицаИнтерфейса *интерфейс_создать(void);
void               интерфейс_освободить(ТаблицаИнтерфейса *);
size_t             интерфейс_число(const ТаблицаИнтерфейса *);
const ИнтФункция  *интерфейс_получить(const ТаблицаИнтерфейса *, size_t);
// Именованные типы библиотеки (структуры/перечисления) из «.и».
size_t             интерфейс_тип_число(const ТаблицаИнтерфейса *);
const ИнтТип      *интерфейс_тип_получить(const ТаблицаИнтерфейса *, size_t);
const ИнтТип      *интерфейс_тип_найти(const ТаблицаИнтерфейса *, const char *имя,
                                       size_t длина);
// Найденные рядом с интерфейсом .so — для автолинковки потребителя.
size_t             интерфейс_число_библиотек(const ТаблицаИнтерфейса *);
const char        *интерфейс_библиотека(const ТаблицаИнтерфейса *, size_t);

// Эмиссия интерфейса библиотеки (режим --библиотека) в буфер.
void эмит_интерфейс(const Узел *корень, БуферКода *буфер);

// §101: экспорт обобщённых ШАБЛОНОВ через «.и». Полевая сериализация «.и»
// выражает лишь конкретные типы; тело обобщённого объявления (особенно функции)
// ею не передать. Поэтому шаблон экспортируется как ДОСЛОВНЫЙ исходник, а
// потребитель переразбирает его и мономорфизирует нужную специализацию локально
// (header-only, как шаблоны C++/Rust). эмит_шаблоны_в_строку захватывает исходники
// обобщённых объявлений верхнего уровня (структура/перечисление/функция с <T>) из
// «корень» ДО мономорфизации и возвращает heap-строку записей «Шаблон вид имя
// длина\n<исходник>\n» для дописи в «.и» (или nullptr, если шаблонов нет; free()).
char *эмит_шаблоны_в_строку(const Узел *корень);

// §101: имена обобщённых шаблонов из «.и» библиотек — ДО разбора (как
// собрать_имена_типов_интерфейсов): чтобы «Пара<символ> x» / «макс<символ>(…)» с
// шаблоном из библиотеки распознавались парсером как инстанцирование, а не «<».
void собрать_имена_обобщённых_интерфейсов(МассивТокенов *токены, const char *база,
                                          ИменаОбобщённых *куда);

// §101: внедрение обобщённых шаблонов из «.и» библиотек в дерево ДО мономорфизации.
// Для каждого локального «#содержит "X.h"» читает соседний «X.и», переразбирает
// исходники его шаблонов и добавляет узлы (шаблон_библиотеки=1) в «корень» —
// мономорфизация разворачивает нужные потребителю специализации локально.
// Возвращает число внедрённых шаблонов.
int внедрить_шаблоны_библиотек(Узел *корень, const char *база);

// Сбор интерфейсов потребителя: для каждого локального «#содержит "X.h"» ищет
// соседний «X.и» (и «X.so») относительно база_путей и загружает. Именованные
// типы библиотеки (структуры/sum-перечисления) реконструируются как AST-узлы с
// флагом «внешняя» и ДОБАВЛЯЮТСЯ в «корень» (потому non-const): семантика/кодоген
// работают с ними штатной машинерией (RAII, выбор, доступ к полям), но C их не
// эмитит — определения приходят из «X.h». Возвращает 1 при успехе.
int собрать_интерфейсы(Узел *корень, const char *база_путей,
                       ТаблицаИнтерфейса *куда);

// Имена типов библиотек — ДО разбора: парсер должен распознавать
// «Имя п = …» для структур/перечислений, которые придут из «.и» (реконструкция
// узлов в собрать_интерфейсы — после разбора). Для каждого локального
// «#содержит "X.h"» ищет соседний «X.и» и добавляет его типы в списки.
void собрать_имена_типов_интерфейсов(МассивТокенов *токены, const char *база_путей,
                                      ИменаСтруктур *структуры,
                                      ИменаПеречислений *перечисления);

// §90: имена функций-ПРОСТРАНСТВ из «.и» (строки «Ф Имя::член …») — ДО разбора,
// чтобы парсер потребителя распознавал квалифицированный вызов
// «Пространство::член(…)» к библиотечной функции (набор — строковый, повторно
// используем ИменаСтруктур). интерфейс_имена_функций_пр читает один «.и»;
// собрать_имена_функций_пр_интерфейсов сканирует локальные «#содержит "X.h"».
void интерфейс_имена_функций_пр(const char *путь, ИменаСтруктур *набор);
void собрать_имена_функций_пр_интерфейсов(МассивТокенов *токены,
                                          const char *база_путей,
                                          ИменаСтруктур *набор);

// Читает «.и» напрямую и добавляет имена содержащихся типов (структур «С» и
// перечислений «Е») в списки парсера. Используется для авто-подключения
// стандартной библиотеки (каталог без «#содержит» в исходнике).
void интерфейс_имена_типов(const char *путь, ИменаСтруктур *структуры,
                            ИменаПеречислений *перечисления);

// Авто-подключение каталога стандартной библиотеки: для каждого «X.и» в
// каталоге добавляет имена типов в списки парсера (до разбора).
void собрать_имена_типов_из_каталога(const char *каталог,
                                      ИменаСтруктур *структуры,
                                      ИменаПеречислений *перечисления);

// Для каждого «X.и» в каталоге: загружает функции в «куда», реконструирует
// типы в «корень» (только если типа с таким именем ещё нет — дедуп при
// ручном «#содержит» той же библиотеки) и регистрирует «X.so» для
// автолинковки. Возвращает 1 при успехе.
int собрать_интерфейсы_из_каталога(Узел *корень, const char *каталог,
                                    ТаблицаИнтерфейса *куда);

// Перечислить модули stdlib в каталоге: базовые имена всех «*.и» (без суффикса)
// → out (каждое до 127 байт). Возвращает число (≤ макс). Так многомодульная
// stdlib подхватывается сканом каталога, без хардкод-списка модулей.
int перечислить_модули_stdlib(const char *каталог, char (*out)[128], int макс);

#endif /* ИНТЕРФЕЙС_H */
