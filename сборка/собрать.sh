#!/bin/sh
# Собрать фронтенд «konda build»: сперва libkonda_toml (.so + .и), затем сам
# фронтенд. Источники передаём АБСОЛЮТНЫМИ путями — тогда DT_NEEDED у toml.so
# абсолютный и бинарь находит библиотеку из любого рабочего каталога
# (иначе относительный путь-со-слэшами резолвится от CWD запуска). POSIX sh.
#
# БУТСТРАП: фронтенд НЕ линкует libkonda_std.so (её собирает ОН САМ — был бы
# цикл). Поэтому «--без-стандартной-библиотеки», а нужные чистые Konda-модули
# stdlib (хеш — FNV, строки — предикаты) ВКОМПИЛИВАЮТСЯ прямо во фронтенд
# входными файлами: единый источник логики (та же stdlib), но без runtime-зависимости.
# «--имя=сборка» фиксирует имя выхода (иначе оно берётся от первого входного файла).
# ПОРЯДОК ВХОДНЫХ ВАЖЕН: сборка.конда — ПЕРВОЙ, т.к. каталог «-I» для локальных
# «#содержит» (сборка_шим.h, ../toml/вывод/toml.h) берётся от каталога ПЕРВОГО файла.
set -eu
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/.." && pwd)"
BIN="$ROOT/Собранное/ТранспиляторКонда"

[ -x "$BIN" ] || { echo "нет транспилятора: $BIN (собери 'make' в корне)" >&2; exit 1; }

"$BIN" --библиотека --вывод="$ROOT/toml/вывод" "$ROOT/toml/toml.конда" >/dev/null
"$BIN" --без-стандартной-библиотеки --имя=сборка --вывод="$HERE/вывод" \
    "$HERE/сборка.конда" "$ROOT/stdlib/хеш.конда" "$ROOT/stdlib/строки.конда" >/dev/null
echo "Собран фронтенд: $HERE/вывод/сборка.elf"
echo "Запуск: KONDA_TRANSPILER=<путь к ТранспиляторКонда> сборка.elf [Konda.toml]"
