/* ─────────────────────────────────────────────────────────────────────────────
   сборка_шим.h — L1: доверенный C-шим фронтенда сборки Konda.
   Единственная зона «небезопасности» build-фронтенда: чтение файла и запуск
   транспилятора. Konda-слой (сборка.конда) сюда не смотрит, работает только с
   безопасными обёртками. Паттерн — как stdlib/конда_ио.h.

   Тип Срез должен совпадать с ТИПДЕФ_СРЕЗ кодогена; общий guard KONDA_SREZ_DEFINED.
   ────────────────────────────────────────────────────────────────────────── */
#pragma once
#include <stddef.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>
#include <sys/wait.h>

#ifndef KONDA_SREZ_DEFINED
#define KONDA_SREZ_DEFINED
typedef struct { void *данные; size_t длина; } Срез;
#endif

/* Прочитать файл целиком в буфер (Срез {данные, длина} — границы гарантированы
   длиной по построению). Возврат: число прочитанных байт (>=0) или -1. */
static inline int32_t сборка_прочитать_файл(const char *путь, Срез буфер) {
    FILE *файл = fopen(путь, "rb");
    if (!файл) return -1;
    size_t прочитано = fread(буфер.данные, 1, буфер.длина, файл);
    fclose(файл);
    return (int32_t)прочитано;
}

/* Склеить два среза в NUL-терминированную C-строку в куче (для сборки элементов
   argv: «--аллокатор=» + значение, «--вывод=вывод/» + триплет, копия пути-среза).
   Утечка намеренна: процесс вскоре execvp-нется/выйдет. NULL при OOM. */
static inline char *сборка_склеить(Срез префикс, Срез хвост) {
    char *строка = (char *)malloc(префикс.длина + хвост.длина + 1);
    if (!строка) return NULL;
    memcpy(строка, префикс.данные, префикс.длина);
    memcpy(строка + префикс.длина, хвост.данные, хвост.длина);
    строка[префикс.длина + хвост.длина] = '\0';
    return строка;
}

/* Запустить транспилятор с argv-хвостом (флаги + источники — уже C-строки).
   БЕЗ shell: fork + execvp, поэтому пути/аргументы с пробелами и спецсимволами
   передаются дословно (нет разбора оболочкой). Путь транспилятора — из
   KONDA_TRANSPILER, иначе «ТранспиляторКонда» (PATH); шим ставит его argv[0].
   «аргв» — Срез: .данные = char**, .длина = число аргументов (без argv[0]/NULL).
   Возврат: код выхода транспилятора или -1 при ошибке запуска. */
static inline int32_t сборка_запустить(Срез аргв) {
    const char *транспилятор = getenv("KONDA_TRANSPILER");
    if (!транспилятор || !транспилятор[0]) транспилятор = "ТранспиляторКонда";
    char **хвост = (char **)аргв.данные;
    size_t количество = аргв.длина;
    char **полный = (char **)malloc((количество + 2) * sizeof(char *));
    if (!полный) return -1;
    полный[0] = (char *)транспилятор;
    for (size_t i = 0; i < количество; ++i) полный[1 + i] = хвост[i];
    полный[количество + 1] = NULL;
    fflush(stdout);
    pid_t потомок = fork();
    if (потомок < 0) { free(полный); return -1; }
    if (потомок == 0) {
        execvp(транспилятор, полный);
        _exit(127);   /* execvp вернулся — транспилятор не найден/не запустился */
    }
    int статус;
    int итог = (waitpid(потомок, &статус, 0) < 0) ? -1
             : (WIFEXITED(статус) ? (int32_t)WEXITSTATUS(статус) : -1);
    free(полный);
    return итог;
}

/* ─── Хеш-кэш для защиты от устаревания (инкрементальная сборка) ──────────────
   FNV-1a 64-бит. Всё хеширование — здесь: байтовая арифметика и беззнаковое
   переполнение (с переносом) не выражаются в Konda (символ неарифметичен §31,
   а знаковый целое64-overflow в отладке падает по guard). Konda лишь передаёт
   данные и сравнивает готовые целое64-ключи. seed==0 → начать с offset basis
   (детерминированно; см. docs/СИСТЕМА_СБОРКИ.md). */
static inline int64_t _сборка_фнв(const unsigned char *данные, size_t длина, uint64_t хеш) {
    for (size_t i = 0; i < длина; ++i) { хеш ^= данные[i]; хеш *= 1099511628211ULL; }
    return (int64_t)хеш;
}
static inline uint64_t _сборка_начало(int64_t seed) {
    return seed == 0 ? 14695981039346656037ULL : (uint64_t)seed;
}
/* Продолжить хеш содержимым среза. */
static inline int64_t сборка_хеш_среза_с(Срез срез, int64_t seed) {
    return _сборка_фнв((const unsigned char *)срез.данные, срез.длина, _сборка_начало(seed));
}
/* Продолжить хеш содержимым argv (каждая C-строка + разделитель между ними —
   чтобы ["-a","bc"] и ["-ab","c"] давали разные ключи). */
static inline int64_t сборка_хеш_аргв_с(Срез аргв, int64_t seed) {
    char **строки = (char **)аргв.данные;
    uint64_t хеш = _сборка_начало(seed);
    for (size_t i = 0; i < аргв.длина; ++i) {
        const char *с = строки[i];
        хеш = (uint64_t)_сборка_фнв((const unsigned char *)с, strlen(с), хеш);
        хеш ^= 0x1fu; хеш *= 1099511628211ULL;   /* разделитель аргументов */
    }
    return (int64_t)хеш;
}
/* Файл существует? (для проверки выходного бинаря перед пропуском по кэшу —
   иначе `rm вывод/x.elf` при совпавшем ключе не пересобрал бы.) */
static inline int32_t сборка_файл_есть(const char *путь) {
    return access(путь, F_OK) == 0 ? 1 : 0;
}

static inline int64_t сборка_хеш_файла_с(const char *путь, int64_t seed);  /* ниже */

/* Продолжить хеш содержимым ЛОКАЛЬНЫХ C-заголовков, подключённых источником через
   «#содержит "..."» (кавычки — локальный; «<...>» системный, пропускаем). Путь
   заголовка резолвится относительно каталога источника. Один уровень (в сами
   заголовки не спускаемся — v1). Так правка C-шима (напр. сборка_шим.h) меняет
   ключ → пересборка (аналог depfiles -MMD у make). */
static inline int64_t сборка_хеш_включений_с(const char *путь_источника, int64_t seed) {
    uint64_t хеш = _сборка_начало(seed);
    FILE *файл = fopen(путь_источника, "rb");
    if (!файл) return (int64_t)хеш;
    char каталог[4096]; каталог[0] = '\0';
    const char *слэш = strrchr(путь_источника, '/');
    if (слэш) {
        size_t длина = (size_t)(слэш - путь_источника);
        if (длина < sizeof каталог) { memcpy(каталог, путь_источника, длина); каталог[длина] = '\0'; }
    }
    char строка[4096];
    while (fgets(строка, sizeof строка, файл)) {
        char *метка = strstr(строка, "#содержит");
        if (!метка) continue;
        char *кавычка = strchr(метка, '"');
        if (!кавычка) continue;                 /* «<...>» — системный, пропуск */
        char *конец = strchr(кавычка + 1, '"');
        if (!конец) continue;
        char заголовок[4096];
        size_t длина_заг = (size_t)(конец - (кавычка + 1));
        if (длина_заг >= sizeof заголовок) continue;
        memcpy(заголовок, кавычка + 1, длина_заг); заголовок[длина_заг] = '\0';
        char полный[8192];
        if (каталог[0]) snprintf(полный, sizeof полный, "%s/%s", каталог, заголовок);
        else            snprintf(полный, sizeof полный, "%s", заголовок);
        хеш = (uint64_t)сборка_хеш_файла_с(полный, (int64_t)хеш);
    }
    fclose(файл);
    return (int64_t)хеш;
}

/* Продолжить хеш содержимым файла. Отсутствие файла — тоже вклад (маркер),
   чтобы появление/исчезновение источника меняло ключ. */
static inline int64_t сборка_хеш_файла_с(const char *путь, int64_t seed) {
    uint64_t хеш = _сборка_начало(seed);
    FILE *файл = fopen(путь, "rb");
    if (!файл) { хеш ^= 0xFEEDu; хеш *= 1099511628211ULL; return (int64_t)хеш; }
    unsigned char буфер[4096];
    size_t прочитано;
    while ((прочитано = fread(буфер, 1, sizeof буфер, файл)) > 0)
        хеш = (uint64_t)_сборка_фнв(буфер, прочитано, хеш);
    fclose(файл);
    return (int64_t)хеш;
}
/* Продолжить хеш содержимым бинаря транспилятора (KONDA_TRANSPILER или PATH-имя;
   если по имени не открылось — вклад «файла нет», деградирует безопасно). */
static inline int64_t сборка_хеш_транспилятора_с(int64_t seed) {
    const char *транспилятор = getenv("KONDA_TRANSPILER");
    if (!транспилятор || !транспилятор[0]) транспилятор = "ТранспиляторКонда";
    return сборка_хеш_файла_с(транспилятор, seed);
}
/* Прочитать сохранённый ключ (0 — нет кэша/ошибка). */
static inline int64_t сборка_читать_кэш(const char *путь) {
    FILE *файл = fopen(путь, "r");
    if (!файл) return 0;
    long long значение = 0;
    if (fscanf(файл, "%lld", &значение) != 1) значение = 0;
    fclose(файл);
    return (int64_t)значение;
}
/* Записать ключ. */
static inline void сборка_писать_кэш(const char *путь, int64_t значение) {
    FILE *файл = fopen(путь, "w");
    if (файл) { fprintf(файл, "%lld\n", (long long)значение); fclose(файл); }
}
/* Сравнение C-строк (для разбора флагов argv). */
static inline int32_t сборка_равно_си(const char *левый, const char *правый) {
    return strcmp(левый, правый) == 0 ? 1 : 0;
}

/* Собрать зависимость: запустить ЭТОТ ЖЕ фронтенд в каталоге зависимости (у неё
   свой Konda.toml и свой .konda-сборка.кэш → пер-проектный инкремент). Возврат:
   код выхода дочерней сборки или -1. */
static inline int32_t сборка_собрать_зависимость(const char *каталог) {
    char сам[4096];
    ssize_t длина = readlink("/proc/self/exe", сам, sizeof сам - 1);
    if (длина < 0) return -1;
    сам[длина] = '\0';
    fflush(stdout);
    pid_t потомок = fork();
    if (потомок < 0) return -1;
    if (потомок == 0) {
        if (chdir(каталог) != 0) _exit(126);
        execl(сам, сам, (char *)NULL);
        _exit(127);
    }
    int статус;
    if (waitpid(потомок, &статус, 0) < 0) return -1;
    return WIFEXITED(статус) ? (int32_t)WEXITSTATUS(статус) : -1;
}

/* Переименовать файл (для поля «выход»). Пути — срезы (NUL-терминируем внутри).
   Возврат: 0 или -1. */
static inline int32_t сборка_переименовать_срез(Срез из, Срез в) {
    char *путь_из = (char *)malloc(из.длина + 1);
    char *путь_в = (char *)malloc(в.длина + 1);
    int32_t итог = -1;
    if (путь_из && путь_в) {
        memcpy(путь_из, из.данные, из.длина); путь_из[из.длина] = '\0';
        memcpy(путь_в, в.данные, в.длина);   путь_в[в.длина] = '\0';
        итог = rename(путь_из, путь_в) == 0 ? 0 : -1;
    }
    free(путь_из); free(путь_в);
    return итог;
}
