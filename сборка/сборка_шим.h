/* ─────────────────────────────────────────────────────────────────────────────
   сборка_шим.h — L1: доверенный C-шим фронтенда сборки Konda.
   Единственная зона «небезопасности» build-фронтенда: чтение файла и запуск
   транспилятора. Konda-слой (сборка.конда) сюда не смотрит, работает только с
   безопасными обёртками. Паттерн — как stdlib/конда_ио.h.

   Тип Срез должен совпадать с ТИПДЕФ_СРЕЗ кодогена; общий guard KONDA_SREZ_DEFINED.
   ────────────────────────────────────────────────────────────────────────── */
#pragma once
#include <stddef.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>
#include <fcntl.h>
#include <sys/file.h>
#include <sys/wait.h>
#include <dirent.h>
#include <errno.h>

#ifndef KONDA_SREZ_DEFINED
#define KONDA_SREZ_DEFINED
typedef struct { void *данные; size_t длина; } Срез;
#endif

/* Единый источник FNV — Konda-функция `фнв1а_с` из stdlib/хеш.конда, вкомпилённая
   в этот же бинарь фронтенда (собрать.sh подаёт хеш.конда входным файлом). Шим
   БОЛЬШЕ НЕ держит своей копии арифметики: I/O-хешеры ниже читают байты и
   делегируют счёт сюда. Конвенция seed: 0 → offset basis, иначе продолжить.
   Сигнатура — ровно как эмитит кодоген для `целое64 фнв1а_с(срез<символ>,целое64)`. */
int64_t фнв1а_с(Срез данные, int64_t seed);

/* Прочитать файл целиком в буфер (Срез {данные, длина} — границы гарантированы
   длиной по построению). Возврат: число прочитанных байт (>=0) или -1. */
static inline int32_t сборка_прочитать_файл(const char *путь, Срез буфер) {
    FILE *файл = fopen(путь, "rb");
    if (!файл) return -1;
    size_t прочитано = fread(буфер.данные, 1, буфер.длина, файл);
    fclose(файл);
    return (int32_t)прочитано;
}

/* Склеить два среза в NUL-терминированную C-строку в куче (для сборки элементов
   argv: «--аллокатор=» + значение, «--вывод=вывод/» + триплет, копия пути-среза).
   Утечка намеренна: процесс вскоре execvp-нется/выйдет. NULL при OOM. */
static inline char *сборка_склеить(Срез префикс, Срез хвост) {
    char *строка = (char *)malloc(префикс.длина + хвост.длина + 1);
    if (!строка) return NULL;
    memcpy(строка, префикс.данные, префикс.длина);
    memcpy(строка + префикс.длина, хвост.данные, хвост.длина);
    строка[префикс.длина + хвост.длина] = '\0';
    return строка;
}

/* Запустить транспилятор с argv-хвостом (флаги + источники — уже C-строки).
   БЕЗ shell: fork + execvp, поэтому пути/аргументы с пробелами и спецсимволами
   передаются дословно (нет разбора оболочкой). Путь транспилятора — из
   KONDA_TRANSPILER, иначе «ТранспиляторКонда» (PATH); шим ставит его argv[0].
   «аргв» — Срез: .данные = char**, .длина = число аргументов (без argv[0]/NULL).
   Возврат: код выхода транспилятора или -1 при ошибке запуска. */
static inline int32_t сборка_запустить(Срез аргв) {
    const char *транспилятор = getenv("KONDA_TRANSPILER");
    if (!транспилятор || !транспилятор[0]) транспилятор = "ТранспиляторКонда";
    char **хвост = (char **)аргв.данные;
    size_t количество = аргв.длина;
    char **полный = (char **)malloc((количество + 2) * sizeof(char *));
    if (!полный) return -1;
    полный[0] = (char *)транспилятор;
    for (size_t i = 0; i < количество; ++i) полный[1 + i] = хвост[i];
    полный[количество + 1] = NULL;
    fflush(stdout);
    pid_t потомок = fork();
    if (потомок < 0) { free(полный); return -1; }
    if (потомок == 0) {
        execvp(транспилятор, полный);
        _exit(127);   /* execvp вернулся — транспилятор не найден/не запустился */
    }
    int статус;
    int итог = (waitpid(потомок, &статус, 0) < 0) ? -1
             : (WIFEXITED(статус) ? (int32_t)WEXITSTATUS(статус) : -1);
    free(полный);
    return итог;
}

/* ─── Список источников: авто-скан каталога ──────────────────────────────────
   Как в Cargo: источники находятся САМИ — сканированием каталога проекта на
   *.конда (с вычетом «исключить»). Поля «исходники» больше нет. Стор
   держится в статике; в Konda он не виден — фронтенд лишь наполняет его и берёт
   пути по индексу как символ*. Каждое задание — отдельный ПРОЦЕСС (цели/зависимости
   форкаются), поэтому общего изменяемого состояния между заданиями нет: у каждого
   свой стор, инвариант «нет гонок данных» цел. */
#define СБОРКА_МАКС_ИСТОЧНИКОВ 4096
static char *_сборка_источники[СБОРКА_МАКС_ИСТОЧНИКОВ];
static int32_t _сборка_число_источников = 0;

/* Освободить и обнулить стор (перед наполнением очередной цели). */
static inline void сборка_источники_очистить(void) {
    for (int32_t i = 0; i < _сборка_число_источников; ++i) { free(_сборка_источники[i]); _сборка_источники[i] = NULL; }
    _сборка_число_источников = 0;
}
/* Добавить путь-источник (копия в куче; освобождается в …_очистить). */
static inline void сборка_источник_добавить(const char *путь) {
    if (_сборка_число_источников >= СБОРКА_МАКС_ИСТОЧНИКОВ) return;
    char *копия = strdup(путь);
    if (!копия) return;
    _сборка_источники[_сборка_число_источников++] = копия;
}
/* Имя оканчивается на «.конда» (суффикс — байты UTF-8)? */
static inline int32_t _сборка_есть_конда(const char *имя) {
    size_t длина_имени = strlen(имя);
    const char *суффикс = ".конда";
    size_t длина_суффикса = strlen(суффикс);
    return (длина_имени > длина_суффикса
            && memcmp(имя + длина_имени - длина_суффикса, суффикс, длина_суффикса) == 0) ? 1 : 0;
}
/* Скан каталога проекта («.») на *.конда: добавить в стор ОТСОРТИРОВАННО
   (scandir+alphasort — детерминированный порядок, как у оркестратора основа.c →
   стабильный ключ хеш-кэша). Каталоги (в т.ч. «вывод/») в стор не попадают: у них
   нет суффикса «.конда». Возврат: число добавленных. */
static inline int32_t сборка_сканировать_исходники(void) {
    struct dirent **список = NULL;
    int количество = scandir(".", &список, NULL, alphasort);
    if (количество < 0) return 0;
    int32_t добавлено = 0;
    for (int i = 0; i < количество; ++i) {
        if (_сборка_есть_конда(список[i]->d_name)) { сборка_источник_добавить(список[i]->d_name); ++добавлено; }
        free(список[i]);
    }
    free(список);
    return добавлено;
}
/* Убрать источник по имени (поле «исключить» манифеста при авто-скане). Возврат:
   1 — убран, 0 — такого в сторе не было. */
static inline int32_t сборка_источник_исключить(const char *имя) {
    for (int32_t i = 0; i < _сборка_число_источников; ++i) {
        if (strcmp(_сборка_источники[i], имя) == 0) {
            free(_сборка_источники[i]);
            for (int32_t j = i + 1; j < _сборка_число_источников; ++j) _сборка_источники[j - 1] = _сборка_источники[j];
            --_сборка_число_источников;
            return 1;
        }
    }
    return 0;
}
static inline int32_t сборка_число_источников(void) { return _сборка_число_источников; }
/* Путь i-го источника (стабильная C-строка до …_очистить). Вне диапазона → "". */
static inline char *сборка_источник(int32_t индекс) {
    if (индекс < 0 || индекс >= _сборка_число_источников) return (char *)"";
    return _сборка_источники[индекс];
}
/* Базовое имя выхода из ПЕРВОГО источника (без каталога и расширения):
   «src/окно.конда» → «окно». Нужно, когда в манифесте нет ни «имя», ни «выход»,
   а источники авто-сканированы — так же, как транспилятор назвал бы выход по
   первому файлу. Строка в куче (утечка намеренна — процесс вскоре выйдет). */
static inline char *сборка_база_из_источника(void) {
    if (_сборка_число_источников == 0) return (char *)"";
    const char *путь = _сборка_источники[0];
    const char *слэш = strrchr(путь, '/');
    const char *начало = слэш ? слэш + 1 : путь;
    const char *точка = strrchr(начало, '.');
    size_t длина = точка ? (size_t)(точка - начало) : strlen(начало);
    char *база = (char *)malloc(длина + 1);
    if (!база) return (char *)"";
    memcpy(база, начало, длина);
    база[длина] = '\0';
    return база;
}

/* ─── Пул процессов для параллельной сборки (-j) ─────────────────────────────
   Оркестрация — в Konda (сборка.конда): она сама решает, форкать или падать на
   синхронный путь, и агрегирует коды. Шим даёт лишь примитивы-syscall'ы. Работа
   каждого задания — отдельный ПРОЦЕСС (fork+exec транспилятора или re-exec себя),
   поэтому разделяемого изменяемого состояния в Konda не возникает: синхронизация
   на уровне ОС, инвариант «нет гонок данных» цел. */

/* fork: 0 — потомок, >0 — pid у родителя, -1 — ошибка. Родитель разбирает ветку
   в Konda (потомок делает своё задание и зовёт сборка_выход). */
static inline int32_t сборка_форкнуть(void) {
    fflush(stdout);
    return (int32_t)fork();
}
/* _exit(код): лист-потомок задания завершается, НЕ возвращаясь в цикл Konda
   (иначе потомок продолжил бы раздавать задания). Сначала сбрасываем stdout,
   чтобы вывод задания не потерялся. */
static inline void сборка_выход(int32_t код) {
    fflush(stdout);
    _exit(код);
}
/* Дождаться ЛЮБОГО потомка; вернуть его код выхода (>=0) или 1 при гибели по
   сигналу; -1 если детей нет / ошибка (Konda вызывает лишь при живых>0, поэтому
   -1 в норме не встречается). Для дренажа пула и троттлинга -j. */
static inline int32_t сборка_ждать_любого(void) {
    int статус;
    pid_t п = wait(&статус);
    if (п < 0) return -1;
    if (WIFEXITED(статус)) return (int32_t)WEXITSTATUS(статус);
    return 1;   /* убит сигналом → неуспех */
}
/* Запустить зависимость (re-exec этого же фронтенда в её каталоге) БЕЗ ожидания;
   вернуть pid (>0) или -1. Reap — через сборка_ждать_любого (пул -j). Значение
   -j пробрасывается в под-сборку (транзитивный параллелизм). */
static inline int32_t сборка_запустить_зависимость_нежд(const char *каталог, int32_t задания) {
    char сам[4096];
    ssize_t длина = readlink("/proc/self/exe", сам, sizeof сам - 1);
    if (длина < 0) return -1;
    сам[длина] = '\0';
    fflush(stdout);
    pid_t п = fork();
    if (п < 0) return -1;
    if (п == 0) {
        if (chdir(каталог) != 0) _exit(126);
        char флаг[32];
        snprintf(флаг, sizeof флаг, "-j%d", (int)задания);
        execl(сам, сам, флаг, (char *)NULL);
        _exit(127);
    }
    return (int32_t)п;
}

/* ─── Разбор -j / число ядер / блокировка каталога ───────────────────────────
   Байтовая арифметика над строками и целочисленный разбор не выражаются в Konda
   (символ неарифметичен §31) → здесь, как и хеш-кэш. */

/* Разбор «число ли строка» / «первое число из строки» — теперь на Konda
   (`строки.это_число` / `строки.первое_число`, вкомпилены во фронтенд). Шим их
   больше не дублирует. */
/* Число онлайн-ядер (для «-j» без числа = авто). Всегда >=1. */
static inline int32_t сборка_число_ядер(void) {
    long ядер = sysconf(_SC_NPROCESSORS_ONLN);
    return ядер > 0 ? ((int32_t)ядер + 1) : 1;
}
/* Сравнение строк / «начинается с» — теперь на Konda (`строки.равно`/`==` и
   `строки.начинается_с` над буфером из argv; см. сборка.конда). Шим их не держит. */
/* Взять межпроцессную блокировку сборки ТЕКУЩЕГО каталога (flock LOCK_EX на
   дескрипторе САМОГО каталога сборки — не на отдельном lock-файле, чтобы не
   оставлять артефакт). Держится до выхода процесса (fd намеренно не закрываем).
   Делает параллельную сборку зависимостей корректной при РОМБЕ (один каталог-
   зависимость собирается из двух мест одновременно): второй сборщик ждёт на
   блокировке, затем видит кэш актуальным и ничего не пересобирает. Граф
   зависимостей — DAG (без циклов), блокировки берутся по разным каталогам вниз
   по дереву → взаимоблокировок нет. Каталог всегда существует → нет гонки
   unlink+flock (осиротевший inode), которая была бы у удаляемого lock-файла, и
   не остаётся мусора после сборки. Возврат: fd (>=0) или -1 (тогда без защиты —
   сборка не рвётся). */
static inline int32_t сборка_взять_блокировку(void) {
    int дескриптор = open(".", O_RDONLY | O_DIRECTORY);
    if (дескриптор < 0) return -1;
    if (flock(дескриптор, LOCK_EX) != 0) { close(дескриптор); return -1; }
    return (int32_t)дескриптор;
}

/* ─── Хеш-кэш для защиты от устаревания (инкрементальная сборка) ──────────────
   FNV-1a 64-бит. Арифметика ВЫНЕСЕНА в Konda (`stdlib/хеш.конда: фнв1а_с`, единый
   источник — см. forward-декларацию вверху файла). Хешеры среза и argv — тоже на
   Konda (`фнв1а_с`/`фнв1а_аргв_с`), их шим больше не содержит. Здесь остались лишь
   I/O-хешеры (файл/включения/транспилятор): они читают байты и ДЕЛЕГИРУЮТ счёт в
   `фнв1а_с`, продолжая ключ по конвенции seed (0 → basis). seed-цепочка бесшовно
   стыкует Konda-пути и эти C-пути (см. docs/СИСТЕМА_СБОРКИ.md). */
/* Файл существует? (для проверки выходного бинаря перед пропуском по кэшу —
   иначе `rm вывод/x.elf` при совпавшем ключе не пересобрал бы.) */
static inline int32_t сборка_файл_есть(const char *путь) {
    return access(путь, F_OK) == 0 ? 1 : 0;
}

static inline int64_t сборка_хеш_файла_с(const char *путь, int64_t seed);  /* ниже */

/* Продолжить хеш содержимым ЛОКАЛЬНЫХ C-заголовков, подключённых источником через
   «#содержит "..."» (кавычки — локальный; «<...>» системный, пропускаем). Путь
   заголовка резолвится относительно каталога источника. Один уровень (в сами
   заголовки не спускаемся — v1). Так правка C-шима (напр. сборка_шим.h) меняет
   ключ → пересборка (аналог depfiles -MMD у make). */
static inline int64_t сборка_хеш_включений_с(const char *путь_источника, int64_t seed) {
    int64_t хеш = seed;
    FILE *файл = fopen(путь_источника, "rb");
    if (!файл) return хеш;
    char каталог[4096]; каталог[0] = '\0';
    const char *слэш = strrchr(путь_источника, '/');
    if (слэш) {
        size_t длина = (size_t)(слэш - путь_источника);
        if (длина < sizeof каталог) { memcpy(каталог, путь_источника, длина); каталог[длина] = '\0'; }
    }
    char строка[4096];
    while (fgets(строка, sizeof строка, файл)) {
        char *метка = strstr(строка, "#содержит");
        if (!метка) continue;
        char *кавычка = strchr(метка, '"');
        if (!кавычка) continue;                 /* «<...>» — системный, пропуск */
        char *конец = strchr(кавычка + 1, '"');
        if (!конец) continue;
        char заголовок[4096];
        size_t длина_заг = (size_t)(конец - (кавычка + 1));
        if (длина_заг >= sizeof заголовок) continue;
        memcpy(заголовок, кавычка + 1, длина_заг); заголовок[длина_заг] = '\0';
        char полный[8192];
        if (каталог[0]) snprintf(полный, sizeof полный, "%s/%s", каталог, заголовок);
        else            snprintf(полный, sizeof полный, "%s", заголовок);
        хеш = сборка_хеш_файла_с(полный, хеш);
    }
    fclose(файл);
    return хеш;
}

/* Продолжить хеш содержимым файла, делегируя счёт в Konda `фнв1а_с` (единый
   источник FNV). Файл читается целиком в кучу и хешируется ОДНИМ вызовом — так
   вклад seed-конвенции (0→basis) применяется на границе файла ровно раз, как в
   прежней потоковой версии. Отсутствие файла — стабильный вклад-маркер {0xFE,0xED}
   (чтобы появление/исчезновение источника меняло ключ). Ошибки чтения деградируют
   безопасно (возврат seed без изменения — файл просто не учтён). */
static inline int64_t сборка_хеш_файла_с(const char *путь, int64_t seed) {
    FILE *файл = fopen(путь, "rb");
    if (!файл) {
        unsigned char маркер[2] = { 0xFE, 0xED };
        Срез м = { маркер, 2 };
        return фнв1а_с(м, seed);
    }
    if (fseek(файл, 0, SEEK_END) != 0) { fclose(файл); return seed; }
    long размер = ftell(файл);
    if (размер < 0) { fclose(файл); return seed; }
    rewind(файл);
    unsigned char *данные = (unsigned char *)malloc((size_t)размер + 1);
    if (!данные) { fclose(файл); return seed; }
    size_t прочитано = fread(данные, 1, (size_t)размер, файл);
    fclose(файл);
    Срез содержимое = { данные, прочитано };
    int64_t ключ = фнв1а_с(содержимое, seed);
    free(данные);
    return ключ;
}
/* Продолжить хеш содержимым бинаря транспилятора (KONDA_TRANSPILER или PATH-имя;
   если по имени не открылось — вклад «файла нет», деградирует безопасно). */
static inline int64_t сборка_хеш_транспилятора_с(int64_t seed) {
    const char *транспилятор = getenv("KONDA_TRANSPILER");
    if (!транспилятор || !транспилятор[0]) транспилятор = "ТранспиляторКонда";
    return сборка_хеш_файла_с(транспилятор, seed);
}
/* ─── Окружение C в ключе кэша (§139) ────────────────────────────────────────
   Ключ выше видит лишь файлы проекта, но выход зависит и от ОКРУЖЕНИЯ: версии
   компилятора, пакетов pkg-config и содержимого системных заголовков. Без них
   обновление библиотеки/компилятора или удаление dev-пакета оставляли
   «актуально» (устаревший бинарь, как у make без depfiles системных заголовков).
   Ничего не кэшируем «про запас» (в отличие от meson, помнящего «пакет найден»):
   окружение опрашивается заново на каждой проверке, изменилось → пересборка, и
   транспилятор сам даёт понятную ошибку, если пакета больше нет. Цена — ~2 мс на
   «--version»/pkg-config и ~10–40 мс на «cc -M» (stdio … стек weston). */

/* Запустить команду (execvp, без shell), захватив stdout+stderr в кучу; stdin —
   /dev/null. *вывод — malloc-буфер с NUL в конце (освобождает вызывающий),
   *длина — число байт. Возврат: код выхода (127 — не запустилась), -1 — сбой
   fork/pipe или гибель по сигналу. */
static inline int32_t _сборка_выполнить_захват(char *const *аргументы, char **вывод, size_t *длина) {
    *вывод = NULL;
    *длина = 0;
    int канал[2];
    if (pipe(канал) != 0) return -1;
    fflush(stdout);
    pid_t потомок = fork();
    if (потомок < 0) { close(канал[0]); close(канал[1]); return -1; }
    if (потомок == 0) {
        int пустой = open("/dev/null", O_RDONLY);
        if (пустой >= 0) { dup2(пустой, STDIN_FILENO); close(пустой); }
        dup2(канал[1], STDOUT_FILENO);
        dup2(канал[1], STDERR_FILENO);
        close(канал[0]);
        close(канал[1]);
        execvp(аргументы[0], аргументы);
        _exit(127);
    }
    close(канал[1]);
    size_t ёмкость = 4096, занято = 0;
    char *буфер = (char *)malloc(ёмкость);
    for (;;) {
        if (буфер && занято + 1 >= ёмкость) {
            char *больше = (char *)realloc(буфер, ёмкость * 2);
            if (!больше) { free(буфер); буфер = NULL; }
            else { буфер = больше; ёмкость *= 2; }
        }
        char сброс[4096];
        char *куда = буфер ? буфер + занято : сброс;
        size_t сколько = буфер ? ёмкость - занято - 1 : sizeof сброс;
        ssize_t прочитано = read(канал[0], куда, сколько);
        if (прочитано < 0 && errno == EINTR) continue;
        if (прочитано <= 0) break;
        if (буфер) занято += (size_t)прочитано;   /* без памяти — дочитываем в сброс */
    }
    close(канал[0]);
    int статус;
    int32_t код = -1;
    while (waitpid(потомок, &статус, 0) < 0) {
        if (errno != EINTR) { статус = -1; break; }
    }
    if (статус != -1 && WIFEXITED(статус)) код = (int32_t)WEXITSTATUS(статус);
    if (буфер) буфер[занято] = '\0';
    *вывод = буфер;
    *длина = буфер ? занято : 0;
    return код;
}

/* Продолжить хеш байтами (обёртка над Konda `фнв1а_с`). */
static inline int64_t _сборка_хеш_байтов(const void *данные, size_t длина, int64_t seed) {
    Срез срез = { (void *)данные, длина };
    return фнв1а_с(срез, seed);
}

/* NULL-терминированный argv из префикса и Срез'а символ* (элементы — C-строки). */
static inline char **_сборка_аргв(const char *const *префикс, size_t число_префикса, Срез хвост) {
    char **аргв = (char **)malloc((число_префикса + хвост.длина + 1) * sizeof(char *));
    if (!аргв) return NULL;
    for (size_t i = 0; i < число_префикса; ++i) аргв[i] = (char *)префикс[i];
    for (size_t i = 0; i < хвост.длина; ++i) аргв[число_префикса + i] = ((char **)хвост.данные)[i];
    аргв[число_префикса + хвост.длина] = NULL;
    return аргв;
}

/* Продолжить хеш ВЫВОДОМ (stdout+stderr) и КОДОМ ВЫХОДА команды «аргв» (Срез
   символ*: .данные = char**, argv[0] — программа). Для «cc --version» и
   «pkg-config --modversion --cflags --libs …»: сменилась версия/флаги пакета
   или пакет исчез (pkg-config — ошибка, код 1) → другой ключ. */
static inline int64_t сборка_хеш_команды_с(Срез аргв, int64_t seed) {
    if (аргв.длина == 0) return seed;
    char **полный = _сборка_аргв(NULL, 0, аргв);
    if (!полный) return seed;
    char *вывод;
    size_t длина;
    int32_t код = _сборка_выполнить_захват(полный, &вывод, &длина);
    free(полный);
    int64_t хеш = _сборка_хеш_байтов(вывод ? вывод : "", длина, seed);
    хеш = _сборка_хеш_байтов(&код, sizeof код, хеш);
    free(вывод);
    return хеш;
}

/* Начинается ли «строка» со слова «слово» (байты UTF-8)? Возврат: указатель за
   словом или NULL. */
static inline const char *_сборка_после_слова(const char *строка, const char *слово) {
    size_t длина_слова = strlen(слово);
    return strncmp(строка, слово, длина_слова) == 0 ? строка + длина_слова : NULL;
}

/* Перенести директиву включения из строки источника в пробный C-файл:
   «#содержит <x>»/«#содержит "x"» (и C-запись «#include») — как есть;
   «использовать x.h» (§102: аргумент с точкой) — как «#include "x.h"».
   Возврат: 1 — директива перенесена, 0 — строка не включение. */
static inline int32_t _сборка_проба_строка(const char *строка, FILE *проба) {
    const char *п = строка;
    while (*п == ' ' || *п == '\t') ++п;
    if (*п == '#') {
        ++п;
        while (*п == ' ' || *п == '\t') ++п;
        const char *после = _сборка_после_слова(п, "содержит");
        if (!после) после = _сборка_после_слова(п, "include");
        if (!после) return 0;
        while (*после == ' ' || *после == '\t') ++после;
        char закрывающая = *после == '<' ? '>' : (*после == '"' ? '"' : '\0');
        if (!закрывающая) return 0;
        const char *конец = strchr(после + 1, закрывающая);
        if (!конец) return 0;
        fprintf(проба, "#include %.*s\n", (int)(конец + 1 - после), после);
        return 1;
    }
    const char *после = _сборка_после_слова(п, "использовать");
    if (!после || (*после != ' ' && *после != '\t')) return 0;
    while (*после == ' ' || *после == '\t') ++после;
    const char *конец = после;
    int есть_точка = 0;
    while (*конец && *конец != '\n' && *конец != '\r' && !(конец[0] == '/' && конец[1] == '/')) {
        if (*конец == '.') есть_точка = 1;
        ++конец;
    }
    while (конец > после && (конец[-1] == ' ' || конец[-1] == '\t')) --конец;
    if (!есть_точка || конец == после) return 0;   /* «использовать Имя» — импорт пространства */
    fprintf(проба, "#include \"%.*s\"\n", (int)(конец - после), после);
    return 1;
}

/* Разбить вывод «pkg-config --cflags» на слова НА МЕСТЕ (pkg-config экранирует
   пробелы/спецсимволы обратным слэшем). Возврат: malloc-массив указателей в
   «текст» (NULL-терминирован), *число — сколько слов. */
static inline char **_сборка_разбить_слова(char *текст, size_t *число) {
    size_t ёмкость = strlen(текст) / 2 + 2;
    char **слова = (char **)malloc(ёмкость * sizeof(char *));
    *число = 0;
    if (!слова) return NULL;
    char *чтение = текст, *запись = текст;
    for (;;) {
        while (*чтение == ' ' || *чтение == '\t' || *чтение == '\n' || *чтение == '\r') ++чтение;
        if (!*чтение) break;
        слова[(*число)++] = запись;
        while (*чтение && *чтение != ' ' && *чтение != '\t' && *чтение != '\n' && *чтение != '\r') {
            if (*чтение == '\\' && чтение[1]) ++чтение;
            *запись++ = *чтение++;
        }
        if (*чтение) ++чтение;
        *запись++ = '\0';
    }
    слова[*число] = NULL;
    return слова;
}

/* Продолжить хеш содержимым ВСЕХ заголовков, которые реально подключают
   источники (системные «<…>» транзитивно, локальные «"…"» — тоже):
   директивы включения источников → пробный .c во временном каталоге →
   «<компилятор> -M -MG -MT konda -iquote . <флаги> <cflags пакетов> проба.c»
   (флаги — «-I/-D» манифеста, пакеты — имена pkg-config; -MG: отсутствующий
   заголовок не ошибка, а имя в списке → его появление/исчезновение меняет ключ).
   В ключ — путь КАЖДОГО заголовка из списка и его содержимое. Сбой опроса
   (нет компилятора, #error) — стабильный маркер + код (вывод не хешируем: в нём
   случайное имя пробы). Источников без включений → seed без изменений. */
static inline int64_t сборка_хеш_заголовков_с(const char *компилятор, Срез флаги, Срез пакеты, int64_t seed) {
    const char *каталог_tmp = getenv("TMPDIR");
    if (!каталог_tmp || !каталог_tmp[0]) каталог_tmp = "/tmp";
    char путь_пробы[4096];
    if (snprintf(путь_пробы, sizeof путь_пробы, "%s/konda-проба-XXXXXX.c", каталог_tmp)
        >= (int)sizeof путь_пробы) return seed;
    int дескриптор = mkstemps(путь_пробы, 2);
    if (дескриптор < 0) return _сборка_хеш_байтов("нет-пробы", strlen("нет-пробы"), seed);
    FILE *проба = fdopen(дескриптор, "w");
    if (!проба) { close(дескриптор); unlink(путь_пробы); return seed; }
    int32_t включений = 0;
    for (int32_t i = 0; i < _сборка_число_источников; ++i) {
        FILE *источник = fopen(_сборка_источники[i], "rb");
        if (!источник) continue;
        char строка[4096];
        while (fgets(строка, sizeof строка, источник)) включений += _сборка_проба_строка(строка, проба);
        fclose(источник);
    }
    fclose(проба);
    if (включений == 0) { unlink(путь_пробы); return seed; }

    /* cflags пакетов: те же каталоги поиска, что у транспилятора (§129). Провал
       pkg-config здесь не важен — его уже учёл сборка_хеш_команды_с. */
    char *вывод_cflags = NULL;
    char **слова_cflags = NULL;
    size_t число_cflags = 0;
    if (пакеты.длина > 0) {
        const char *префикс_pkg[] = { "pkg-config", "--cflags" };
        char **аргв_pkg = _сборка_аргв(префикс_pkg, 2, пакеты);
        size_t длина_cflags;
        if (аргв_pkg && _сборка_выполнить_захват(аргв_pkg, &вывод_cflags, &длина_cflags) == 0 && вывод_cflags)
            слова_cflags = _сборка_разбить_слова(вывод_cflags, &число_cflags);
        free(аргв_pkg);
    }

    const char *префикс_cc[] = { компилятор, "-M", "-MG", "-MT", "konda", "-iquote", "." };
    size_t число_префикса = sizeof префикс_cc / sizeof префикс_cc[0];
    size_t всего = число_префикса + флаги.длина + число_cflags + 2;
    char **аргв_cc = (char **)malloc(всего * sizeof(char *));
    int64_t хеш = seed;
    if (аргв_cc) {
        size_t к = 0;
        for (size_t i = 0; i < число_префикса; ++i) аргв_cc[к++] = (char *)префикс_cc[i];
        for (size_t i = 0; i < флаги.длина; ++i) аргв_cc[к++] = ((char **)флаги.данные)[i];
        for (size_t i = 0; i < число_cflags; ++i) аргв_cc[к++] = слова_cflags[i];
        аргв_cc[к++] = путь_пробы;
        аргв_cc[к] = NULL;
        char *зависимости;
        size_t длина_зависимостей;
        int32_t код = _сборка_выполнить_захват(аргв_cc, &зависимости, &длина_зависимостей);
        if (код != 0 || !зависимости) {
            хеш = _сборка_хеш_байтов("сбой-пробы", strlen("сбой-пробы"), хеш);
            хеш = _сборка_хеш_байтов(&код, sizeof код, хеш);
        } else {
            /* Правило make: «konda: файл файл \<NL> файл…»; пробел в имени — «\ »,
               «$» — «$$». Первый файл — сама проба (случайное имя) — пропускаем. */
            char *п = strchr(зависимости, ':');
            п = п ? п + 1 : зависимости + длина_зависимостей;
            char имя[8192];
            for (;;) {
                while (*п == ' ' || *п == '\t' || *п == '\n' || *п == '\r'
                       || (п[0] == '\\' && (п[1] == '\n' || п[1] == '\r'))) {
                    п += (п[0] == '\\') ? 2 : 1;
                }
                if (!*п) break;
                size_t длина_имени = 0;
                while (*п && *п != ' ' && *п != '\t' && *п != '\n' && *п != '\r') {
                    if (п[0] == '\\' && (п[1] == '\n' || п[1] == '\r')) break;
                    if (п[0] == '\\' && п[1] == ' ') ++п;
                    else if (п[0] == '$' && п[1] == '$') ++п;
                    if (длина_имени + 1 < sizeof имя) имя[длина_имени++] = *п;
                    ++п;
                }
                имя[длина_имени] = '\0';
                if (strcmp(имя, путь_пробы) == 0) continue;
                хеш = _сборка_хеш_байтов(имя, длина_имени + 1, хеш);   /* +NUL — граница имён */
                хеш = сборка_хеш_файла_с(имя, хеш);
            }
        }
        free(зависимости);
        free(аргв_cc);
    }
    free(слова_cflags);
    free(вывод_cflags);
    unlink(путь_пробы);
    return хеш;
}

/* Прочитать сохранённый ключ (0 — нет кэша/ошибка). */
static inline int64_t сборка_читать_кэш(const char *путь) {
    FILE *файл = fopen(путь, "r");
    if (!файл) return 0;
    long long значение = 0;
    if (fscanf(файл, "%lld", &значение) != 1) значение = 0;
    fclose(файл);
    return (int64_t)значение;
}
/* Записать ключ. */
static inline void сборка_писать_кэш(const char *путь, int64_t значение) {
    FILE *файл = fopen(путь, "w");
    if (файл) { fprintf(файл, "%lld\n", (long long)значение); fclose(файл); }
}
/* Сравнение строк / «начинается с» для разбора флагов argv — на Konda (`==` над
   срезами §100 и `строки.начинается_с`); шим C-версий не держит. */

/* Собрать зависимость: запустить ЭТОТ ЖЕ фронтенд в каталоге зависимости (у неё
   свой Konda.toml и свой .konda-сборка.кэш → пер-проектный инкремент). Возврат:
   код выхода дочерней сборки или -1. */
static inline int32_t сборка_собрать_зависимость(const char *каталог) {
    char сам[4096];
    ssize_t длина = readlink("/proc/self/exe", сам, sizeof сам - 1);
    if (длина < 0) return -1;
    сам[длина] = '\0';
    fflush(stdout);
    pid_t потомок = fork();
    if (потомок < 0) return -1;
    if (потомок == 0) {
        if (chdir(каталог) != 0) _exit(126);
        execl(сам, сам, (char *)NULL);
        _exit(127);
    }
    int статус;
    if (waitpid(потомок, &статус, 0) < 0) return -1;
    return WIFEXITED(статус) ? (int32_t)WEXITSTATUS(статус) : -1;
}

/* Переименовать файл (для поля «выход»). Пути — срезы (NUL-терминируем внутри).
   Возврат: 0 или -1. */
static inline int32_t сборка_переименовать_срез(Срез из, Срез в) {
    char *путь_из = (char *)malloc(из.длина + 1);
    char *путь_в = (char *)malloc(в.длина + 1);
    int32_t итог = -1;
    if (путь_из && путь_в) {
        memcpy(путь_из, из.данные, из.длина); путь_из[из.длина] = '\0';
        memcpy(путь_в, в.данные, в.длина);   путь_в[в.длина] = '\0';
        итог = rename(путь_из, путь_в) == 0 ? 0 : -1;
    }
    free(путь_из); free(путь_в);
    return итог;
}
