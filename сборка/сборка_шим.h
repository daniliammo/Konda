/* ─────────────────────────────────────────────────────────────────────────────
   сборка_шим.h — L1: доверенный C-шим фронтенда сборки Konda.
   Единственная зона «небезопасности» build-фронтенда: чтение файла и запуск
   транспилятора. Konda-слой (сборка.конда) сюда не смотрит, работает только с
   безопасными обёртками. Паттерн — как stdlib/конда_ио.h.

   Тип Срез должен совпадать с ТИПДЕФ_СРЕЗ кодогена; общий guard KONDA_SREZ_DEFINED.
   ────────────────────────────────────────────────────────────────────────── */
#pragma once
#include <stddef.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#ifndef KONDA_SREZ_DEFINED
#define KONDA_SREZ_DEFINED
typedef struct { void *данные; size_t длина; } Срез;
#endif

/* Прочитать файл целиком в буфер (Срез {данные, длина} — границы гарантированы
   длиной по построению). Возврат: число прочитанных байт (>=0) или -1. */
static inline int32_t сборка_прочитать_файл(const char *путь, Срез буфер) {
    FILE *файл = fopen(путь, "rb");
    if (!файл) return -1;
    size_t прочитано = fread(буфер.данные, 1, буфер.длина, файл);
    fclose(файл);
    return (int32_t)прочитано;
}

/* Запустить транспилятор с хвостом аргументов (флаги + источники). Путь к
   транспилятору — из окружения KONDA_TRANSPILER, иначе «ТранспиляторКонда» (PATH).
   «хвост» — Срез сырых байт команды (без NUL); шим сам добавляет NUL.
   Возврат: код выхода транспилятора (0 — успех) или -1 при ошибке запуска. */
static inline int32_t сборка_запустить(Срез хвост) {
    const char *транспилятор = getenv("KONDA_TRANSPILER");
    if (!транспилятор || !транспилятор[0]) транспилятор = "ТранспиляторКонда";
    size_t длина_нужна = strlen(транспилятор) + 2 + хвост.длина + 1;
    char *команда = (char *)malloc(длина_нужна);
    if (!команда) return -1;
    int префикс = snprintf(команда, длина_нужна, "%s ", транспилятор);
    memcpy(команда + префикс, хвост.данные, хвост.длина);
    команда[префикс + хвост.длина] = '\0';
    int результат = system(команда);
    free(команда);
    if (результат == -1) return -1;
    return (int32_t)((результат >> 8) & 0xff);   /* код выхода потомка */
}
