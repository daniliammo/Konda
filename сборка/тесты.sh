#!/bin/sh
# E2E-тест фронтенда «konda build»: собрать фронтенд, прогнать на демо-проекте
# сборка/пример (манифест Konda.toml → транспилятор → рабочий .elf). POSIX sh,
# имена переменных — ASCII.
set -eu
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/.." && pwd)"
BIN="$ROOT/Собранное/ТранспиляторКонда"
FRONT="$HERE/вывод/сборка.elf"
DEMO="$HERE/пример"

fail() { echo "  ОШИБКА: $1" >&2; exit 1; }

echo "== сборка фронтенда (libkonda_toml + сборка.конда) =="
sh "$HERE/собрать.sh" >/dev/null 2>&1 || fail "фронтенд не собрался"
[ -x "$FRONT" ] || fail "нет $FRONT"
echo "  ок"

echo "== konda build на демо-проекте (манифест → транспилятор → .elf) =="
[ -f "$DEMO/Konda.toml" ] || fail "нет демо-манифеста $DEMO/Konda.toml"
rm -rf "$DEMO/вывод"
( cd "$DEMO" && KONDA_TRANSPILER="$BIN" "$FRONT" >"$HERE/вывод/e2e.log" 2>&1 ) \
    || { cat "$HERE/вывод/e2e.log" >&2; fail "konda build завершился с ошибкой"; }
grep -q "готово" "$HERE/вывод/e2e.log" || { cat "$HERE/вывод/e2e.log" >&2; fail "нет отметки 'готово'"; }
[ -x "$DEMO/вывод/привет.elf" ] || fail "транспилятор не собрал привет.elf"
OUTP="$("$DEMO/вывод/привет.elf")"
[ "$OUTP" = "привет из собранной программы" ] \
    || fail "собранная программа дала неожиданный вывод: [$OUTP]"
echo "  ок: манифест разобран, программа собрана и запущена"

echo "== §89: версия из [проект].версия вшита в ELF =="
# Демо-манифест: версия = "0.1.0" → штамп в бинарнике (символ/нота/.comment).
strings "$DEMO/вывод/привет.elf" | grep -q "project=0.1.0" \
    || fail "версия проекта из Konda.toml не попала в ELF (нота .note.konda)"
echo "  ок: [проект].версия → --версия-проекта → ELF"

echo "== хеш-кэш: повторный прогон пропускает сборку =="
( cd "$DEMO" && KONDA_TRANSPILER="$BIN" "$FRONT" >"$HERE/вывод/e2e2.log" 2>&1 ) || fail "2-й прогон упал"
grep -q "актуально" "$HERE/вывод/e2e2.log" \
    || { cat "$HERE/вывод/e2e2.log" >&2; fail "2-й прогон должен был пропустить сборку (кэш)"; }
echo "  ок: кэш совпал → сборка пропущена"

echo "== --пересобрать форсирует сборку несмотря на кэш =="
( cd "$DEMO" && KONDA_TRANSPILER="$BIN" "$FRONT" --пересобрать >"$HERE/вывод/e2e3.log" 2>&1 ) || fail "форс-прогон упал"
grep -q "готово" "$HERE/вывод/e2e3.log" \
    || { cat "$HERE/вывод/e2e3.log" >&2; fail "--пересобрать должен был собрать заново"; }
echo "  ок: --пересобрать собрал заново"

echo "== смена флага в манифесте → пересборка (не устаревает) =="
cp "$DEMO/Konda.toml" "$HERE/вывод/Konda.toml.копия"
sed -i 's/режим       = "релиз"/режим       = "дебаг"/' "$DEMO/Konda.toml"
( cd "$DEMO" && KONDA_TRANSPILER="$BIN" "$FRONT" >"$HERE/вывод/e2e4.log" 2>&1 ); RC=$?
cp "$HERE/вывод/Konda.toml.копия" "$DEMO/Konda.toml"   # восстановить
[ "$RC" = 0 ] || { cat "$HERE/вывод/e2e4.log" >&2; fail "прогон после смены флага упал"; }
grep -q "готово" "$HERE/вывод/e2e4.log" \
    || { cat "$HERE/вывод/e2e4.log" >&2; fail "смена флага должна была вызвать пересборку"; }
echo "  ок: смена флага манифеста → ключ изменился → пересборка"

echo "== #2: удаление выходного бинаря → пересборка (кэш не пропускает без бинаря) =="
rm -f "$DEMO/вывод/привет.elf"
( cd "$DEMO" && KONDA_TRANSPILER="$BIN" "$FRONT" >"$HERE/вывод/e2e5.log" 2>&1 ) || { cat "$HERE/вывод/e2e5.log" >&2; fail "прогон после rm бинаря упал"; }
grep -q "сборка" "$HERE/вывод/e2e5.log" || { cat "$HERE/вывод/e2e5.log" >&2; fail "удалён бинарь, но сборка пропущена по кэшу (#2)"; }
[ -x "$DEMO/вывод/привет.elf" ] || fail "бинарь не восстановлен после rm"
echo "  ок: нет бинаря → пересборка несмотря на совпавший кэш"

echo "== #3: правка локального C-заголовка меняет ключ → пересборка =="
INCDIR="$HERE/вывод/вкл-проект"
rm -rf "$INCDIR"; mkdir -p "$INCDIR"
printf '#pragma once\nstatic inline int дв(int x){return x*2;}\n' > "$INCDIR/ш.h"
cat > "$INCDIR/м.конда" <<'KONDA'
#содержит <stdio.h>
#содержит "ш.h"
внешняя целое32 дв(целое32 x)
целое32 точка_входа(срез<символ*> аргументы)
{
    printf("%d\n", дв(3))
    вернуть 0
}
KONDA
printf '[проект]\n' > "$INCDIR/Konda.toml"
( cd "$INCDIR" && KONDA_TRANSPILER="$BIN" "$FRONT" >/dev/null 2>&1 ) || fail "вкл: первая сборка упала"
printf '#pragma once\nstatic inline int дв(int x){return x*3;}\n' > "$INCDIR/ш.h"
( cd "$INCDIR" && KONDA_TRANSPILER="$BIN" "$FRONT" >"$HERE/вывод/e2e6.log" 2>&1 ) || fail "вкл: пересборка упала"
grep -q "сборка" "$HERE/вывод/e2e6.log" || { cat "$HERE/вывод/e2e6.log" >&2; fail "правка C-заголовка не вызвала пересборку (#3)"; }
echo "  ок: изменённый #содержит-заголовок → пересборка"

echo "== #1: смена ИСТОЧНИКА зависимости → пересборка главного (транзитивно) =="
DEPROOT="$HERE/вывод/деп-проект"
rm -rf "$DEPROOT"; mkdir -p "$DEPROOT/либа" "$DEPROOT/главный"
printf 'целое32 ф(целое32 x) { вернуть x }\n' > "$DEPROOT/либа/л.конда"
printf '[проект]\nтип = "библиотека"\n' > "$DEPROOT/либа/Konda.toml"
cat > "$DEPROOT/главный/г.конда" <<'KONDA'
#содержит <stdio.h>
целое32 точка_входа(срез<символ*> аргументы)
{
    printf("g\n")
    вернуть 0
}
KONDA
printf '[проект]\n[сборка]\nзависимости = ["../либа"]\n' > "$DEPROOT/главный/Konda.toml"
( cd "$DEPROOT/главный" && KONDA_TRANSPILER="$BIN" "$FRONT" >/dev/null 2>&1 ) || fail "деп: первая сборка упала"
( cd "$DEPROOT/главный" && KONDA_TRANSPILER="$BIN" "$FRONT" >"$HERE/вывод/e2e7.log" 2>&1 ) || fail "деп: повтор упал"
grep -q "актуально" "$HERE/вывод/e2e7.log" || { cat "$HERE/вывод/e2e7.log" >&2; fail "без изменений главный должен быть актуален"; }
printf 'целое32 ф(целое32 x) { вернуть x + 1 }\n' > "$DEPROOT/либа/л.конда"
( cd "$DEPROOT/главный" && KONDA_TRANSPILER="$BIN" "$FRONT" >"$HERE/вывод/e2e8.log" 2>&1 ) || fail "деп: пересборка упала"
grep -q "\[хост\] сборка" "$HERE/вывод/e2e8.log" || { cat "$HERE/вывод/e2e8.log" >&2; fail "смена источника зависимости не пересобрала главного (#1)"; }
echo "  ок: изменилась зависимость → главный пересобрался"

echo "== execvp: путь источника с ПРОБЕЛОМ собирается (system() бы разбил по словам) =="
SPACEDIR="$HERE/вывод/проб-проект"
rm -rf "$SPACEDIR"; mkdir -p "$SPACEDIR"
cat > "$SPACEDIR/мой модуль.конда" <<'KONDA'
#содержит <stdio.h>
целое32 точка_входа(срез<символ*> аргументы)
{
    printf("пробел ок\n")
    вернуть 0
}
KONDA
cat > "$SPACEDIR/Konda.toml" <<'TOML'
[проект]
выход     = "прог"
TOML
( cd "$SPACEDIR" && KONDA_TRANSPILER="$BIN" "$FRONT" >"$HERE/вывод/проб.log" 2>&1 ) \
    || { cat "$HERE/вывод/проб.log" >&2; fail "сборка с пробелом в пути упала"; }
[ -x "$SPACEDIR/вывод/прог" ] || fail "выход не собран для пути с пробелом"
[ "$("$SPACEDIR/вывод/прог")" = "пробел ок" ] \
    || fail "программа из пути с пробелом дала неверный вывод"
echo "  ок: путь с пробелом собран (execvp, без shell)"

echo "== [проект].имя → --имя: монолитная библиотека из НЕСКОЛЬКИХ источников =="
# Имя артефакта берётся из «имя», а НЕ из первого источника (иначе .so назвался бы
# «а.so»). Так собирается сама stdlib (stdlib/Konda.toml, имя = "libkonda_std").
LIBDIR="$HERE/вывод/имя-либа"
rm -rf "$LIBDIR"; mkdir -p "$LIBDIR"
cat > "$LIBDIR/а.конда" <<'KONDA'
целое32 удвоить(целое32 x) { вернуть x * 2 }
KONDA
cat > "$LIBDIR/б.конда" <<'KONDA'
целое32 утроить(целое32 x) { вернуть x * 3 }
KONDA
cat > "$LIBDIR/Konda.toml" <<'TOML'
[проект]
тип       = "библиотека"
имя       = "мойлиб"
[сборка]
режим = "релиз"
TOML
( cd "$LIBDIR" && KONDA_TRANSPILER="$BIN" "$FRONT" >"$HERE/вывод/имялиба.log" 2>&1 ) \
    || { cat "$HERE/вывод/имялиба.log" >&2; fail "сборка именованной библиотеки упала"; }
[ -f "$LIBDIR/вывод/мойлиб.so" ] || fail "--имя не применилось: нет вывод/мойлиб.so"
[ -f "$LIBDIR/вывод/мойлиб.и" ] || fail "--имя не применилось: нет вывод/мойлиб.и (интерфейс)"
[ ! -f "$LIBDIR/вывод/а.so" ] || fail "библиотека названа по первому источнику (а.so), а не по имени"
# Обе функции из РАЗНЫХ источников попали в один монолит (§18/§80).
grep -q "удвоить" "$LIBDIR/вывод/мойлиб.и" && grep -q "утроить" "$LIBDIR/вывод/мойлиб.и" \
    || fail "не все модули слились в монолит (в .и нет обеих функций)"
echo "  ок: имя из манифеста → монолит вывод/мойлиб.{so,и}, оба модуля внутри"

echo "== кэш именованной библиотеки: повторный прогон пропускает (бинарь на месте) =="
( cd "$LIBDIR" && KONDA_TRANSPILER="$BIN" "$FRONT" >"$HERE/вывод/имялиба2.log" 2>&1 ) \
    || { cat "$HERE/вывод/имялиба2.log" >&2; fail "2-й прогон именованной либы упал"; }
grep -q "актуально" "$HERE/вывод/имялиба2.log" \
    || { cat "$HERE/вывод/имялиба2.log" >&2; fail "ожидаемый путь выхода .so не совпал с --имя → кэш не пропустил"; }
echo "  ок: ожидаемый путь артефакта учитывает имя → кэш пропускает"

echo "== -j: параллельная сборка нескольких зависимостей =="
PARROOT="$HERE/вывод/пар-деп"
rm -rf "$PARROOT"; mkdir -p "$PARROOT/д1" "$PARROOT/д2" "$PARROOT/д3" "$PARROOT/корень"
for i in 1 2 3; do
    printf 'целое32 ф%s(целое32 x) { вернуть x }\n' "$i" > "$PARROOT/д$i/л.конда"
    printf '[проект]\nтип = "библиотека"\n' > "$PARROOT/д$i/Konda.toml"
done
cat > "$PARROOT/корень/к.конда" <<'KONDA'
#содержит <stdio.h>
целое32 точка_входа(срез<символ*> аргументы)
{
    printf("корень ок\n")
    вернуть 0
}
KONDA
printf '[проект]\n[сборка]\nзависимости = ["../д1", "../д2", "../д3"]\n' > "$PARROOT/корень/Konda.toml"
( cd "$PARROOT/корень" && KONDA_TRANSPILER="$BIN" "$FRONT" -j4 >"$HERE/вывод/парj.log" 2>&1 ) \
    || { cat "$HERE/вывод/парj.log" >&2; fail "-j: сборка с параллельными зависимостями упала"; }
grep -q "готово" "$HERE/вывод/парj.log" || { cat "$HERE/вывод/парj.log" >&2; fail "-j: нет 'готово'"; }
for i in 1 2 3; do
    [ -f "$PARROOT/д$i/вывод/л.so" ] || fail "-j: зависимость д$i не собрана"
done
[ -x "$PARROOT/корень/вывод/к.elf" ] || fail "-j: корень не собран"
[ "$("$PARROOT/корень/вывод/к.elf")" = "корень ок" ] || fail "-j: корень дал неверный вывод"
echo "  ок: 3 зависимости собраны под -j4, корень слинкован и запущен"

echo "== -j: ромб зависимостей (общая под-зависимость) собирается корректно =="
ROMB="$HERE/вывод/пар-ромб"
rm -rf "$ROMB"; mkdir -p "$ROMB/общая" "$ROMB/а" "$ROMB/б" "$ROMB/гл"
printf 'целое32 общ(целое32 x) { вернуть x }\n' > "$ROMB/общая/о.конда"
printf '[проект]\nтип = "библиотека"\n' > "$ROMB/общая/Konda.toml"
for d in а б; do
    printf 'целое32 ф(целое32 x) { вернуть x }\n' > "$ROMB/$d/л.конда"
    printf '[проект]\nтип = "библиотека"\n[сборка]\nзависимости = ["../общая"]\n' > "$ROMB/$d/Konda.toml"
done
cat > "$ROMB/гл/г.конда" <<'KONDA'
#содержит <stdio.h>
целое32 точка_входа(срез<символ*> аргументы)
{
    printf("ромб ок\n")
    вернуть 0
}
KONDA
printf '[проект]\n[сборка]\nзависимости = ["../а", "../б"]\n' > "$ROMB/гл/Konda.toml"
( cd "$ROMB/гл" && KONDA_TRANSPILER="$BIN" "$FRONT" -j8 >"$HERE/вывод/ромб.log" 2>&1 ) \
    || { cat "$HERE/вывод/ромб.log" >&2; fail "-j: ромб-сборка упала"; }
grep -q "готово" "$HERE/вывод/ромб.log" || { cat "$HERE/вывод/ромб.log" >&2; fail "-j: ромб без 'готово'"; }
[ -f "$ROMB/общая/вывод/о.so" ] || fail "-j: общая под-зависимость не собрана"
[ -x "$ROMB/гл/вывод/г.elf" ] || fail "-j: ромб-корень не собран"
echo "  ок: общая под-зависимость собрана без гонки (блокировка каталога), ромб корректен"

echo "== -j: параллельная сборка нескольких целей (кросс, если есть тулчейн) =="
if command -v x86_64-linux-gnu-gcc >/dev/null 2>&1; then
    PT="$HERE/вывод/пар-цели"
    rm -rf "$PT"; mkdir -p "$PT"
    cat > "$PT/п.конда" <<'KONDA'
#содержит <stdio.h>
целое32 точка_входа(срез<символ*> аргументы)
{
    printf("цель ок\n")
    вернуть 0
}
KONDA
    printf '[проект]\n[сборка]\nцели = ["хост", "x86_64-linux-gnu"]\n' > "$PT/Konda.toml"
    ( cd "$PT" && KONDA_TRANSPILER="$BIN" "$FRONT" -j4 >"$HERE/вывод/парцели.log" 2>&1 ) \
        || { cat "$HERE/вывод/парцели.log" >&2; fail "-j: параллельные цели упали"; }
    grep -q "готово" "$HERE/вывод/парцели.log" || fail "-j: цели без 'готово'"
    [ -x "$PT/вывод/п.elf" ] || fail "-j: хост-цель не собрана"
    [ -x "$PT/вывод/x86_64-linux-gnu/п.elf" ] || fail "-j: кросс-цель не собрана"
    echo "  ок: две цели (хост + x86_64-linux-gnu) собраны параллельно в раздельные каталоги"
else
    echo "  пропуск: нет x86_64-linux-gnu-gcc (кросс-цели не проверить на этом хосте)"
fi

echo "== -j паритет: демо под -j даёт тот же результат =="
rm -rf "$DEMO/вывод"
( cd "$DEMO" && KONDA_TRANSPILER="$BIN" "$FRONT" -j2 >"$HERE/вывод/демоj.log" 2>&1 ) \
    || { cat "$HERE/вывод/демоj.log" >&2; fail "-j2 на демо упал"; }
[ -x "$DEMO/вывод/привет.elf" ] || fail "-j2: демо не собралось"
[ "$("$DEMO/вывод/привет.elf")" = "привет из собранной программы" ] || fail "-j2: демо дало неверный вывод"
echo "  ок: -j2 собрало демо идентично последовательному"

echo "== авто-скан: без [проект].исходники источники находятся сами (*.конда) =="
# Как в Cargo: манифест НЕ перечисляет исходники. Два реальных источника +
# один не-исходник (со своей точкой входа) убирается через «исключить».
SCANDIR="$HERE/вывод/скан-проект"
rm -rf "$SCANDIR"; mkdir -p "$SCANDIR"
cat > "$SCANDIR/главная.конда" <<'KONDA'
#содержит <stdio.h>
внешняя целое32 удвоить(целое32 x)
целое32 точка_входа(срез<символ*> аргументы)
{
    printf("скан: %d\n", удвоить(21))
    вернуть 0
}
KONDA
printf 'целое32 удвоить(целое32 x) { вернуть x + x }\n' > "$SCANDIR/помощник.конда"
# не-исходник: своя точка входа, в сборку попасть не должен
printf 'целое32 точка_входа(срез<символ*> аргументы) { вернуть 7 }\n' > "$SCANDIR/демо_пример.конда"
cat > "$SCANDIR/Konda.toml" <<'TOML'
[проект]
имя       = "скан"
выход     = "скан"
исключить = ["демо_пример.конда"]
TOML
( cd "$SCANDIR" && KONDA_TRANSPILER="$BIN" "$FRONT" >"$HERE/вывод/скан.log" 2>&1 ) \
    || { cat "$HERE/вывод/скан.log" >&2; fail "авто-скан: сборка упала"; }
grep -q "2 источник" "$HERE/вывод/скан.log" \
    || { cat "$HERE/вывод/скан.log" >&2; fail "авто-скан должен был найти ровно 2 источника"; }
[ -x "$SCANDIR/вывод/скан" ] || fail "авто-скан: выход не собран"
[ "$("$SCANDIR/вывод/скан")" = "скан: 42" ] || fail "авто-скан: неверный вывод программы"
echo "  ок: источники найдены сканом, не-исходник исключён"

echo "== авто-скан: fallback имени выхода = базовое имя первого источника =="
# Ни «имя», ни «выход» — транспилятор и фронтенд именуют выход по первому файлу.
FALLDIR="$HERE/вывод/скан-fallback"
rm -rf "$FALLDIR"; mkdir -p "$FALLDIR"
cat > "$FALLDIR/альфа.конда" <<'KONDA'
#содержит <stdio.h>
целое32 точка_входа(срез<символ*> аргументы) { printf("а\n"); вернуть 0 }
KONDA
printf '[проект]\nверсия = "0.1.0"\n' > "$FALLDIR/Konda.toml"
( cd "$FALLDIR" && KONDA_TRANSPILER="$BIN" "$FRONT" >"$HERE/вывод/fallback.log" 2>&1 ) \
    || { cat "$HERE/вывод/fallback.log" >&2; fail "авто-скан fallback: сборка упала"; }
