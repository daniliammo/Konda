#define МАКС_ТИПОПАРАМ 8
#define МАКС_ШАБЛОНОВ  128

// ─── вспомогательное ─────────────────────────────────────────────────────────

static int байты_равны_л(const char *a, size_t la, const char *b, size_t lb)
{
    return la == lb && memcmp(a, b, la) == 0;
}

// Число ведущих детей-УЗЕЛ_ТИПОПАРАМЕТР функции (сколько у неё тип-параметров).
static size_t число_типопараметров_функции(const Узел *ф)
{
    size_t n = 0;
    for (size_t i = 0; i < узел_число_детей(ф); ++i) {
        const Узел *реб = узел_ребёнок(ф, i);
        if (реб && реб->тип == УЗЕЛ_ТИПОПАРАМЕТР) n++;
        else break;  // тип-параметры идут строго перед параметрами
    }
    return n;
}

// Число ведущих детей-УЗЕЛ_ТИПОАРГУМЕНТ вызова.
static size_t число_типоаргументов_вызова(const Узел *в)
{
    size_t n = 0;
    for (size_t i = 0; i < узел_число_детей(в); ++i) {
        const Узел *реб = узел_ребёнок(в, i);
        if (реб && реб->тип == УЗЕЛ_ТИПОАРГУМЕНТ) n++;
        else break;
    }
    return n;
}

// Удаляет (и освобождает) всех детей заданного типа, компактируя массив.
static void удалить_детей_типа(Узел *у, ТипУзла т)
{
    size_t w = 0;
    for (size_t r = 0; r < у->дети.длина; ++r) {
        Узел *реб = узел_ребёнок(у, r);
        if (реб && реб->тип == т) {
            освободить_узел(реб);
            continue;
        }
        Узел **слот = дин_массив_получить(&у->дети, w);
        *слот = реб;
        w++;
    }
    у->дети.длина = w;
}

// Konda-имя конкретного типа для суффикса мономорфизированного имени. Результат
// — валидный идентификатор Konda (кириллица/цифры/подчёркивание): указатели
// кодируются «_ук», беззнаковость — «неподписанный_».
static void суффикс_типа(const Узел *та, char *out, size_t cap)
{
    char базовый[128];
    switch (та->тип_данных) {
        case ТОКЕН_ЦЕЛОЕ8:  snprintf(базовый, sizeof базовый, "целое8");  break;
        case ТОКЕН_ЦЕЛОЕ16: snprintf(базовый, sizeof базовый, "целое16"); break;
        case ТОКЕН_ЦЕЛОЕ32: snprintf(базовый, sizeof базовый, "целое32"); break;
        case ТОКЕН_ЦЕЛОЕ64: snprintf(базовый, sizeof базовый, "целое64"); break;
        case ТОКЕН_БАЙТ:         snprintf(базовый, sizeof базовый, "байт"); break;
        case ТОКЕН_ВЕЩЕСТВЕННОЕ:  snprintf(базовый, sizeof базовый, "вещественное"); break;
        case ТОКЕН_ВЕЩЕСТВЕННОЕ64: snprintf(базовый, sizeof базовый, "вещественное64"); break;
        case ТОКЕН_ТИП_СИМВОЛ:   snprintf(базовый, sizeof базовый, "символ"); break;
        case ТОКЕН_ЛОГИЧЕСКИЙ:   snprintf(базовый, sizeof базовый, "логический"); break;
        case ТОКЕН_СТРУКТУРА:
        case ТОКЕН_ПЕРЕЧИСЛЕНИЕ:
            snprintf(базовый, sizeof базовый, "%.*s",
                     (int)та->имя_типа.длина, та->имя_типа.начало);
            break;
        default: snprintf(базовый, sizeof базовый, "тип"); break;
    }
    char укз[24] = {0};
    for (int i = 0; i < та->указатели && i < 8; ++i) memcpy(укз + i * 3, "_ук", 3);
    snprintf(out, cap, "%s%s%s", та->беззнаковый ? "неподписанный_" : "",
             базовый, укз);
}

// ─── подстановка тип-параметров ──────────────────────────────────────────────

// Заменяет в поддереве каждый ТОКЕН_ТИПОПАРАМЕТР на соответствующий конкретный
// тип из тип-аргументов (позиционно по именам). Указатели складываются:
// «T*» при T = символ* даёт символ**.
static void подставить(Узел *узел, const Токен парам_имена[], size_t число_парам,
                       const Узел *типарг[])
{
    if (!узел) return;
    if (узел->тип_данных == ТОКЕН_ТИПОПАРАМЕТР) {
        for (size_t k = 0; k < число_парам; ++k) {
            if (байты_равны_л(узел->имя_типа.начало, узел->имя_типа.длина,
                              парам_имена[k].начало, парам_имена[k].длина)) {
                const Узел *та = типарг[k];
                узел->тип_данных  = та->тип_данных;
                узел->беззнаковый = та->беззнаковый;
                узел->срез       |= та->срез;
                узел->указатели  += та->указатели;
                // Имя типа копируем ГЛУБОКО в собственную owned-строку: у
                // выведенных тип-аргументов (проход вывода) имя_типа лежит в
                // имя_типа_строка узла-аргумента, который мономорфизация вскоре
                // освободит — простое копирование Токена оставило бы висячий
                // указатель в имени специализации. Для явных (имя в исходнике)
                // копия безвредна.
                free(узел->имя_типа_строка);
                узел->имя_типа_строка = nullptr;
                узел->имя_типа = та->имя_типа;
                if ((та->тип_данных == ТОКЕН_СТРУКТУРА
                     || та->тип_данных == ТОКЕН_ПЕРЕЧИСЛЕНИЕ)
                    && та->имя_типа.начало && та->имя_типа.длина > 0) {
                    узел->имя_типа_строка = strndup(та->имя_типа.начало,
                                                    та->имя_типа.длина);
                    if (узел->имя_типа_строка) {
                        узел->имя_типа.начало = узел->имя_типа_строка;
                        узел->имя_типа.длина = strlen(узел->имя_типа_строка);
                    }
                }
                break;
            }
        }
    }
    for (size_t i = 0; i < узел_число_детей(узел); ++i)
        подставить(узел_ребёнок(узел, i), парам_имена, число_парам, типарг);
}

// Присваивает узлу собственное (сгенерированное) имя и перенаправляет его токен.
static void переименовать(Узел *узел, const char *имя)
{
    free(узел->собственное_имя);
    узел->собственное_имя = strdup(имя);
    if (узел->собственное_имя) {
        узел->токен.тип = ТОКЕН_ИДЕНТИФИКАТОР;
        узел->токен.начало = узел->собственное_имя;
        узел->токен.длина = strlen(узел->собственное_имя);
    }
}

// Перенаправляет ССЫЛКУ НА ТИП (имя_типа узла-носителя: объявление/параметр/
// поле/возврат) на манглированное имя специализации структуры. Строку держим в
// owned имя_типа_строка (освобождается с узлом, копируется узел_копировать).
static void переименовать_тип(Узел *узел, const char *имя)
{
    free(узел->имя_типа_строка);
    узел->имя_типа_строка = strdup(имя);
    if (узел->имя_типа_строка) {
        узел->имя_типа.тип = ТОКЕН_ИДЕНТИФИКАТОР;
        узел->имя_типа.начало = узел->имя_типа_строка;
        узел->имя_типа.длина = strlen(имя);
    }
}

// ─── таблица шаблонов ────────────────────────────────────────────────────────

typedef struct {
    const char *имя;
    size_t      длина_имени;
    Узел       *узел;
    Токен       парам_имена[МАКС_ТИПОПАРАМ];
    size_t      число_параметров;
} Шаблон;

// ─── контекст прогона ────────────────────────────────────────────────────────

typedef struct {
    Шаблон     шаблоны[МАКС_ШАБЛОНОВ];
    size_t     число_шаблонов;
    Шаблон     структ_шаблоны[МАКС_ШАБЛОНОВ];  // обобщённые структуры
    size_t     число_структ_шаблонов;
    Шаблон     enum_шаблоны[МАКС_ШАБЛОНОВ];    // обобщённые перечисления (sum-типы)
    size_t     число_enum_шаблонов;
    ДинМассив  имена_инстанций;  // char*  — уже созданные специализации (дедуп)
    ДинМассив  клоны;            // Узел*  — специализации функций для добавления
    ДинМассив  очередь;          // Узел*  — специализации, чьи тела ещё не скан.
    ДинМассив  структ_клоны;     // Узел*  — специализации структур для добавления
    ДинМассив  структ_очередь;   // Узел*  — специализации структур, поля не скан.
    ДинМассив  enum_клоны;       // Узел*  — специализации перечислений для добавления
    Диагностика *диаг;
} Контекст;

// Есть ли в корне перечисление/структура с именем (токеном) «как-у» узла?
// Позволяет не создавать специализацию, чьё имя уже занято (например, типом
// стандартной библиотеки, реконструированным из «.и»).
static int узел_с_именем_в_корне(const Узел *корень, const Узел *узел)
{
    if (!корень || !узел) return 0;
    for (size_t i = 0; i < узел_число_детей(корень); ++i) {
        const Узел *у = узел_ребёнок(корень, i);
        if (!у) continue;
        if (у->тип != УЗЕЛ_СТРУКТУРА && у->тип != УЗЕЛ_ПЕРЕЧИСЛЕНИЕ) continue;
        if (у->токен.длина == узел->токен.длина &&
            strncmp(у->токен.начало, узел->токен.начало, у->токен.длина) == 0)
            return 1;
    }
    return 0;
}

static Шаблон *найти_шаблон(Контекст *к, const Токен *имя)
{
    for (size_t i = 0; i < к->число_шаблонов; ++i)
        if (байты_равны_л(к->шаблоны[i].имя, к->шаблоны[i].длина_имени,
                          имя->начало, имя->длина))
            return &к->шаблоны[i];
    return nullptr;
}

static Шаблон *найти_структ_шаблон(Контекст *к, const Токен *имя)
{
    for (size_t i = 0; i < к->число_структ_шаблонов; ++i)
        if (байты_равны_л(к->структ_шаблоны[i].имя, к->структ_шаблоны[i].длина_имени,
                          имя->начало, имя->длина))
            return &к->структ_шаблоны[i];
    return nullptr;
}

static Шаблон *найти_enum_шаблон(Контекст *к, const Токен *имя)
{
    for (size_t i = 0; i < к->число_enum_шаблонов; ++i)
        if (байты_равны_л(к->enum_шаблоны[i].имя, к->enum_шаблоны[i].длина_имени,
                          имя->начало, имя->длина))
            return &к->enum_шаблоны[i];
    return nullptr;
}

static int инстанция_существует(Контекст *к, const char *имя)
{
    for (size_t i = 0; i < к->имена_инстанций.длина; ++i) {
        char **p = дин_массив_получить(&к->имена_инстанций, i);
        if (*p && strcmp(*p, имя) == 0) return 1;
    }
    return 0;
}

static void ошибка(Контекст *к, const Токен *где, const char *текст)
{
    if (к->диаг->ошибка) return;  // держим первую
    к->диаг->ошибка = 1;
    к->диаг->строка = где ? где->строка : 0;
    к->диаг->колонка = где ? где->позиция_в_строке : 0;
    snprintf(к->диаг->сообщение, sizeof(к->диаг->сообщение), "%s", текст);
}

// Обрабатывает один обобщённый вызов: проверяет арность, вычисляет имя
// специализации, при необходимости создаёт клон (подстановка + переименование +
// снятие тип-параметров) и ставит его в очередь; переписывает сам вызов на
// сгенерированное имя и снимает тип-аргументы.
static void обработать_обобщённый_вызов(Контекст *к, Узел *вызов)
{
    Шаблон *ш = найти_шаблон(к, &вызов->токен);
    if (!ш) {
        ошибка(к, &вызов->токен,
               "вызов обобщённой функции: шаблон не найден в этом файле");
        return;
    }
    size_t числоТА = число_типоаргументов_вызова(вызов);
    if (числоТА != ш->число_параметров) {
        char msg[256];
        snprintf(msg, sizeof msg,
                 "обобщённая функция «%.*s» ожидает %zu тип-аргумент(ов), "
                 "передано %zu", (int)ш->длина_имени, ш->имя,
                 ш->число_параметров, числоТА);
        ошибка(к, &вызов->токен, msg);
        return;
    }

    const Узел *типарг[МАКС_ТИПОПАРАМ];
    for (size_t i = 0; i < числоТА && i < МАКС_ТИПОПАРАМ; ++i)
        типарг[i] = узел_ребёнок(вызов, i);

    // Имя специализации: имя_суффикс1[_суффикс2…].
    char имя[512];
    int поз = snprintf(имя, sizeof имя, "%.*s",
                       (int)ш->длина_имени, ш->имя);
    for (size_t i = 0; i < числоТА; ++i) {
        char суф[160];
        суффикс_типа(типарг[i], суф, sizeof суф);
        int напис = snprintf(имя + поз, sizeof имя - (size_t)поз, "_%s", суф);
        if (напис > 0) поз += напис;
        if ((size_t)поз >= sizeof имя) { поз = sizeof имя - 1; break; }
    }

    // Создаём клон-специализацию (если такой ещё нет).
    if (!инстанция_существует(к, имя)) {
        char *копияимени = strdup(имя);
        дин_массив_добавить(&к->имена_инстанций, &копияимени);

        Узел *клон = узел_копировать(ш->узел);
        подставить(клон, ш->парам_имена, ш->число_параметров, типарг);
        удалить_детей_типа(клон, УЗЕЛ_ТИПОПАРАМЕТР);
        переименовать(клон, имя);
        клон->статический = 1;  // специализация — внутренняя связь (как inline)

        Узел *указ = клон;
        дин_массив_добавить(&к->клоны, &указ);
        дин_массив_добавить(&к->очередь, &указ);
    }

    // Переписываем сам вызов: имя специализации + снятие тип-аргументов.
    удалить_детей_типа(вызов, УЗЕЛ_ТИПОАРГУМЕНТ);
    переименовать(вызов, имя);
}

// Рекурсивный обход: обрабатывает обобщённые вызовы, затем спускается в детей.
static void обойти(Контекст *к, Узел *узел)
{
    if (!узел || к->диаг->ошибка) return;
    if (узел->тип == УЗЕЛ_ВЫЗОВ) {
        if (число_типоаргументов_вызова(узел) > 0) {
            обработать_обобщённый_вызов(к, узел);
        } else if (найти_шаблон(к, &узел->токен)) {
            // Вызов обобщённой функции без явных «<>», и проход вывода не смог
            // вывести тип-аргументы из аргументов (напр. разные типы, тип
            // зависит от другого обобщения, или T только в возврате). Явная
            // ошибка вместо смутного «функция не объявлена» ниже по конвейеру.
            char msg[256];
            snprintf(msg, sizeof msg,
                     "обобщённую функцию «%.*s» нельзя вызвать без тип-аргументов: "
                     "вывести их из аргументов не удалось — укажите явно «%.*s<…>»",
                     (int)узел->токен.длина, узел->токен.начало,
                     (int)узел->токен.длина, узел->токен.начало);
            ошибка(к, &узел->токен, msg);
            return;
        }
    }
    for (size_t i = 0; i < узел_число_детей(узел) && !к->диаг->ошибка; ++i)
        обойти(к, узел_ребёнок(узел, i));
}

// Обрабатывает одну ССЫЛКУ на обобщённую структуру «Пара<целое32>» в позиции типа
// (объявление/параметр/поле/возврат): проверяет арность, вычисляет имя
// специализации, при необходимости клонирует структуру (подстановка + снятие
// тип-параметров + переименование) и ставит в очередь; переписывает саму ссылку
// на манглированное имя и снимает тип-аргументы. Схема имени — как у функций.
static void обработать_обобщённую_структуру(Контекст *к, Узел *ссылка)
{
    Шаблон *ш = найти_структ_шаблон(к, &ссылка->имя_типа);
    if (!ш) return;  // не обобщённая структура — не наша забота
    size_t числоТА = число_типоаргументов_вызова(ссылка);
    if (числоТА != ш->число_параметров) {
        char msg[256];
        snprintf(msg, sizeof msg,
                 "обобщённая структура «%.*s» ожидает %zu тип-аргумент(ов), "
                 "передано %zu", (int)ш->длина_имени, ш->имя,
                 ш->число_параметров, числоТА);
        ошибка(к, &ссылка->имя_типа, msg);
        return;
    }

    const Узел *типарг[МАКС_ТИПОПАРАМ];
    for (size_t i = 0; i < числоТА && i < МАКС_ТИПОПАРАМ; ++i)
        типарг[i] = узел_ребёнок(ссылка, i);

    char имя[512];
    int поз = snprintf(имя, sizeof имя, "%.*s", (int)ш->длина_имени, ш->имя);
    for (size_t i = 0; i < числоТА; ++i) {
        char суф[160];
        суффикс_типа(типарг[i], суф, sizeof суф);
        int напис = snprintf(имя + поз, sizeof имя - (size_t)поз, "_%s", суф);
        if (напис > 0) поз += напис;
        if ((size_t)поз >= sizeof имя) { поз = sizeof имя - 1; break; }
    }

    if (!инстанция_существует(к, имя)) {
        char *копияимени = strdup(имя);
        дин_массив_добавить(&к->имена_инстанций, &копияимени);

        Узел *клон = узел_копировать(ш->узел);
        подставить(клон, ш->парам_имена, ш->число_параметров, типарг);
        удалить_детей_типа(клон, УЗЕЛ_ТИПОПАРАМЕТР);
        переименовать(клон, имя);  // имя структуры — в токене

        Узел *указ = клон;
        дин_массив_добавить(&к->структ_клоны, &указ);
        дин_массив_добавить(&к->структ_очередь, &указ);  // поля могут ссылаться
    }

    удалить_детей_типа(ссылка, УЗЕЛ_ТИПОАРГУМЕНТ);
    переименовать_тип(ссылка, имя);  // ссылка на тип — в имя_типа
}

// Рекурсивный обход для ССЫЛОК на обобщённые структуры. Узел-носитель типа несёт
// ведущие УЗЕЛ_ТИПОАРГУМЕНТ и имя_типа обобщённой структуры (вызовы уже
// обработаны фазой функций — их тип-аргументы сняты). Обрабатываем узел, затем
// спускаемся в оставшихся детей.
static void обойти_структуры(Контекст *к, Узел *узел)
{
    if (!узел || к->диаг->ошибка) return;
    if (узел->тип != УЗЕЛ_ВЫЗОВ && число_типоаргументов_вызова(узел) > 0
        && найти_структ_шаблон(к, &узел->имя_типа))
        обработать_обобщённую_структуру(к, узел);
    for (size_t i = 0; i < узел_число_детей(узел) && !к->диаг->ошибка; ++i)
        обойти_структуры(к, узел_ребёнок(узел, i));
}

// Обрабатывает ссылку на обобщённое перечисление «Результат<целое32, целое32>»
// в позиции типа. Аналогично структуре, но с двумя важными отличиями (v1):
// (а) специализация РАЗ на программу — второй набор тип-аргументов того же
//     шаблона отвергаем, потому что имена вариантов (Успех/Ошибка) НЕ манглятся:
//     `Успех(5)` в пользовательском коде должен резолвиться однозначно, а
//     полноценный вывод типа-контекста ещё не реализован (следующая итерация);
// (б) манглированное имя специализации возвращается пользователю через ту же
//     имя_типа/имя_типа_строка (типа переменной), поэтому кодоген/семантика
//     видят обычный конкретный enum-тип.
static void обработать_обобщённое_перечисление(Контекст *к, Узел *ссылка)
{
    Шаблон *ш = найти_enum_шаблон(к, &ссылка->имя_типа);
    if (!ш) return;
    size_t числоТА = число_типоаргументов_вызова(ссылка);
    if (числоТА != ш->число_параметров) {
        char msg[256];
        snprintf(msg, sizeof msg,
                 "обобщённое перечисление «%.*s» ожидает %zu тип-аргумент(ов), "
                 "передано %zu", (int)ш->длина_имени, ш->имя,
                 ш->число_параметров, числоТА);
        ошибка(к, &ссылка->имя_типа, msg);
        return;
    }

    const Узел *типарг[МАКС_ТИПОПАРАМ];
    for (size_t i = 0; i < числоТА && i < МАКС_ТИПОПАРАМ; ++i)
        типарг[i] = узел_ребёнок(ссылка, i);

    char имя[512];
    int поз = snprintf(имя, sizeof имя, "%.*s", (int)ш->длина_имени, ш->имя);
    for (size_t i = 0; i < числоТА; ++i) {
        char суф[160];
        суффикс_типа(типарг[i], суф, sizeof суф);
        int напис = snprintf(имя + поз, sizeof имя - (size_t)поз, "_%s", суф);
        if (напис > 0) поз += напис;
        if ((size_t)поз >= sizeof имя) { поз = sizeof имя - 1; break; }
    }

    if (!инстанция_существует(к, имя)) {
        // v1: имена ВАРИАНТОВ (Успех/Ошибка) в шаблоне общие — вторая
        // специализация того же шаблона перепутает конструкторы, т.к. проход
        // вывода типа-контекста ещё не реализован. Проверяем: есть ли уже
        // специализация ЭТОГО шаблона с ДРУГИМ набором тип-аргументов.
        for (size_t i = 0; i < к->имена_инстанций.длина; ++i) {
            char **p = дин_массив_получить(&к->имена_инстанций, i);
            if (!*p) continue;
            // Специализация того же шаблона начинается с «Имя_» и уже присутствует
            // → это ДРУГАЯ комбинация тип-аргументов.
            size_t l = ш->длина_имени;
            if (strlen(*p) > l && memcmp(*p, ш->имя, l) == 0 && (*p)[l] == '_') {
                char msg[512];
                snprintf(msg, sizeof msg,
                    "обобщённое перечисление «%.*s» уже специализировано "
                    "иначе («%s»); v1 поддерживает одну специализацию на "
                    "шаблон (иначе конструкторы вариантов неоднозначны)",
                    (int)ш->длина_имени, ш->имя, *p);
                ошибка(к, &ссылка->имя_типа, msg);
                return;
            }
        }

        char *копияимени = strdup(имя);
        дин_массив_добавить(&к->имена_инстанций, &копияимени);

        Узел *клон = узел_копировать(ш->узел);
        подставить(клон, ш->парам_имена, ш->число_параметров, типарг);
        удалить_детей_типа(клон, УЗЕЛ_ТИПОПАРАМЕТР);
        переименовать(клон, имя);

        Узел *указ = клон;
        дин_массив_добавить(&к->enum_клоны, &указ);
    }

    удалить_детей_типа(ссылка, УЗЕЛ_ТИПОАРГУМЕНТ);
    переименовать_тип(ссылка, имя);
}

// Обход дерева в поисках ссылок на обобщённые перечисления. Идёт в паре с
// обойти_структуры — используем ту же схему: узел-носитель типа несёт ведущие
// УЗЕЛ_ТИПОАРГУМЕНТ и имя_типа. Тип-аргументы вызовов уже сняты фазой функций.
static void обойти_перечисления(Контекст *к, Узел *узел)
{
    if (!узел || к->диаг->ошибка) return;
    if (узел->тип != УЗЕЛ_ВЫЗОВ && число_типоаргументов_вызова(узел) > 0
        && найти_enum_шаблон(к, &узел->имя_типа))
        обработать_обобщённое_перечисление(к, узел);
    for (size_t i = 0; i < узел_число_детей(узел) && !к->диаг->ошибка; ++i)
        обойти_перечисления(к, узел_ребёнок(узел, i));
}

// ─── вход ────────────────────────────────────────────────────────────────────

int мономорфизировать(Узел *программа, Диагностика *диаг)
{
    if (!программа) return 1;

    Контекст к = { .диаг = диаг };
    дин_массив_инициализировать(&к.имена_инстанций, sizeof(char *));
    дин_массив_инициализировать(&к.клоны, sizeof(Узел *));
    дин_массив_инициализировать(&к.очередь, sizeof(Узел *));
    дин_массив_инициализировать(&к.структ_клоны, sizeof(Узел *));
    дин_массив_инициализировать(&к.структ_очередь, sizeof(Узел *));
    дин_массив_инициализировать(&к.enum_клоны, sizeof(Узел *));

    // 1. Собрать шаблоны: функции, структуры и перечисления с тип-параметрами
    //    (ведущие УЗЕЛ_ТИПОПАРАМЕТР). Схема сбора для всех трёх одинакова.
    for (size_t i = 0; i < узел_число_детей(программа); ++i) {
        Узел *у = узел_ребёнок(программа, i);
        if (!у) continue;
        int это_функция = у->тип == УЗЕЛ_ФУНКЦИЯ;
        int это_структура = у->тип == УЗЕЛ_СТРУКТУРА;
        int это_перечисление = у->тип == УЗЕЛ_ПЕРЕЧИСЛЕНИЕ;
        if (!это_функция && !это_структура && !это_перечисление) continue;
        size_t чп = число_типопараметров_функции(у);  // считает ведущие УЗЕЛ_ТИПОПАРАМЕТР
        if (чп == 0) continue;
        Шаблон *таблица = это_функция ? к.шаблоны
                        : это_структура ? к.структ_шаблоны
                        : к.enum_шаблоны;
        size_t *счёт = это_функция ? &к.число_шаблонов
                     : это_структура ? &к.число_структ_шаблонов
                     : &к.число_enum_шаблонов;
        if (*счёт >= МАКС_ШАБЛОНОВ) {
            // Раньше — тихий пропуск: шаблон терялся, вызов «шаблон не найден».
            // Теперь явная ошибка с позицией.
            char msg[128];
            snprintf(msg, sizeof msg,
                     "слишком много обобщённых объявлений одного вида "
                     "(предел компилятора — %d)", МАКС_ШАБЛОНОВ);
            ошибка(&к, &у->токен, msg);
            break;
        }
        Шаблон *ш = &таблица[(*счёт)++];
        ш->имя = у->токен.начало;
        ш->длина_имени = у->токен.длина;
        ш->узел = у;
        ш->число_параметров = чп < МАКС_ТИПОПАРАМ ? чп : МАКС_ТИПОПАРАМ;
        for (size_t j = 0; j < ш->число_параметров; ++j)
            ш->парам_имена[j] = узел_ребёнок(у, j)->токен;
    }

    if (к.число_шаблонов == 0 && к.число_структ_шаблонов == 0
        && к.число_enum_шаблонов == 0) {
        дин_массив_освободить(&к.имена_инстанций);
        дин_массив_освободить(&к.клоны);
        дин_массив_освободить(&к.очередь);
        дин_массив_освободить(&к.структ_клоны);
        дин_массив_освободить(&к.структ_очередь);
        дин_массив_освободить(&к.enum_клоны);
        return 1;
    }

    // 2. Сканировать тела не-шаблонных функций верхнего уровня (обобщённые вызовы).
    for (size_t i = 0; i < узел_число_детей(программа) && !диаг->ошибка; ++i) {
        Узел *ф = узел_ребёнок(программа, i);
        if (!ф || ф->тип != УЗЕЛ_ФУНКЦИЯ) continue;
        if (число_типопараметров_функции(ф) > 0) continue;  // сам шаблон
        обойти(&к, ф);
    }

    // 3. Обработать очередь клонов функций (транзитивные обобщённые вызовы).
    for (size_t qi = 0; qi < к.очередь.длина && !диаг->ошибка; ++qi) {
        Узел **p = дин_массив_получить(&к.очередь, qi);
        обойти(&к, *p);
    }

    // 3б. Фаза структур: тип-аргументы вызовов уже сняты фазой функций, а
    //     тип-параметры внутри специализаций функций уже подставлены — теперь
    //     все ссылки «Пара<конкретный>» конкретны. Сканируем не-шаблонные
    //     объявления верхнего уровня и специализации функций, затем транзитивно
    //     поля порождённых специализаций структур.
    for (size_t i = 0; i < узел_число_детей(программа) && !диаг->ошибка; ++i) {
        Узел *у = узел_ребёнок(программа, i);
        if (!у) continue;
        if (у->тип == УЗЕЛ_ФУНКЦИЯ && число_типопараметров_функции(у) > 0) continue;
        if (у->тип == УЗЕЛ_СТРУКТУРА && число_типопараметров_функции(у) > 0) continue;
        обойти_структуры(&к, у);
    }
    for (size_t i = 0; i < к.клоны.длина && !диаг->ошибка; ++i) {
        Узел **p = дин_массив_получить(&к.клоны, i);
        обойти_структуры(&к, *p);
    }
    for (size_t qi = 0; qi < к.структ_очередь.длина && !диаг->ошибка; ++qi) {
        Узел **p = дин_массив_получить(&к.структ_очередь, qi);
        обойти_структуры(&к, *p);
    }

    // 3в. Фаза перечислений: аналогично структурам. Сканируем не-шаблонные
    //     объявления верхнего уровня, специализации функций и полей структур,
    //     ища ссылки на обобщённые перечисления. Каждая порождает специализацию
    //     (v1: одна на шаблон).
    for (size_t i = 0; i < узел_число_детей(программа) && !диаг->ошибка; ++i) {
        Узел *у = узел_ребёнок(программа, i);
        if (!у) continue;
        if (у->тип == УЗЕЛ_ФУНКЦИЯ && число_типопараметров_функции(у) > 0) continue;
        if (у->тип == УЗЕЛ_СТРУКТУРА && число_типопараметров_функции(у) > 0) continue;
        if (у->тип == УЗЕЛ_ПЕРЕЧИСЛЕНИЕ && число_типопараметров_функции(у) > 0) continue;
        обойти_перечисления(&к, у);
    }
    for (size_t i = 0; i < к.клоны.длина && !диаг->ошибка; ++i) {
        Узел **p = дин_массив_получить(&к.клоны, i);
        обойти_перечисления(&к, *p);
    }
    for (size_t i = 0; i < к.структ_клоны.длина && !диаг->ошибка; ++i) {
        Узел **p = дин_массив_получить(&к.структ_клоны, i);
        обойти_перечисления(&к, *p);
    }

    if (диаг->ошибка) {
        for (size_t i = 0; i < к.клоны.длина; ++i) {
            Узел **p = дин_массив_получить(&к.клоны, i);
            освободить_узел(*p);
        }
        for (size_t i = 0; i < к.структ_клоны.длина; ++i) {
            Узел **p = дин_массив_получить(&к.структ_клоны, i);
            освободить_узел(*p);
        }
        for (size_t i = 0; i < к.enum_клоны.длина; ++i) {
            Узел **p = дин_массив_получить(&к.enum_клоны, i);
            освободить_узел(*p);
        }
        for (size_t i = 0; i < к.имена_инстанций.длина; ++i) {
            char **p = дин_массив_получить(&к.имена_инстанций, i);
            free(*p);
        }
        дин_массив_освободить(&к.имена_инстанций);
        дин_массив_освободить(&к.клоны);
        дин_массив_освободить(&к.очередь);
        дин_массив_освободить(&к.структ_клоны);
        дин_массив_освободить(&к.структ_очередь);
        дин_массив_освободить(&к.enum_клоны);
        return 0;
    }

    // 4. Перестроить детей программы: убрать шаблоны, добавить специализации.
    //    Порядок: перечисления → структуры → функции (кодогену это удобно —
    //    типы объявляются раньше функций, а enum-payload может использоваться
    //    полями структур). Дедуп семантики полагается на этот порядок.
    //    Если имя специализации уже занято в корне (например, тип стандартной
    //    библиотеки «Результат_целое64_целое32», реконструированный из её
    //    «.и»), клон не создаём — совпавшая специализация семантически та же.
    ДинМассив новые;
    дин_массив_инициализировать(&новые, sizeof(Узел *));
    for (size_t i = 0; i < к.enum_клоны.длина; ++i) {
        Узел **p = дин_массив_получить(&к.enum_клоны, i);
        if (!узел_с_именем_в_корне(программа, *p)) дин_массив_добавить(&новые, p);
        else освободить_узел(*p);
    }
    for (size_t i = 0; i < к.структ_клоны.длина; ++i) {
        Узел **p = дин_массив_получить(&к.структ_клоны, i);
        if (!узел_с_именем_в_корне(программа, *p)) дин_массив_добавить(&новые, p);
        else освободить_узел(*p);
    }
    for (size_t i = 0; i < узел_число_детей(программа); ++i) {
        Узел *у = узел_ребёнок(программа, i);
        if (у && у->тип == УЗЕЛ_ФУНКЦИЯ && число_типопараметров_функции(у) > 0) {
            освободить_узел(у);  // шаблон-функция больше не нужен
            continue;
        }
        if (у && у->тип == УЗЕЛ_СТРУКТУРА && число_типопараметров_функции(у) > 0) {
            освободить_узел(у);  // шаблон-структура больше не нужен
            continue;
        }
        if (у && у->тип == УЗЕЛ_ПЕРЕЧИСЛЕНИЕ && число_типопараметров_функции(у) > 0) {
            освободить_узел(у);  // шаблон-перечисление больше не нужен
            continue;
        }
        дин_массив_добавить(&новые, &у);
    }
    for (size_t i = 0; i < к.клоны.длина; ++i) {
        Узел **p = дин_массив_получить(&к.клоны, i);
        дин_массив_добавить(&новые, p);
    }
    дин_массив_освободить(&программа->дети);
    программа->дети = новые;

    for (size_t i = 0; i < к.имена_инстанций.длина; ++i) {
        char **p = дин_массив_получить(&к.имена_инстанций, i);
        free(*p);
    }
    дин_массив_освободить(&к.имена_инстанций);
    дин_массив_освободить(&к.клоны);
    дин_массив_освободить(&к.очередь);
    дин_массив_освободить(&к.структ_клоны);
    дин_массив_освободить(&к.структ_очередь);
    дин_массив_освободить(&к.enum_клоны);
    return 1;
}
